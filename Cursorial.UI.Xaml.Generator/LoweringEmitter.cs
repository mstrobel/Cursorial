    private static void EmitExtensionAssign(Context c, string varExpr, XamlMember xm, in ExtensionRecord ext, INamedTypeSymbol? dataType)
    {
        switch (ext.Kind)
        {
            case ExtensionKind.Binding when c.Doc.ParsedExtensions[ext.Payload] is { } node:
                EmitBinding(c, varExpr, xm, node, dataType);
                return;

            case ExtensionKind.DynamicResource:
                EmitDynamicResource(c, varExpr, xm, in ext);
                return;

            case ExtensionKind.StaticResource:
                EmitStaticResource(c, varExpr, xm, in ext);
                return;

            case ExtensionKind.TemplateBinding when c.Doc.ParsedExtensions[ext.Payload] is { } node:
                EmitTemplateBinding(c, varExpr, xm, node);
                return;

            case ExtensionKind.Reference:
                EmitReference(c, varExpr, xm, c.Doc.Strings[ext.Payload]);
                return;

            default:
                c.Todo($"extension {ext.Kind} for '{xm.Name}' not yet lowered");
                return;
        }
    }

    // {x:Reference Name} → a deferred assignment from the document name scope, emitted at the end of
    // InitializeComponent (after every x:Name is registered) so a forward reference resolves. Document-level only:
    // a template factory has its own scope (no __scope), so it degrades to reflective.
    private static void EmitReference(Context c, string varExpr, XamlMember xm, string name)
    {
        if (c.InTemplate)
        {
            c.Todo($"{{x:Reference}} for '{xm.Name}' inside a template not yet lowered (no document name scope)");
            return;
        }

        var owner = RegisteredOwner(xm);
        var clrType = owner is null ? ValueTypeSymbol(xm.ValueType) : null;
        c.References.Add(new ReferenceResolution(varExpr, owner, xm.Name, name, clrType));
    }

    // {DynamicResource Key} → ResourceExtensions.SetResourceReference(element, Owner.FooProperty, key): a live
    // producer that re-resolves against the element's ancestor chain on attach (no eager-resolution timing
    // problem — works inline AND inside templates). Requires a registered StyledProperty<T> target (the runtime
    // handler rejects direct/attached); a literal key only (a nested-extension key is deferred to a later cut).
    private static void EmitDynamicResource(Context c, string varExpr, XamlMember xm, in ExtensionRecord ext)
    {
        if (!XamlDataTypeScope.IsUIElement(c.CurrentObjectType))
        {
            c.Todo($"{{DynamicResource}} on a non-UIElement target ('{xm.Name}') not yet lowered");
            return;
        }

        if (RegisteredOwner(xm) is not { } owner || !XamlDataTypeScope.IsStyledProperty(owner, xm.Name))
        {
            c.Todo($"{{DynamicResource}} target '{xm.Name}' is not a styled UIProperty (direct/attached unsupported)");
            return;
        }

        // The key: a literal string, or a nested {x:Static} member (SetResourceReference's key param is object).
        if (ResourceKeyArgExpr(c, in ext) is not { } keyExpr)
        {
            c.Todo($"{{DynamicResource}} with an unsupported markup-extension key for '{xm.Name}' not yet lowered");
            return;
        }

        // SetResourceReference<T> infers T from the StyledProperty<T> field; call it statically (no using).
        c.Line($"global::Cursorial.UI.ResourceExtensions.SetResourceReference({varExpr}, {Global(owner)}.{xm.Name}Property, {keyExpr});");
    }

    // {StaticResource Key} — eager, but deferred to end-of-InitializeComponent (see EmitDeferredStaticResources):
    // record (element, target, key). A markup-extension key, or a StaticResource inside a template factory
    // (where there is no end-of-tree FindResource anchor — it needs the captured lexical scope), stays a // TODO.
    private static void EmitStaticResource(Context c, string varExpr, XamlMember xm, in ExtensionRecord ext)
    {
        // Same-dictionary key (string OR nested {x:Type}/{x:Static}, lexically built before this use): reference the
        // entry's var directly — StaticResource's exact load-time-snapshot semantics, and the only form that works
        // inside a template factory (a non-static local function captures the var). Works inline too (the var is in
        // the same Build() scope).
        if (ResourceKeyArgExpr(c, in ext) is { } keyExpr && c.ResourceVarsByKeyExpr.TryGetValue(keyExpr, out var srcVar))
        {
            if (c.InTemplate) c.CurrentFactoryCaptures = true; // the factory references an enclosing local ⇒ not static
            AssignResolvedResource(c, varExpr, xm, srcVar);
            return;
        }

        if (ext.PayloadIsParsedExtension)
        {
            // A nested {x:Type}/{x:Static} key that isn't a same-dictionary entry: there's no string anchor for the
            // end-of-tree FindResource fallback (which is string-keyed), so defer.
            c.Todo($"{{StaticResource}} with a markup-extension key for '{xm.Name}' is not a same-dictionary entry — not yet lowered");
            return;
        }

        var key = c.Doc.Strings[ext.Payload];

        if (c.InTemplate)
        {
            c.Todo($"{{StaticResource}} for '{xm.Name}' inside a template not yet lowered (needs the captured lexical scope)");
            return;
        }

        // FindResource is a UIElement extension; a {StaticResource} on a non-element object (e.g. a brush inside a
        // resource value) can't use the end-of-tree FindResource anchor — bail rather than emit an uncompilable call.
        if (!XamlDataTypeScope.IsUIElement(c.CurrentObjectType))
        {
            c.Todo($"{{StaticResource}} on a non-UIElement target ('{xm.Name}') not yet lowered");
            return;
        }

        var owner = RegisteredOwner(xm);
        // For a CLR (non-UIProperty) target, remember the value type so the assignment casts FindResource's
        // object? to the property type — needed even for a `string` target (object? → string is not implicit).
        var clrType = owner is null ? ValueTypeSymbol(xm.ValueType) : null;
        c.StaticResources.Add(new StaticResourceResolution(varExpr, owner, xm.Name, key, clrType));
    }

    // Assigns an already-resolved resource value expression (a built entry's var) to a member: SetValue for a
    // registered UIProperty target; else a CLR set (cast to the member value type when it's a concrete type, so a
    // base/interface-typed target accepts the concrete-typed var — and object/string targets need no cast).
    private static void AssignResolvedResource(Context c, string varExpr, XamlMember xm, string valueExpr)
    {
        if (RegisteredOwner(xm) is { } owner)
            c.Line($"{varExpr}.SetValue({Global(owner)}.{xm.Name}Property, {valueExpr});");
        else if (!IsObjectOrString(xm.ValueType) && ValueTypeSymbol(xm.ValueType) is { } ct)
            c.Line($"{varExpr}.{xm.Name} = ({Global(ct)}){valueExpr};");
        else
            c.Line($"{varExpr}.{xm.Name} = {valueExpr};");
    }

    // Emits the recorded {StaticResource} resolutions at the end of InitializeComponent. By here the whole tree
    // is constructed + attached and every <X.Resources> is populated, so el.FindResource walks the full ancestor
    // chain (throw-on-miss, matching the loader's eager resolution). Lexical == live for an inline document.
    private static void EmitDeferredStaticResources(Context c)
    {
        if (c.StaticResources.Count == 0)
            return;

        c.Line("// X5.4 — resolve {StaticResource}s now the tree is built + attached and resources are populated.");
        foreach (var sr in c.StaticResources)
        {
            string find = $"global::Cursorial.UI.ResourceExtensions.FindResource({sr.Var}, \"{Escape(sr.Key)}\")";

            if (sr.Owner is { } owner)
                c.Line($"{sr.Var}.SetValue({Global(owner)}.{sr.Property}Property, {find});");
            else if (sr.ClrType is { } ct)
                c.Line($"{sr.Var}.{sr.Property} = ({Global(ct)}){find}!;");
            else
                c.Line($"{sr.Var}.{sr.Property} = {find};");
        }
    }

    // {x:Reference} resolutions, emitted after the tree is built + every x:Name registered, so a forward
    // reference (the named element appears later) resolves against the now-complete document name scope.
    private static void EmitDeferredReferences(Context c)
    {
        if (c.References.Count == 0)
            return;

        c.Line("// {x:Reference} — resolve against the now-fully-populated document name scope (forward refs included).");
        foreach (var r in c.References)
        {
            var find = $"__scope.Find(\"{Escape(r.Name)}\")";

            if (r.Owner is { } owner)
                c.Line($"{r.Var}.SetValue({Global(owner)}.{r.Property}Property, {find});");
            else if (r.ClrType is { } ct)
                c.Line($"{r.Var}.{r.Property} = ({Global(ct)}){find}!;");
            else
                c.Line($"{r.Var}.{r.Property} = {find};");
        }
    }

    // B3a/B3b — {Binding} lowering. The compiled lane (zero reflection, AOT-clean) is taken for an
    // x:DataType-scoped, DataContext-relative, single-hop binding; everything else falls back to a faithful
    // reflective `new Binding(...)` (the plan's "graceful reflective fallback" — the binding still works, just
    // through the reflective engine, which surfaces an AOT warning pointing at the binding to fix). Only a
    // Converter-bearing binding (needs eager resource/static resolution, deferred with resources) or an
    // unsupported RelativeSource stays a // TODO X5.
    private static void EmitBinding(Context c, string varExpr, XamlMember xm, MarkupExtensionNode node, INamedTypeSymbol? dataType)
    {
        // A binding target must be a registered UIProperty — the runtime handler enforces the same (X119).
        if (RegisteredOwner(xm) is not { } owner)
        {
            c.Todo($"binding target '{xm.Name}' is not a bindable UIProperty");
            return;
        }

        if (TryEmitCompiledBinding(c, varExpr, owner, xm, node, dataType, out var reason))
            return;

        var reflectiveEmitted = EmitReflectiveBinding(c, varExpr, owner, xm, node);

        // B3 — the reflective-fallback INFO (CURG2002): a binding that WAS a compiled-lane candidate (x:DataType in
        // scope) but stayed reflective, naming why. Only when the reflective binding actually emitted (a Converter
        // etc. that the reflective lane also drops is a CURG3001 gap, not a "works-but-reflective" info) AND a reason
        // was recorded — a non-candidate (no x:DataType) and a path-walk failure (not-found → CURG2001 owns it;
        // static/write-only → wouldn't resolve reflectively anyway) both leave reason null and get no noise. The
        // reason already states the cause; no generic remedy clause (it varies per reason and was misleading).
        if (reflectiveEmitted && reason is not null)
            c.Info($"{{Binding}} for '{xm.Name}' stays reflective ({reason}) — it works, but is not the AOT-optimal compiled form.");
    }

    // Emits a typed, reflection-free CompiledBinding when the binding is an x:DataType-rooted, DataContext-relative,
    // compilable path. Returns true when it emitted; false when it declined, with <paramref name="reason"/> set to
    // a human phrase for the CURG2002 info (null when there was no x:DataType in scope — not a candidate at all).
    private static bool TryEmitCompiledBinding(
        Context c, string varExpr, INamedTypeSymbol owner, XamlMember xm, MarkupExtensionNode node, INamedTypeSymbol? dataType, out string? reason)
    {
        reason = null;
        if (dataType is null)
            return false; // no x:DataType ⇒ never a compiled candidate ⇒ no info

        // Only a plain DataContext-relative binding is x:DataType-rooted; an anchor/converter/format/fallback arg
        // changes semantics this lane doesn't reproduce — bail to the reflective fallback.
        if (HasNamed(node, "Source") || HasNamed(node, "ElementName") || HasNamed(node, "RelativeSource"))
        {
            reason = "it has an explicit Source/ElementName/RelativeSource (not DataContext-relative)";
            return false;
        }
        if (HasNamed(node, "Converter") || HasNamed(node, "StringFormat") || HasNamed(node, "FallbackValue"))
        {
            reason = "it has a Converter/StringFormat/FallbackValue";
            return false;
        }

        var path = BindingPathOf(node);
        if (string.IsNullOrEmpty(path) || path == ".")
            return false; // a whole-DataContext binding has no compiled leaf — not an actionable info (reason stays null)

        // Indexers / method calls never compile here (the engine supports constant-index hops, but the generator's
        // path-walk is member-access only) — they stay reflective.
        if (path!.IndexOf('[') >= 0 || path.IndexOf('(') >= 0)
        {
            reason = "its path uses an indexer or a method call";
            return false;
        }

        if (CanonicalMode(node) is not { } modeName)
        {
            reason = "its binding Mode is not recognized";
            return false;
        }

        // Walk the (single- or multi-hop) dotted path against the x:DataType, threading the running owner type.
        // Every hop must be a readable INSTANCE property/field (a static-named hop can't be `prev.Member`, CS0176);
        // an intermediate must be a named type to continue the walk.
        var hops = path.Split('.');
        var owners = new INamedTypeSymbol[hops.Length]; // the type each hop is accessed ON
        var types = new ITypeSymbol[hops.Length];       // each hop's value type
        var leafWritable = false;
        var current = dataType;
        for (int h = 0; h < hops.Length; h++)
        {
            // A member accessed ON a Nullable<T> (the path walks through .Value/.HasValue) isn't compiled: the
            // typed whole-chain read would NRE on a null intermediate, and the per-hop `is T? __t` step pattern
            // doesn't even parse (the `?` reads as a ternary). Bail to the reflective lane, which reflects it.
            if (current is { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T })
            {
                reason = "a path hop accesses a Nullable<T> member";
                return false;
            }

            if (XamlDataTypeScope.FindMember(current, hops[h]) is not { IsStatic: false } member ||
                !XamlDataTypeScope.IsReadable(member) ||
                XamlDataTypeScope.MemberType(member) is not { } hopType)
            {
                // A not-found member is the path validator's CURG2001 (don't also raise the "works-but-reflective"
                // CURG2002); a static / write-only member won't resolve through an instance DataContext either, so
                // no "It works" info — leave reason null. The reflective fallback still emits a (possibly inert) binding.
                return false;
            }

            owners[h] = current;
            types[h] = hopType;
            if (h == hops.Length - 1)
                leafWritable = XamlDataTypeScope.IsWritable(member);
            else if (hopType is INamedTypeSymbol named)
                current = named;
            else
            {
                reason = "an intermediate path hop is not a named type";
                return false;
            }
        }

        var leafType = types[hops.Length - 1];
        string data = Global(dataType);
        string value = Global(leafType);

        // Getter — a null-safe whole-chain read: `?.` after each reference-typed hop so a null intermediate yields
        // default(leaf), never an NRE. The pinned full-lowering compiled-multi-hop null semantics (B188) — safer
        // than Binding.Compiled's path.Compile() (which throws on a null intermediate); it matches the reflective
        // lane for the non-null reads B156 pins (a null intermediate is default(leaf) here vs the reflective
        // UnsetValue — the documented, opt-in-via-full-lowering difference).
        // Member-access positions @-escape a hop that collides with a C# reserved keyword (a member name on a
        // VB/F# VM can be `event`/`class`/…); the CompiledPathStep string label stays the raw name (the runtime
        // resolves by name).
        var chain = new StringBuilder("__s");
        var conditional = false;
        for (int h = 0; h < hops.Length; h++)
        {
            var accessor = h == 0 ? "." : (types[h - 1].IsReferenceType ? "?." : ".");
            if (accessor == "?.") conditional = true;
            chain.Append(accessor).Append(EscapeId(hops[h]));
        }
        var getter = conditional ? $"static __s => ({chain}) ?? default({value})" : $"static __s => {chain}";

        // One CompiledPathStep per hop — an object-typed reader for INPC/INCC subscription rewiring (null-safe; the
        // typed Getter does the value read). The reader casts to the type the hop is accessed on.
        var steps = new List<string>(hops.Length);
        for (int h = 0; h < hops.Length; h++)
            steps.Add($"new global::Cursorial.UI.Data.CompiledPathStep(\"{Escape(hops[h])}\", " +
                      $"static __o => __o is {Global(owners[h])} __t ? (object?)__t.{EscapeId(hops[h])} : null)");

        // Setter (TwoWay) — only when the leaf is writable AND its owner is a reference type (writing through a
        // value-typed owner mutates a copy ⇒ a no-op, so degrade to OneWay/null, matching the reflective lane —
        // B152). Multi-hop is null-guarded (a broken chain is a no-op write).
        var setter = "null";
        if (leafWritable && owners[hops.Length - 1].IsReferenceType)
        {
            if (hops.Length == 1)
            {
                setter = $"static (__s, __v) => __s.{EscapeId(hops[0])} = __v";
            }
            else
            {
                var ownerChain = new StringBuilder("__s");
                for (int h = 0; h < hops.Length - 1; h++)
                    ownerChain.Append(h == 0 ? "." : (types[h - 1].IsReferenceType ? "?." : ".")).Append(EscapeId(hops[h]));
                setter = $"static (__s, __v) => {{ if (({ownerChain}) is {{ }} __o) __o.{EscapeId(hops[hops.Length - 1])} = __v; }}";
            }
        }

        c.Line(
            $"global::Cursorial.UI.Data.BindingOperations.Install({varExpr}, {Global(owner)}.{xm.Name}Property, " +
            $"new global::Cursorial.UI.Data.CompiledBinding<{data}, {value}>({getter}, {setter}, " +
            $"new global::Cursorial.UI.Data.CompiledPathStep[] {{ {string.Join(", ", steps)} }}, \"{Escape(path)}\"){Initializers(ModeInit(modeName))});");
        return true;
    }

    // The reflective fallback (B3b) — a faithful `new Binding(path) { … }` mirroring the runtime handler's
    // BuildBinding (Mode/ElementName/Source/StringFormat/FallbackValue/RelativeSource), minus Converter. Returns
    // true when it emitted a working binding; false when it left a hard // TODO X5 gap (CURG3001, no runtime effect)
    // — the caller uses this to decide whether a CURG2002 "works-but-reflective" info is appropriate.
    private static bool EmitReflectiveBinding(Context c, string varExpr, INamedTypeSymbol owner, XamlMember xm, MarkupExtensionNode node)
    {
        if (CanonicalMode(node) is not { } modeName)
        {
            c.Todo($"{{Binding}} with an unrecognized Mode for '{xm.Name}'");
            return false;
        }

        if (RelativeSourceInit(c, node) is not { } relSource)
        {
            c.Todo($"{{Binding}} RelativeSource for '{xm.Name}' not supported in lowering (Self / TemplatedParent / FindAncestor)");
            return false;
        }

        if (ConverterInit(c, node) is not { } converterInit)
        {
            c.Todo($"{{Binding}} Converter for '{xm.Name}' is not a same-dictionary {{StaticResource}} / {{x:Static}} (cross-dict / custom not yet lowered)");
            return false;
        }

        string path = Escape(BindingPathOf(node) ?? string.Empty);
        var inits = new List<string>(ModeInit(modeName))
        {
            relSource,
            converterInit,
            StringInit("ElementName", NamedText(node, "ElementName")),
            StringInit("Source", NamedText(node, "Source")),       // mirrors the handler: Source = the bare string
            StringInit("StringFormat", NamedText(node, "StringFormat")),
            StringInit("FallbackValue", NamedText(node, "FallbackValue")),
        };

        c.Line(
            $"global::Cursorial.UI.Data.BindingOperations.Install({varExpr}, {Global(owner)}.{xm.Name}Property, " +
            $"new global::Cursorial.UI.Data.Binding(\"{path}\"){Initializers(inits)});");
        return true;
    }

    // {TemplateBinding SourceProp} (inside a template body) → a one-way TemplateBinding tracking the templated
    // parent's SourceProp. The source property is resolved against the template's target type (statically known
    // here via the ControlTemplate TargetType / enclosing control); the engine finds the live templated parent
    // at apply-time via the target's TemplatedParent (so the lowered emission needs no parent reference).
    private static void EmitTemplateBinding(Context c, string varExpr, XamlMember xm, MarkupExtensionNode node)
    {
        if (RegisteredOwner(xm) is not { } targetOwner)
        {
            c.Todo($"{{TemplateBinding}} target '{xm.Name}' is not a bindable UIProperty");
            return;
        }

        if (c.TemplatedParentType is not { } parentType)
        {
            c.Todo($"{{TemplateBinding}} for '{xm.Name}' has no statically-known template target type (DataTemplate / unresolved TargetType)");
            return;
        }

        if (FirstPositionalText(node) is not { Length: > 0 } sourceName)
        {
            c.Todo($"{{TemplateBinding}} for '{xm.Name}' has no source property name");
            return;
        }

        if (SymbolXamlModel.FindRegisteredPropertyOwner(parentType, sourceName) is not { } sourceOwner)
        {
            c.Todo($"{{TemplateBinding {sourceName}}} — '{sourceName}' is not a registered property on '{parentType.Name}'");
            return;
        }

        c.Line(
            $"global::Cursorial.UI.Data.BindingOperations.Install({varExpr}, {Global(targetOwner)}.{xm.Name}Property, " +
            $"new global::Cursorial.UI.Data.TemplateBinding({Global(sourceOwner)}.{sourceName}Property));");
    }

    // The binding path: the first positional argument, else the Path= named argument (mirrors the runtime handler).
    private static string? BindingPathOf(MarkupExtensionNode node)
        => node.PositionalArguments.Count > 0 && node.PositionalArguments[0].Text is { } p ? p : NamedText(node, "Path");

    private static bool HasNamed(MarkupExtensionNode node, string name) => node.FindNamed(name) is not null;

    private static string? NamedText(MarkupExtensionNode node, string name)
        => node.FindNamed(name) is { Text: { } t } ? t : null;

    private static string? FirstPositionalText(MarkupExtensionNode node)
        => node.PositionalArguments.Count > 0 ? node.PositionalArguments[0].Text : null;

    // The canonical BindingMode member name; "" for unspecified (Default — resolved at install, BD10); null for
    // an unrecognized token (the caller bails — the compiled path to the reflective fallback, the fallback to TODO).
    private static string? CanonicalMode(MarkupExtensionNode node)
    {
        if (NamedText(node, "Mode") is not { } text)
            return string.Empty;

        // BindingMode is a closed enum; match case-insensitively (WPF/Avalonia parity with the runtime handler).
        return text.ToLowerInvariant() switch
        {
            "default" => "Default",
            "oneway" => "OneWay",
            "twoway" => "TwoWay",
            "onetime" => "OneTime",
            "onewaytosource" => "OneWayToSource",
            _ => null,
        };
    }

    // The `Mode = BindingMode.X` initializer fragment for a carried mode ("" when unspecified ⇒ no fragment).
    private static IEnumerable<string> ModeInit(string modeName)
        => modeName.Length == 0 ? [] : [$"Mode = global::Cursorial.UI.Data.BindingMode.{modeName}"];

    private static string StringInit(string member, string? value)
        => value is null ? string.Empty : $"{member} = \"{Escape(value)}\"";

    // The `RelativeSource = …` fragment: "" not present; the Self/TemplatedParent fragment; null for an
    // unsupported mode (FindAncestor etc. — the caller TODOs), mirroring the handler's ParseRelativeSource.
    private static string? RelativeSourceInit(Context c, MarkupExtensionNode node)
    {
        if (node.FindNamed("RelativeSource") is not { } value)
            return string.Empty;

        string? mode = value.IsNested
            ? FirstPositionalText(value.Nested!) ?? NamedText(value.Nested!, "Mode")
            : value.Text;

        return mode switch
        {
            "TemplatedParent" => "RelativeSource = global::Cursorial.UI.Data.RelativeSource.TemplatedParent",
            "Self" => "RelativeSource = global::Cursorial.UI.Data.RelativeSource.Self",
            "FindAncestor" when value.IsNested => FindAncestorInit(c, value.Nested!),
            null when value.IsNested => "RelativeSource = global::Cursorial.UI.Data.RelativeSource.Self", // WPF default
            _ => null,
        };
    }

    // {Binding Converter={StaticResource Conv}} → the same-dictionary converter resource's built var; {Binding
    // Converter={x:Static M}} → the static converter instance. Empty when there's no Converter; null (bail to the
    // reflective fallback) for any other Converter form (cross-dictionary {StaticResource}, a custom extension).
    private static string? ConverterInit(Context c, MarkupExtensionNode node)
    {
        if (node.FindNamed("Converter") is not { } arg)
            return string.Empty;

        if (arg.IsNested && arg.Nested is { } inner &&
            inner.PositionalArguments.Count > 0 && inner.PositionalArguments[0].Text is { } first)
        {
            // {StaticResource Key} — a same-dictionary converter resource (the var holds the built instance; the
            // loader's ResolveConverter resolves the same nested {StaticResource}).
            if (inner.Name is "StaticResource" && c.ResourceVarsByKeyExpr.TryGetValue($"\"{Escape(first)}\"", out var srcVar))
            {
                if (c.InTemplate) c.CurrentFactoryCaptures = true;
                return $"Converter = {srcVar}";
            }

            // {x:Static Member} — the static converter instance.
            if (inner.Name is "x:Static" or "Static" && ResolveStaticPath(c, first) is { } expr)
                return $"Converter = {expr}";
        }

        return null;
    }

    // {RelativeSource FindAncestor, AncestorType={x:Type T} | T [, AncestorLevel=n]} → an object-initializer matching
    // the loader's RelativeSource (Mode/AncestorType/AncestorLevel) so the dual-run renders identically. Null (bail to
    // reflective) when AncestorType is absent / unresolvable.
    private static string? FindAncestorInit(Context c, MarkupExtensionNode node)
    {
        if (node.FindNamed("AncestorType") is not { } typeArg)
            return null;

        var typeName = typeArg.IsNested
            ? (typeArg.Nested!.PositionalArguments.Count > 0 ? typeArg.Nested.PositionalArguments[0].Text : null)
            : typeArg.Text;
        if (string.IsNullOrEmpty(typeName) || XamlDataTypeScope.ResolveToken(c.Doc, typeName!, c.Resolver) is not { } typeSym)
            return null;

        var level = NamedText(node, "AncestorLevel") is { } lvl && int.TryParse(lvl, out var n) && n > 0 ? n : 1;
        return $"RelativeSource = new global::Cursorial.UI.Data.RelativeSource {{ Mode = global::Cursorial.UI.Data.RelativeSourceMode.FindAncestor, " +
               $"AncestorType = typeof({Global(typeSym)}), AncestorLevel = {level} }}";
    }

    // Joins non-empty object-initializer member assignments into a ` { a, b }` suffix, or "" when none.
    private static string Initializers(IEnumerable<string> members)
    {
        var present = members.Where(s => s.Length > 0).ToList();
        return present.Count == 0 ? string.Empty : " { " + string.Join(", ", present) + " }";
    }

    // Resolves an {x:Static Type.Member} path to a C# static reference. The type token (before the last dot)
    // is resolved through the same symbol resolver the parse used (default UI xmlns); the member is appended.
    private static string? ResolveStaticPath(Context c, string memberPath)
    {
        int dot = memberPath.LastIndexOf('.');
        if (dot <= 0)
            return null;

        var typeName = memberPath.Substring(0, dot);
        var member = memberPath.Substring(dot + 1);
        var typeSymbol = c.Resolver.Resolve(XamlSymbolResolver.CursorialUiNamespace, typeName, out _);
        return typeSymbol is null ? null : $"{Global(typeSymbol)}.{member}"; // Global() already prefixes global::
    }

    private static INamedTypeSymbol? RegisteredOwner(XamlMember member) => member.Property as INamedTypeSymbol;

    private static bool IsObjectOrString(IXamlType valueType)
        => valueType is RoslynXamlType { Symbol.SpecialType: SpecialType.System_Object or SpecialType.System_String };

    private static ITypeSymbol? ValueTypeSymbol(IXamlType valueType)
        => valueType is RoslynXamlType { Symbol: { } symbol } ? symbol : null;

    private static INamedTypeSymbol? TypeSymbolOf(XamlDocument document, int typeId)
        => typeId >= 0 && document.ResolvedTypes[typeId]?.ClrType is RoslynXamlType { Symbol: INamedTypeSymbol s } ? s : null;

    private static string Global(ITypeSymbol type) => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    private static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");

    // A C#-identifier emission position (member access): verbatim-escape (@) a name that is a reserved keyword, so a
    // member from a non-C# VM (VB/F# `event`/`class`/…) emits `__s.@event`, not the uncompilable `__s.event`.
    private static string EscapeId(string name)
        => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None
            ? "@" + name
            : name;

    // The result of an init-only member pre-scan: the object-initializer entries + the member indices to skip.
    private sealed class InitOnlyScan
    {
        public List<string> Entries { get; } = [];
        public HashSet<int> Indices { get; } = [];
    }

    private sealed class Context(XamlDocument document, string indent, XamlSymbolResolver resolver)
    {
        public XamlDocument Doc { get; } = document;
        public XamlSymbolResolver Resolver { get; } = resolver;
        public string Indent { get; } = indent;
        public StringBuilder Body { get; } = new();
        public bool UsesConverter { get; set; }
        public List<UnloweredMember> Unlowered { get; } = [];

        /// <summary>Info-level notes (CURG2002): the member emitted a WORKING but non-optimal form (a binding that
        /// stayed reflective when it could have been a zero-reflection compiled binding). No <c>// TODO</c> marker.</summary>
        public List<UnloweredMember> Infos { get; } = [];

        public List<StaticResourceResolution> StaticResources { get; } = [];

        public List<ReferenceResolution> References { get; } = []; // {x:Reference} deferred assignments

        /// <summary>
        /// Raw-string resource key → the local var holding the already-built dictionary entry. A same-dictionary
        /// <c>{StaticResource key}</c> (lexically defined before its use) resolves to this var — StaticResource's
        /// exact load-time-snapshot semantics. A flat map (unique theme keys); cross-scope lexical shadowing is a
        /// future refinement caught by the dual-run gate. Populated as <see cref="EmitDictionaryEntry"/> builds entries.
        /// </summary>
        public Dictionary<string, string> ResourceVars { get; } = new(System.StringComparer.Ordinal);

        /// <summary>
        /// Every built dictionary entry by its <em>key expression</em> (the C# the key lowers to — a string
        /// literal, a <c>typeof(...)</c> for an <c>{x:Type}</c> key, or an <c>{x:Static}</c> member ref), to its
        /// built var. The superset of <see cref="ResourceVars"/> (which is string-keys-only): this also tracks
        /// <c>{x:Type}</c>/<c>{x:Static}</c>-keyed entries (control themes), so a same-dictionary
        /// <c>{StaticResource {x:Type T}}</c> — including a <c>Style.BasedOn</c> — resolves to the entry's var.
        /// </summary>
        public Dictionary<string, string> ResourceVarsByKeyExpr { get; } = new(System.StringComparer.Ordinal);

        private INamedTypeSymbol? _control;
        private bool _controlResolved;

        /// <summary>The <c>Cursorial.UI.Controls.Control</c> symbol — a keyed <c>ControlTemplate</c>'s implicit
        /// templated-parent base (it's always applied to a Control), so a {TemplateBinding} with no explicit
        /// TargetType resolves its source against it. Resolved once, lazily; null if unavailable.</summary>
        public INamedTypeSymbol? Control
        {
            get
            {
                if (!_controlResolved)
                {
                    _control = Resolver.Resolve(XamlSymbolResolver.CursorialUiNamespace, "Control", out _);
                    _controlResolved = true;
                }
                return _control;
            }
        }

        /// <summary>The emitted template factory local functions, appended at the end of InitializeComponent (hoisted).</summary>
        public List<string> Factories { get; } = [];

        /// <summary>True while lowering inside a template factory (no end-of-tree FindResource anchor for {StaticResource}).</summary>
        public bool InTemplate { get; set; }

        /// <summary>Set while emitting a template factory body when it references an enclosing local (a same-dict
        /// {StaticResource} var) — so the factory drops <c>static</c> and captures it. Saved/restored per factory.</summary>
        public bool CurrentFactoryCaptures { get; set; }

        /// <summary>The TemplateBuildContext var name while inside a template factory (x:Name → its RegisterName); null otherwise.</summary>
        public string? TemplateContextVar { get; set; }

        /// <summary>The templated-parent type while lowering inside a ControlTemplate body — the {TemplateBinding} source-property owner; null outside / in a DataTemplate.</summary>
        public INamedTypeSymbol? TemplatedParentType { get; set; }

        /// <summary>The type of the object whose members are currently being lowered — the receiver of resource extensions.</summary>
        public INamedTypeSymbol? CurrentObjectType { get; set; }

        /// <summary>The packed source position of the member currently being lowered — stamps any TODO note.</summary>
        public int CurrentLineInfo { get; set; }

        private int _counter;
        private int _factoryCounter;
        private StringBuilder? _current; // the emit target; null ⇒ Body (a template factory redirects via SwapBuffer)

        private StringBuilder Current => _current ?? Body;

        public string NextVar() => $"__e{_counter++}";

        public string NextFactory() => $"__Factory{_factoryCounter++}";

        /// <summary>Redirects <see cref="Line"/> to <paramref name="buffer"/> and returns the previous target (for restore).</summary>
        public StringBuilder SwapBuffer(StringBuilder buffer)
        {
            var prev = Current;
            _current = buffer;
            return prev;
        }

        public void Line(string statement) => Current.AppendLine(Indent + statement);

        /// <summary>
        /// Records a feature the full-lowering can't yet emit: leaves a visible <c>// TODO X5</c> marker in the
        /// generated code AND a note the generator surfaces as a build warning (so an opted-in <c>full</c> build
        /// never silently drops a member — the marker alone would be invisible at the call site).
        /// </summary>
        public void Todo(string message)
        {
            Line("// TODO X5: " + message);
            Unlowered.Add(new UnloweredMember(message, LineInfo.Line(CurrentLineInfo), LineInfo.Column(CurrentLineInfo)));
        }

        /// <summary>Records a CURG2002 info note for an emitted-but-non-optimal member (no <c>// TODO</c> marker —
        /// the member works). Stamped at the current member's source position.</summary>
        public void Info(string message)
            => Infos.Add(new UnloweredMember(message, LineInfo.Line(CurrentLineInfo), LineInfo.Column(CurrentLineInfo)));
    }

    /// <summary>The lowered source, the members it couldn't emit (build-warning candidates), and info-level notes
    /// for members emitted in a non-optimal form (CURG2002 — e.g. a binding that stayed reflective).</summary>
    public readonly struct LoweringResult(string source, IReadOnlyList<UnloweredMember> unlowered, IReadOnlyList<UnloweredMember> infos)
    {
        public string Source { get; } = source;
        public IReadOnlyList<UnloweredMember> Unlowered { get; } = unlowered;
        public IReadOnlyList<UnloweredMember> Infos { get; } = infos;
    }

    /// <summary>A member the full-lowering couldn't emit, with its 1-based source position (0 if unknown).</summary>
    public readonly struct UnloweredMember(string message, int line, int column)
    {
        public string Message { get; } = message;
        public int Line { get; } = line;
        public int Column { get; } = column;
    }

    // A {StaticResource} to resolve at end-of-InitializeComponent. Owner non-null ⇒ SetValue(Owner.<Prop>Property);
    // else a CLR set (cast to ClrType when non-null, i.e. a typed non-object/string CLR target).
    private readonly struct StaticResourceResolution(string var, INamedTypeSymbol? owner, string property, string key, ITypeSymbol? clrType)
    {
        public string Var { get; } = var;
        public INamedTypeSymbol? Owner { get; } = owner;
        public string Property { get; } = property;
        public string Key { get; } = key;
        public ITypeSymbol? ClrType { get; } = clrType;
    }

    private readonly struct ReferenceResolution(string var, INamedTypeSymbol? owner, string property, string name, ITypeSymbol? clrType)
    {
        public string Var { get; } = var;
        public INamedTypeSymbol? Owner { get; } = owner;
        public string Property { get; } = property;
        public string Name { get; } = name;
        public ITypeSymbol? ClrType { get; } = clrType;
    }
