    // The `RelativeSource = …` fragment: "" not present; the Self/TemplatedParent fragment; null for an
    // unsupported mode (FindAncestor etc. — the caller TODOs), mirroring the handler's ParseRelativeSource.
    private static string? RelativeSourceInit(Context c, MarkupExtensionNode node)
    {
        if (node.FindNamed("RelativeSource") is not { } value)
            return string.Empty;

        string? mode = value.IsNested
            ? FirstPositionalText(value.Nested!) ?? NamedText(value.Nested!, "Mode")
            : value.Text;

        return mode switch
        {
            "TemplatedParent" => "RelativeSource = global::Cursorial.UI.Data.RelativeSource.TemplatedParent",
            "Self" => "RelativeSource = global::Cursorial.UI.Data.RelativeSource.Self",
            "FindAncestor" when value.IsNested => FindAncestorInit(c, value.Nested!),
            null when value.IsNested => "RelativeSource = global::Cursorial.UI.Data.RelativeSource.Self", // WPF default
            _ => null,
        };
    }

    // {Binding Converter={StaticResource Conv}} → the same-dictionary converter resource's built var; {Binding
    // Converter={x:Static M}} → the static converter instance. Empty when there's no Converter; null (bail to the
    // reflective fallback) for a Converter form it cannot lower HERE (fenced/forward {StaticResource},
    // unresolvable {x:Static}); a CUSTOM extension converter lowers via ProvideValue + RequireConverter.
    private static string? ConverterInit(Context c, MarkupExtensionNode node)
    {
        if (node.FindNamed("Converter") is not { } arg)
            return string.Empty;

        if (arg.IsNested && arg.Nested is {} inner)
        {
            if (inner.PositionalArguments.Count > 0 && inner.PositionalArguments[0].Text is { } first)
            {
                // {StaticResource Key} — a converter resource. A same-dictionary visible entry → its var; an
                // external key → an eager ResolveStatic (cast to IValueConverter). The loader's ResolveConverter
                // resolves the same nested {StaticResource}. A forward intra-document / in-template key falls
                // through (the caller degrades to the reflective binding lane).
                if (inner.Name is "StaticResource")
                {
                    var keyExpr = $"\"{Escape(first)}\""; // a plain-string key is its own canonical identity
                    if (ResolveVisibleResourceVar(c, keyExpr, out var fenceRequired) is { } srcVar)
                        return $"Converter = {srcVar}";
                    if (!fenceRequired && ExternalStaticResolveExpr(c, keyExpr, keyExpr) is { } resolve)
                        // RequireConverter (not a bare cast): a null/non-converter resource must throw like the
                        // loader's ResolveConverter, never a silent null converter binding unconverted.
                        return $"Converter = global::Cursorial.UI.ResourceScopes.RequireConverter({resolve}, {keyExpr})";
                }

                // {x:Static Member} — the static converter instance.
                if (inner.Name is "x:Static" or "Static" && ResolveStaticPath(c, first) is { } expr)
                    return $"Converter = {expr}";
            }

            // Only a genuinely CUSTOM nested extension reaches the ProvideValue lane. A built-in that
            // fell through above (a fenced/forward {StaticResource}, an unresolvable {x:Static}) must
            // decline to the reflective lane with the caller's accurate reason — not chase a phantom
            // 'StaticResourceExtension' type; live/deferred forms ({Binding}/{DynamicResource}/
            // {TemplateBinding}/{x:Reference}) can never be converters (the loader Fatals on them).
            if (inner.Name is "x:Null" or "Null" or "x:Static" or "Static" or "x:Type" or "StaticResource"
                or "DynamicResource" or "Binding" or "TemplateBinding" or "x:Reference" or "Reference")
                return null;

            if (CustomExtensionExpr(c, inner, null, null) is {} customExpr)
                return $"Converter = global::Cursorial.UI.ResourceScopes.RequireConverter({customExpr}, \"Converter\")";
        }

        return null;
    }

    // {RelativeSource FindAncestor, AncestorType={x:Type T} | T [, AncestorLevel=n]} → an object-initializer matching
    // the loader's RelativeSource (Mode/AncestorType/AncestorLevel) so the dual-run renders identically. Null (bail to
    // reflective) when AncestorType is absent / unresolvable.
    private static string? FindAncestorInit(Context c, MarkupExtensionNode node)
    {
        if (node.FindNamed("AncestorType") is not { } typeArg)
            return null;

        var typeName = typeArg.IsNested
            ? (typeArg.Nested!.PositionalArguments.Count > 0 ? typeArg.Nested.PositionalArguments[0].Text : null)
            : typeArg.Text;
        if (string.IsNullOrEmpty(typeName) || XamlDataTypeScope.ResolveToken(c.Doc, typeName!, c.Resolver) is not { } typeSym)
            return null;

        var level = NamedText(node, "AncestorLevel") is { } lvl && int.TryParse(lvl, out var n) && n > 0 ? n : 1;
        return $"RelativeSource = new global::Cursorial.UI.Data.RelativeSource {{ Mode = global::Cursorial.UI.Data.RelativeSourceMode.FindAncestor, " +
               $"AncestorType = typeof({Global(typeSym, false)}), AncestorLevel = {level} }}";
    }

    // Joins non-empty object-initializer member assignments into a ` { a, b }` suffix, or "" when none.
    private static string Initializers(IEnumerable<string> members)
    {
        var present = members.Where(s => s.Length > 0).ToList();
        return present.Count == 0 ? string.Empty : " { " + string.Join(", ", present) + " }";
    }

    // Resolves an {x:Static [prefix:]Type.Member} path to a C# static reference. The prefix binds through
    // the document xmlns table (P1C — a prefix maps to its declared namespace, a bare token to the default
    // xmlns), then ClosedTypeSet.ResolveStaticExpr bakes the expression — the SAME helper the generated
    // provider's switch bakes through, so the lowered and loaded lanes resolve identically (a miss degrades
    // to the caller's TODO, never non-compiling code).
    private static string? ResolveStaticPath(Context c, string memberPath)
        => SplitStaticPath(c, memberPath, out var ns, out var path)
               ? ClosedTypeSet.ResolveStaticExpr(c.Resolver, ns, path)
               : null;

    // As ResolveStaticPath, but for a {StaticResource} / x:Key KEY: when the {x:Static} member is a compile-time
    // CONST STRING, return its VALUE as a string literal instead of the `global::Type.Member` access. The loader
    // resolves an x:Static key to the member's value, so a const-string x:Static key and a plain-string key with
    // that value are the SAME runtime key — canonicalizing to the literal makes their lowered key EXPRESSIONS
    // textually identical too, so KeyExprToVar / DocumentResourceKeys / the {StaticResource} lookup match by value
    // across the two forms. Without this, a cross-form key silently DIVERGES under an unreachable scope: the var
    // lookup misses (different text), the DocumentResourceKeys backstop misses (external key not enumerated), and
    // the ResolveStatic chain — which drops the unreachable scope — resolves a farther/app value the loader shadows.
    private static string? ResolveStaticKeyExpr(Context c, string memberPath)
    {
        if (SplitStaticPath(c, memberPath, out var ns, out var path) &&
            ClosedTypeSet.ResolveStaticConstString(c.Resolver, ns, path) is { } literal)
            return $"\"{Escape(literal)}\"";
        return ResolveStaticPath(c, memberPath);
    }

    // Splits an {x:Static} member path into its resolved xmlns + prefix-free path. Returns false when a declared
    // prefix is present but unbound (the caller then resolves to null, matching the loader's member-not-found).
    private static bool SplitStaticPath(Context c, string memberPath, out string ns, out string path)
    {
        int colon = memberPath.IndexOf(':');
        if (colon > 0)
        {
            path = memberPath.Substring(colon + 1);
            return c.Doc.Namespaces.TryGetValue(memberPath.Substring(0, colon), out ns!);
        }

        path = memberPath;
        ns = c.Doc.Namespaces.TryGetValue(string.Empty, out var dns) ? dns : XamlSymbolResolver.CursorialUiNamespace;
        return true;
    }

