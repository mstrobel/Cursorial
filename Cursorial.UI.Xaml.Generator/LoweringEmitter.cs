    /// <summary>
    /// The C# value expression for an element-form markup extension used as a dictionary/collection ENTRY
    /// (resource aliasing): a folded constant, a custom extension's standalone ProvideValue, a
    /// <c>DynamicResource</c> carrier (<c>new ResourceReference(key)</c>), or a resolvable
    /// <c>StaticResource</c>. Null when the extension has no standalone lowering here; <paramref name="reported"/>
    /// is true when the failure ALREADY emitted its own specific Todo/Error (a fenced custom extension), so the
    /// caller must not add a second, generic CURG3001 over it.
    /// </summary>
    private static string? MarkupExtensionEntryExpr(Context c, in ObjectRecord extObject, out bool reported)
    {
        reported = false;
        var value = ExtensionValueMember(c, in extObject);
        if (value.Kind == XamlValueKind.Folded)
            return FoldedValueExpr(c, c.Doc.Constants[value.ValueIndex]);

        ref readonly var ext = ref c.Doc.Extensions[value.ValueIndex];

        // A custom extension standalone (a dictionary/collection entry) provides its value with a null target —
        // the loader's ProvideStandaloneCustomValue shape. On failure CustomExtensionExpr emits its own specific
        // Todo/Error naming the actual problem — flag it so the caller doesn't double-report generically.
        if (ext.Kind == ExtensionKind.Custom && c.Doc.ParsedExtensions[ext.Payload] is { } node)
        {
            var custom = CustomExtensionExpr(c, node, targetObjectExpr: null, targetPropertyExpr: null);
            reported = custom is null;
            return custom;
        }

        // Reuse the same *Resource value lowering the curly Setter.Value form uses: a DynamicResource
        // carrier (literal OR a nested {x:Static}/{x:Type}/custom key — the common theme-key alias), and a
        // same-dictionary/external StaticResource. Binding/TemplateBinding/{x:Reference} and a forward-or-fenced
        // resource key have no standalone value expression and return null (the caller degrades to CURG3001).
        return ResourceValueExpr(c, in ext);
    }

    /// <summary>The value slot of an element-form markup-extension object (the single Extension/Folded member;
    /// an x:Key directive, when present, is separate).</summary>
    private static MemberRecord ExtensionValueMember(Context c, in ObjectRecord record)
    {
        for (int i = 0; i < record.MemberCount; i++)
        {
            var m = c.Doc.Members[record.MemberStart + i];
            if (m.Kind is XamlValueKind.Extension or XamlValueKind.Folded)
                return m;
        }

        return c.Doc.Members[record.MemberStart + record.MemberCount - 1];
    }

    /// <summary>
    /// Lowers an element-form markup extension (<paramref name="extObject"/>) as the value of member
    /// <paramref name="xm"/> — a folded intrinsic emits its constant; a live extension reuses the same
    /// per-kind lowering the curly attribute form does (so element and curly form lower identically).
    /// </summary>
    private static void EmitMarkupExtensionMember(Context c, string varExpr, XamlMember xm, in ObjectRecord extObject, INamedTypeSymbol? dataType)
    {
        var value = ExtensionValueMember(c, in extObject);
        if (value.Kind == XamlValueKind.Folded)
            EmitFoldedAssign(c, varExpr, xm, c.Doc.Constants[value.ValueIndex]);
        else
            EmitExtensionAssign(c, varExpr, xm, in c.Doc.Extensions[value.ValueIndex], dataType);
    }

    private static void EmitExtensionAssign(Context c, string varExpr, XamlMember xm, in ExtensionRecord ext, INamedTypeSymbol? dataType)
    {
        switch (ext.Kind)
        {
            case ExtensionKind.Binding when c.Doc.ParsedExtensions[ext.Payload] is { } node:
                EmitBinding(c, varExpr, xm, node, dataType);
                return;

            case ExtensionKind.DynamicResource:
                EmitDynamicResource(c, varExpr, xm, in ext);
                return;

            case ExtensionKind.StaticResource:
                EmitStaticResource(c, varExpr, xm, in ext);
                return;

            case ExtensionKind.TemplateBinding when c.Doc.ParsedExtensions[ext.Payload] is { } node:
                EmitTemplateBinding(c, varExpr, xm, node);
                return;

            case ExtensionKind.Reference:
                EmitReference(c, varExpr, xm, c.Doc.Strings[ext.Payload]);
                return;

            case ExtensionKind.Custom when c.Doc.ParsedExtensions[ext.Payload] is { } node:
                EmitCustomExtension(c, varExpr, xm, node);
                return;

            default:
                c.Todo($"extension {ext.Kind} for '{xm.Name}' not yet lowered");
                return;
        }
    }

    // A custom {Foo …} markup extension as a member value → new FooExtension { args }.ProvideValue(services),
    // the result assigned to the target — the AOT-clean twin of the loader's ActivateCustomExtension +
    // XamlServiceProvider. The service bundle carries the provide-value target (this element + the target
    // property), the document root, and the enclosing name scope.
    private static void EmitCustomExtension(Context c, string varExpr, XamlMember xm, MarkupExtensionNode node)
    {
        // TargetProperty mirrors the loader: the UIProperty for a registered target, else the CLR member's
        // runtime type (the loader passes a XamlMember carrying that type; LoweredExtensionServices + the
        // extensions' Type arm read it the same way).
        var owner = RegisteredOwner(xm);
        string targetPropExpr = owner is { } o ? $"{Global(o)}.{xm.Name}Property"
            : ValueTypeSymbol(xm.ValueType) is { } vt ? $"typeof({Global(vt, false)})"
            : "null";

        // An init-only / read-only CLR member can't be assigned post-construction (CS8852/CS0200 — non-compiling
        // generated code, the same fence every sibling assign path carries). A non-root init-only slot normally
        // never reaches here — ScanInitOnlyMembers routes it into the construction object initializer — so this
        // catches the un-routable cases: the root (`this`, already constructed) and an object whose own
        // <X.Resources> shadow-guards the initializer route.
        if (owner is null && ClrSetBlocked(c, xm.Name))
        {
            c.Todo($"custom markup extension target '{xm.Name}' is init-only/read-only — can't be assigned post-construction (set on the root, or an own-Resources scope blocks the initializer route)");
            return;
        }

        if (CustomExtensionExpr(c, node, varExpr, targetPropExpr) is not { } provideValue)
            return; // a specific Todo/Error was emitted

        // A string ProvideValue result destined for a typed (non-string/object) slot runs the converter ladder
        // — the loader's AssignResolvedValue (X121). A no-op for object/string targets, so only wrapped when
        // the slot is a concrete non-string type.
        var valueType = ValueTypeSymbol(xm.ValueType);
        var coerceTyped = valueType is { SpecialType: not (SpecialType.System_Object or SpecialType.System_String) };
        var value = coerceTyped
            ? $"global::Cursorial.UI.Xaml.LoweredExtensionServices.Coerce({provideValue}, typeof({Global(valueType!, false)}))"
            : provideValue;

        if (owner is { } owner2)
            c.Line($"{varExpr}.SetValue({Global(owner2)}.{xm.Name}Property, {value});");
        else if (valueType is { SpecialType: not SpecialType.System_Object } ct)
            c.Line($"{varExpr}.{xm.Name} = ({Global(ct)}){value}!;"); // cast object? to a concrete CLR target (string included)
        else
            c.Line($"{varExpr}.{xm.Name} = {value};"); // object target
    }

    // Builds `new FooExtension { named/positional args }.ProvideValue(new LoweredExtensionServices(…))` for a
    // custom extension node, or null (a specific Todo — or, for input the loader hard-rejects, an error-level
    // marker — was emitted). targetObjectExpr/targetPropertyExpr are null for a standalone entry (the loader's
    // ProvideStandaloneCustomValue passes a null target).
    private static string? CustomExtensionExpr(Context c, MarkupExtensionNode node, string? targetObjectExpr, string? targetPropertyExpr)
    {
        var extType = ResolveCustomExtensionType(c, node);
        if (extType is null || !DerivesFromMarkupExtension(extType))
        {
            // Input the LOADER hard-rejects (ResolveExtensionType Fatal: TypeNotFound) — error-level, so the
            // lowered build fails the way the loader does instead of warn-and-skipping an invalid document.
            c.Error($"custom markup extension '{node.Name}' does not resolve to a MarkupExtension type (the runtime loader rejects it)");
            return null;
        }

        // The IAmbientResources chain we can hand the extension (ReachableAmbientDicts) silently drops EVERY
        // unreachable enclosing-factory scope. A runtime key the loader resolves against a dropped scope would
        // resolve a farther dict / the app tail instead — a fail-open. The extension probes arbitrary keys, so we
        // can't fence per-key: if the chain would be missing any scope the loader's captured chain includes, fence
        // the whole extension.
        if (HasUnreachableAmbientScope(c))
        {
            c.Todo($"custom markup extension '{node.Name}' can't be lowered inside a nested template: an enclosing-factory resource scope is unreachable from the ambient chain");
            return null;
        }

        var inits = new List<string>();

        // Positional args → writable public properties by the WPF [ConstructorArgument] convention (the only
        // GENERAL ordering that lowers PARITY-safe; declaration order is not guaranteed to match reflection's,
        // so an unannotated positional extension fences rather than risk a wrong mapping — except the provably
        // order-irrelevant subset: one positional, one candidate property (SinglePositionalFallback).
        if (node.PositionalArguments.Count > 0)
        {
            var order = ConstructorArgumentOrder(extType, node.PositionalArguments.Count)
                        ?? SinglePositionalFallback(extType, node.PositionalArguments.Count);
            if (order is null)
            {
                c.Todo($"custom markup extension '{node.Name}' has positional args without the [ConstructorArgument] convention — not yet lowered (annotate each ctor parameter's matching property with [ConstructorArgument(\"paramName\")] so both lanes map positionals identically)");
                return null;
            }
            for (int i = 0; i < order.Length; i++)
            {
                if (!IsInitializerSettable(order[i]))
                {
                    // A get-only property / readonly field has no setter in EITHER lane (CS0200/CS0191 here; the
                    // loader's Assign raises its hard "no setter" diagnostic) — error-level for lane parity.
                    c.Error($"custom markup extension '{node.Name}' positional arg {i} targets a read-only member (the runtime loader rejects it: no setter)");
                    return null;
                }
                if (CustomExtensionArgValue(c, node.PositionalArguments[i], XamlDataTypeScope.MemberType(order[i])) is not { } v)
                {
                    FenceUnlowerableArgValue(c, node, $"positional arg {i}", node.PositionalArguments[i]);
                    return null;
                }
                inits.Add($"{order[i].Name} = {v}");
            }
        }

        // Named args → members on the extension.
        foreach (var named in node.NamedArguments)
        {
            if (XamlDataTypeScope.FindMember(extType, named.Name) is not { } memberSym)
            {
                c.Todo($"custom markup extension '{node.Name}' has no member '{named.Name}'");
                return null;
            }
            if (!IsInitializerSettable(memberSym))
            {
                // A get-only property / readonly field can't be set in the object initializer (CS0200/CS0191),
                // AND the loader's Assign raises its hard "no setter" diagnostic on the identical document —
                // error-level, so the lowered build fails the way the loader does.
                c.Error($"custom markup extension '{node.Name}' arg '{named.Name}' targets a read-only member (the runtime loader rejects it: no setter)");
                return null;
            }
            if (CustomExtensionArgValue(c, named.Value, XamlDataTypeScope.MemberType(memberSym)) is not { } v)
            {
                FenceUnlowerableArgValue(c, node, $"arg '{named.Name}'", named.Value);
                return null;
            }
            inits.Add($"{named.Name} = {v}");
        }

        // The services carry the document root (`this`) — inside a template factory that forces the factory
        // non-static so it may reference `this`, exactly as the FindResource-anchored `this` capture does.
        if (c.HasRootElement && c.InTemplate)
            c.CurrentFactoryCaptures = true;

        var root = c.HasRootElement ? "this" : "null";
        var scope = c.InTemplate ? "__ctx.NameScope" : c.HasDocumentScope ? "__scope" : "null";

        // The lexical ambient resource chain (IAmbientResources): the enclosing <X.Resources> dictionary locals
        // in the current C# method scope, INNERMOST-first. LoweredExtensionServices.TryFindResource appends the
        // application tail (App→Theme→Contributions→BuiltIn) at runtime, mirroring XamlResourceScopeStack.
        var reachable = ReachableAmbientDicts(c);
        string ambient = reachable.Count == 0
            ? "null"
            : $"new global::Cursorial.UI.ResourceDictionary[] {{ {string.Join(", ", reachable)} }}";

        // IXamlLineInfo — the node's 1-based author position (harmless 0,0 for a hand-built node).
        var services = $"new global::Cursorial.UI.Xaml.LoweredExtensionServices(" +
                       $"{targetObjectExpr ?? "null"}, {targetPropertyExpr ?? "null"}, {root}, {scope}, {ambient}, {node.Line}, {node.Column})";
        // An empty initializer needs explicit `()` — `new Foo.ProvideValue(…)` would parse ProvideValue as a nested type.
        var ctor = inits.Count > 0 ? $"new {Global(extType)}{Initializers(inits)}" : $"new {Global(extType)}()";
        return $"{ctor}.ProvideValue({services})";
    }

    // A custom-extension argument value as a C# expression: a nested {x:Static}/{x:Type}/{x:Null}/{StaticResource},
    // a nested CUSTOM extension (recursive composition — the runtime's ResolveNestedExtension default arm), or a
    // text value converted to the member type (the converter ladder). Null = not lowerable.
    private static string? CustomExtensionArgValue(Context c, MarkupExtensionArgumentValue arg, ITypeSymbol? memberType)
    {
        if (arg.IsNested)
        {
            var nested = arg.Nested!;
            if (nested.Name is "x:Static" or "Static" && FirstPositionalText(nested) is { Length: > 0 } sp)
                return ResolveStaticPath(c, sp);
            if (nested.Name is "x:Type" or "Type" && FirstPositionalText(nested) is { Length: > 0 } tt &&
                XamlDataTypeScope.ResolveToken(c.Doc, tt, c.Resolver) is { } ts)
                return $"typeof({Global(ts, false)})";
            if (nested.Name is "x:Null" or "Null")
                return "null";
            if (nested.Name is "StaticResource" && FirstPositionalText(nested) is { Length: > 0 } key)
            {
                var keyExpr = $"\"{Escape(key)}\""; // the loader's nested-arg StaticResource is plain-string-keyed only
                if (ResolveVisibleResourceVar(c, keyExpr, out var fenceRequired) is { } srcVar)
                    return srcVar; // a same-dictionary entry var (typed)
                // An external / app-tail / deferred key → an eager ResolveStatic (object?), cast to the arg's member
                // type (object → concrete; string included, since object? → string is not implicit) — exactly the
                // main {StaticResource} path, and the loader's nested-arg StaticResource resolution.
                if (!fenceRequired && ExternalStaticResolveExpr(c, keyExpr, keyExpr) is { } resolve)
                    return memberType is { SpecialType: not SpecialType.System_Object } ? $"({Global(memberType)}){resolve}!" : resolve;
            }

            // A nested CUSTOM extension COMPOSES recursively: since the runtime's nested-custom parity pass
            // (7bdf71e1), ResolveNestedExtension's default arm is ProvideStandaloneCustomValue — an eager
            // target-less ProvideValue, exactly the standalone shape CustomExtensionExpr emits — so recursion
            // reproduces the loader bit-for-bit. Only a genuinely NON-built-in name recurses: a built-in that
            // fell through its own arm above (a fenced/forward {StaticResource}, a live/deferred
            // {Binding}/{DynamicResource}/…) must not chase a phantom '<Name>Extension' type — it stays
            // declined and the caller fences with its accurate message.
            if (!IsBuiltInNestedExtensionName(nested.Name) &&
                CustomExtensionExpr(c, nested, targetObjectExpr: null, targetPropertyExpr: null) is { } customValue)
            {
                // Mirror EmitCustomExtension's Coerce/cast rules for the typed member slot: a string result runs
                // the converter ladder at runtime (Coerce — the loader's AssignResolvedValue twin), and the
                // object?-typed expression casts to the concrete member type (string included — object? → string
                // is not implicit). An object/untyped slot takes the raw provide-value expression.
                if (memberType is null || memberType.SpecialType is SpecialType.System_Object)
                    return customValue;
                if (memberType.SpecialType is SpecialType.System_String)
                    return $"(string){customValue}!";
                return $"({Global(memberType)})global::Cursorial.UI.Xaml.LoweredExtensionServices.Coerce({customValue}, typeof({Global(memberType, false)}))!";
            }

            return null; // {Binding} / nested-key {StaticResource} / a forward-or-unreachable key — no value here
        }

        // A text value → the typed member expression (an object-initializer assignment needs the concrete
        // type, so the converter result is cast — unlike the object-typed Setter.Value lane).
        var text = arg.Text ?? string.Empty;
        if (memberType is null || memberType.SpecialType is SpecialType.System_String or SpecialType.System_Object)
            return $"\"{Escape(text)}\"";
        if (IsSystemType(memberType))
            return XamlDataTypeScope.ResolveToken(c.Doc, text, c.Resolver) is { } resolved ? $"typeof({Global(resolved, false)})" : null;

        c.UsesConverter = true;
        return $"({Global(memberType)})__ConvertXamlValue(typeof({Global(memberType, false)}), \"{Escape(text)}\")!";
    }

    // The nested-position BUILT-IN extension name set (the frontend's ClassifyExtension names plus the bare
    // aliases the emitter's own nested arms accept). Nested argument nodes carry no ExtensionKind, so custom-lane
    // guards check the NAME: a built-in that fell through its own arm (a fenced/forward {StaticResource}, a
    // live/deferred {Binding}/{DynamicResource}/…) must never reach CustomExtensionExpr, which would chase a
    // phantom '<Name>Extension' type and emit a misleading "could not be resolved" Todo.
    private static bool IsBuiltInNestedExtensionName(string name)
        => name is "x:Null" or "Null" or "x:Static" or "Static" or "x:Type" or "Type"
            or "StaticResource" or "DynamicResource" or "Binding" or "TemplateBinding"
            or "x:Reference" or "Reference";

    // The nested names the LOADER hard-rejects as extension-argument values (ResolveNestedExtension Fatal):
    // {Binding}/{DynamicResource}/{TemplateBinding}/{x:Reference} each produce a LIVE or DEFERRED result (a
    // binding, a resource producer, a template pull, a namescope reference) rather than a plain value, so no
    // eager argument value exists in EITHER lane. Returns the name (for the diagnostic), else null.
    private static string? LiveNestedArgName(MarkupExtensionArgumentValue arg)
        => arg.IsNested && arg.Nested!.Name is "Binding" or "DynamicResource" or "TemplateBinding" or "Reference" or "x:Reference"
               ? arg.Nested.Name
               : null;

    // A custom-extension argument value CustomExtensionArgValue declined. A nested live/deferred extension is
    // input the runtime loader Fatals on — error-level for lane parity (the lowered build must fail as loudly).
    // Everything else (a fenced/forward {StaticResource} key, an unresolvable nested value) is a genuine
    // lowering gap over possibly-valid input: warning-level Todo.
    private static void FenceUnlowerableArgValue(Context c, MarkupExtensionNode node, string argLabel, MarkupExtensionArgumentValue arg)
    {
        if (LiveNestedArgName(arg) is { } live)
            c.Error($"custom markup extension '{node.Name}' {argLabel} nests {{{live}}}, which produces a live/deferred value and cannot be a nested extension argument (the runtime loader rejects it)");
        else
            c.Todo($"custom markup extension '{node.Name}' {argLabel} value not lowerable");
    }

    // Resolves a custom extension's type symbol (mirrors the loader's ResolveExtensionType): the name binds
    // through its stamped xmlns (the default UI uri for an unprefixed / hand-built node), preferring the WPF
    // "Extension"-suffixed twin so a `{Icon}` beside an `Icon` CONTROL binds `IconExtension`.
    private static INamedTypeSymbol? ResolveCustomExtensionType(Context c, MarkupExtensionNode node)
    {
        var name = node.Name;
        int colon = name.IndexOf(':');
        if (colon >= 0)
            name = name.Substring(colon + 1);

        var ns = node.ResolvedNamespace ?? XamlSymbolResolver.CursorialUiNamespace;
        return c.Resolver.Resolve(ns, name + "Extension", out _)
               ?? c.Resolver.Resolve(ns, name, out _);
    }

    // True when a member can be set in an object initializer (new T { Member = v }): a public settable or
    // init-only property, or a non-readonly/non-const field. A get-only property (CS0200) or readonly field
    // (CS0191) can't — the caller fences (the loader raises its own "no setter" diagnostic).
    private static bool IsInitializerSettable(ISymbol member)
        => XamlDataTypeScope.IsWritable(member) || XamlDataTypeScope.IsInitOnlySettable(member);

    private static bool DerivesFromMarkupExtension(INamedTypeSymbol type)
    {
        for (INamedTypeSymbol? t = type; t is not null; t = t.BaseType)
            if (t.ToDisplayString() == "Cursorial.UI.Xaml.MarkupExtension")
                return true;
        return false;
    }

    // The property symbols an extension's positional args map to, by the [ConstructorArgument] convention: the
    // public constructor whose arity matches, each parameter resolved to the property carrying
    // [ConstructorArgument(paramName)]. Null when no constructor matches or any parameter is unannotated (the
    // caller fences — declaration order is not parity-safe). Mirrors the loader's ResolveConstructorArgumentOrder.
    private static ISymbol[]? ConstructorArgumentOrder(INamedTypeSymbol extType, int count)
    {
        IMethodSymbol? ctor = null;
        foreach (var candidate in extType.InstanceConstructors)
            if (candidate.DeclaredAccessibility == Accessibility.Public && candidate.Parameters.Length == count)
            {
                ctor = candidate;
                break;
            }
        if (ctor is null)
            return null;

        var result = new ISymbol[count];
        for (int i = 0; i < count; i++)
        {
            var paramName = ctor.Parameters[i].Name;
            ISymbol? match = null;
            for (var t = extType; t is not null && match is null; t = t.BaseType)
                foreach (var member in t.GetMembers())
                {
                    if (member is not (IPropertySymbol or IFieldSymbol))
                        continue;
                    foreach (var attr in member.GetAttributes())
                        if (attr.AttributeClass?.Name == "ConstructorArgumentAttribute" &&
                            attr.ConstructorArguments.Length > 0 &&
                            attr.ConstructorArguments[0].Value as string == paramName)
                        {
                            match = member;
                            break;
                        }
                    if (match is not null)
                        break;
                }
            if (match is null)
                return null;
            result[i] = match;
        }
        return result;
    }

    // The provably-safe UNANNOTATED positional subset: ONE positional arg and EXACTLY ONE candidate property
    // on the whole extension — with a single candidate, the loader's reflection-declaration-order fallback
    // (ApplyPositionalArguments) and this mapping agree trivially, so the ordering hazard that fences the
    // general unannotated case vanishes. The candidate count mirrors the loader's GetProperties(Public|Instance)
    // + CanWrite walk: public instance PROPERTIES with any setter (fields never participate — the loader's
    // fallback walks properties and [ConstructorArgument] is property-only), an override/shadow counted once.
    // The single candidate must also be an initializer-settable non-indexer here, else the fence stays.
    private static ISymbol[]? SinglePositionalFallback(INamedTypeSymbol extType, int count)
    {
        if (count != 1)
            return null;

        IPropertySymbol? single = null;
        HashSet<string>? seen = null;
        for (INamedTypeSymbol? t = extType; t is not null && t.SpecialType != SpecialType.System_Object; t = t.BaseType)
            foreach (var member in t.GetMembers())
            {
                if (member is not IPropertySymbol { IsStatic: false, DeclaredAccessibility: Accessibility.Public, SetMethod: not null } prop)
                    continue;
                if (!(seen ??= new HashSet<string>()).Add(prop.Name))
                    continue; // an override/shadow of a base property — one reflection slot, counted once
                if (single is not null)
                    return null; // two candidates — the mapping is order-dependent again
                single = prop;
            }

        return single is { IsIndexer: false } p && IsInitializerSettable(p) ? new ISymbol[] { p } : null;
    }

    // {x:Reference Name} → a deferred assignment from the ACTIVE name scope, emitted after every x:Name in
    // that scope is registered so a forward reference resolves: the document scope at end-of-
    // InitializeComponent, or — inside a template factory — the per-build template scope flushed before the
    // factory's return (the loader's end-of-slice ResolveDeferredReferences point; scope isolation is
    // automatic since the factory list never reaches the document flush).
    private static void EmitReference(Context c, string varExpr, XamlMember xm, string name)
    {
        // A document-level reference resolves through __scope, which exists only when the document
        // declares document-scope x:Names. Without one, the reference can never resolve (the loader
        // Fatals too) — fence rather than emit a reference to an undeclared __scope (CS0103).
        if (!c.InTemplate && !c.HasDocumentScope)
        {
            c.Todo($"{{x:Reference {name}}} for '{xm.Name}' cannot resolve — the document declares no name scope");
            return;
        }

        var owner = RegisteredOwner(xm);
        var clrType = owner is null ? ValueTypeSymbol(xm.ValueType) : null;
        c.References.Add(new ReferenceResolution(varExpr, owner, xm.Name, name, clrType));
    }

    // {DynamicResource Key} → ResourceExtensions.SetResourceReference(element, Owner.FooProperty, key): a live
    // producer that re-resolves against the element's ancestor chain on attach (no eager-resolution timing
    // problem — works inline AND inside templates). Requires a registered NON-DIRECT styled property target — a
    // StyledProperty<T> or its AttachedProperty<T> subclass (the loader's IsDirect:false gate); only a DIRECT
    // property is rejected. The key: a literal, a nested {x:Static}/{x:Type}, or a nested CUSTOM extension
    // (eager target-less ProvideValue — the key is an opaque object to SetResourceReference).
    private static void EmitDynamicResource(Context c, string varExpr, XamlMember xm, in ExtensionRecord ext)
    {
        if (!XamlDataTypeScope.IsUIElement(c.CurrentObjectType))
        {
            c.Todo($"{{DynamicResource}} on a non-UIElement target ('{xm.Name}') not yet lowered");
            return;
        }

        if (RegisteredOwner(xm) is not { } owner || !XamlDataTypeScope.IsNonDirectStyledProperty(owner, xm.Name))
        {
            c.Todo($"{{DynamicResource}} target '{xm.Name}' is a direct/non-styled UIProperty — not resource-referenceable");
            return;
        }

        // The key: a literal string, a nested {x:Static}/{x:Type} member, or a nested CUSTOM extension providing
        // the key object eagerly (SetResourceReference's key param is object — the value is opaque to lowering,
        // matching the loader's ResolveResourceKey → ResolveNestedExtension).
        if ((ResourceKeyArgExpr(c, in ext) ?? CustomResourceKeyExpr(c, in ext)) is not { } keyExpr)
        {
            c.Todo($"{{DynamicResource}} with an unsupported markup-extension key for '{xm.Name}' not yet lowered");
            return;
        }

        // SetResourceReference<T> infers T from the StyledProperty<T> field; call it statically (no using).
        c.Line($"global::Cursorial.UI.ResourceExtensions.SetResourceReference({varExpr}, {Global(owner)}.{xm.Name}Property, {keyExpr});");
    }

    // {StaticResource Key} on an element member — resolved EAGERLY (the loader resolves a live-member
    // StaticResource eagerly too): a same-dictionary visible entry → its var; an external key → an inline
    // ResourceScopes.ResolveStatic against the lexical chain + application tail (exact parity, replacing the
    // former end-of-tree FindResource anchor). A non-UIElement target, a forward/not-yet-built intra-document
    // key, or an in-template reference stays a // TODO.
    private static void EmitStaticResource(Context c, string varExpr, XamlMember xm, in ExtensionRecord ext)
    {
        // Same-dictionary key (string OR nested {x:Type}/{x:Static}, lexically built before this use): reference the
        // entry's var directly — StaticResource's exact load-time-snapshot semantics, and the only form that works
        // inside a template factory (a non-static local function captures the var). Works inline too (the var is in
        // the same Build() scope).
        if (ResourceKeyArgExpr(c, in ext) is not { } keyExpr)
        {
            c.Todo($"{{StaticResource}} key for '{xm.Name}' is an unsupported markup extension — not yet lowered");
            return;
        }
        var keyId = ResourceKeyArgExpr(c, in ext, canonical: true) ?? keyExpr;

        // A {StaticResource} on a NON-UIElement object (a brush inside another resource) may target an
        // init-only slot (SolidColorBrush.Color) that must be set in the object initializer — the eager-assign
        // form here would be CS8852. Fence (the object-initializer routing is a later phase).
        if (!XamlDataTypeScope.IsUIElement(c.CurrentObjectType))
        {
            c.Todo($"{{StaticResource}} on a non-UIElement target ('{xm.Name}') not yet lowered");
            return;
        }

        // An init-only / read-only CLR member (not a UIProperty) can't be assigned post-construction (CS8852) —
        // fence rather than emit non-compiling code (both the var and the ResolveStatic assign are post-ctor).
        if (RegisteredOwner(xm) is null && ClrSetBlocked(c, xm.Name))
        {
            c.Todo($"{{StaticResource}} target '{xm.Name}' is init-only/read-only — can't be assigned post-construction");
            return;
        }

        // A same-dictionary visible entry → its var (a typed local, the load-time snapshot).
        if (ResolveVisibleResourceVar(c, keyId, out var fenceRequired) is { } srcVar)
        {
            AssignResolvedResource(c, varExpr, xm, srcVar, valueIsObject: false);
            return;
        }

        // External key → resolve EAGERLY against the lexical chain + application tail. A {StaticResource} on a
        // LIVE element is resolved eagerly by the loader too (during member application), so this is exact
        // parity — and ResourceScopes.ResolveStatic drops FindResource's alias-chase / variant-aware /
        // live-tree over-resolution. A forward/not-yet-built intra-document key or an in-template reference fences.
        // fenceRequired (the innermost holder is an unreachable enclosing-factory scope) skips the external path:
        // ResolveStatic would resolve a farther/app value the loader shadows, so fence loudly instead.
        if (!fenceRequired && ExternalStaticResolveExpr(c, keyExpr, keyId) is { } resolve)
        {
            AssignResolvedResource(c, varExpr, xm, resolve, valueIsObject: true);
            return;
        }

        c.Todo(c.InTemplate
            ? $"{{StaticResource}} for '{xm.Name}' inside a template is a forward/not-yet-built reference, or lives in an unreachable enclosing-factory scope — not yet lowered"
            : $"{{StaticResource}} for '{xm.Name}' is a forward/not-yet-built intra-document reference — not yet lowered");
    }

    // Assigns an already-resolved resource value to a member: SetValue for a registered UIProperty (object? param,
    // no cast). For a CLR target, a TYPED value (a built entry's var) casts only for a base/interface-typed slot;
    // an object?-typed value (ResolveStatic) casts to ANY concrete member type — string included, since
    // object? → string is not implicit (the CS0266 the deferred FindResource path used to cast away).
    private static void AssignResolvedResource(Context c, string varExpr, XamlMember xm, string valueExpr, bool valueIsObject)
    {
        if (RegisteredOwner(xm) is { } owner)
        {
            c.Line($"{varExpr}.SetValue({Global(owner)}.{xm.Name}Property, {valueExpr});");
            return;
        }

        c.Line($"{varExpr}.{xm.Name} = {ResolvedResourceExpr(xm, valueExpr, valueIsObject)};");
    }

    // The RHS expression for an already-resolved resource value assigned to a CLR member — the shared core of the
    // post-construction assignment (AssignResolvedResource) and the object-initializer entry (an init-only slot fed
    // by a {StaticResource}). A TYPED value (a built entry's var) casts only for a base/interface-typed slot; an
    // object?-typed value (ResolveStatic) casts to ANY concrete member type — string included, since object? →
    // string is not implicit.
    private static string ResolvedResourceExpr(XamlMember xm, string valueExpr, bool valueIsObject)
    {
        if (valueIsObject && ValueTypeSymbol(xm.ValueType) is { SpecialType: not SpecialType.System_Object } ot)
            return $"({Global(ot)}){valueExpr}!";
        if (!valueIsObject && !IsObjectOrString(xm.ValueType) && ValueTypeSymbol(xm.ValueType) is { } ct)
            return $"({Global(ct)}){valueExpr}";
        return valueExpr;
    }

    // Emits the recorded {StaticResource} resolutions at the end of InitializeComponent. By here the whole tree
    // is constructed + attached and every <X.Resources> is populated, so el.FindResource walks the full ancestor
    // chain (throw-on-miss, matching the loader's eager resolution). Lexical == live for an inline document.
    // {x:Reference} resolutions, emitted after the tree is built + every x:Name registered, so a forward
    // reference (the named element appears later) resolves against the now-complete document name scope.
    private static void EmitDeferredReferences(Context c)
    {
        if (c.References.Count > 0)
        {
            c.Line("// {x:Reference} — resolve against the now-fully-populated document name scope (forward refs included).");
            EmitReferenceResolutions(c, fromIndex: 0, scopeExpr: "__scope");
            c.References.Clear();
        }

        FlushDeferredScopeLines(c, fromIndex: 0);
    }

    // The shared assign emission for recorded {x:Reference} resolutions — the document flush and the
    // per-template-factory flush differ only in the scope lookup expression.
    private static void EmitReferenceResolutions(Context c, int fromIndex, string scopeExpr)
    {
        for (int i = fromIndex; i < c.References.Count; i++)
        {
            var r = c.References[i];
            // Require, not Find: by flush time the scope's names are all registered, so a miss is a
            // genuine unresolved reference — throw-on-miss matches the loader's ReferenceNotFound Fatal
            // instead of silently assigning null (which, for a Binding source, rebinds to DataContext).
            // Static-call form — the generated code carries no `using`, so the extension can't be
            // invoked instance-style.
            var find = $"global::Cursorial.UI.NameScopeExtensions.Require({scopeExpr}, \"{Escape(r.Name)}\")";

            if (r.Owner is { } owner)
                c.Line($"{r.Var}.SetValue({Global(owner)}.{r.Property}Property, {find});");
            else if (r.ClrType is { } ct)
                c.Line($"{r.Var}.{r.Property} = ({Global(ct)}){find};");
            else
                c.Line($"{r.Var}.{r.Property} = {find};");
        }
    }

    // Drops trailing list entries recorded past a saved count (rolls back deferred work whose target
    // locals were emitted into a discarded buffer).
    private static void Truncate<T>(List<T> list, int count)
    {
        if (list.Count > count)
            list.RemoveRange(count, list.Count - count);
    }

    // Flushes deferred whole-line emissions (scope-embedding Installs) recorded past fromIndex.
    private static void FlushDeferredScopeLines(Context c, int fromIndex)
    {
        for (int i = fromIndex; i < c.DeferredScopeLines.Count; i++)
            c.Line(c.DeferredScopeLines[i]);
        c.DeferredScopeLines.RemoveRange(fromIndex, c.DeferredScopeLines.Count - fromIndex);
    }

    // B3a/B3b — {Binding} lowering. The compiled lane (zero reflection, AOT-clean) is taken for an
    // x:DataType-scoped, DataContext-relative, single-hop binding; everything else falls back to a faithful
    // reflective `new Binding(...)` (the plan's "graceful reflective fallback" — the binding still works, just
    // through the reflective engine, which surfaces an AOT warning pointing at the binding to fix). Only a
    // Converter-bearing binding (needs eager resource/static resolution, deferred with resources) or an
    // unsupported RelativeSource stays a // TODO X5.
    private static void EmitBinding(Context c, string varExpr, XamlMember xm, MarkupExtensionNode node, INamedTypeSymbol? dataType)
    {
        // A binding target must be a registered UIProperty — the runtime handler enforces the same (X119).
        if (RegisteredOwner(xm) is not { } owner)
        {
            c.Todo($"binding target '{xm.Name}' is not a bindable UIProperty");
            return;
        }

        if (c.CurrentObjectType is {} current && IsAssignableTo(owner, current))
            owner = current;

        if (TryEmitCompiledBinding(c, varExpr, owner, xm, node, dataType, out var reason))
            return;
    
        var reflectiveEmitted = EmitReflectiveBinding(c, varExpr, owner, xm, node);

        // B3 — the reflective-fallback INFO (CURG2002): a binding that WAS a compiled-lane candidate (x:DataType in
        // scope) but stayed reflective, naming why. Only when the reflective binding actually emitted (a Converter
        // etc. that the reflective lane also drops is a CURG3001 gap, not a "works-but-reflective" info) AND a reason
        // was recorded — a non-candidate (no x:DataType) and a path-walk failure (not-found → CURG2001 owns it;
        // static/write-only → wouldn't resolve reflectively anyway) both leave reason null and get no noise. The
        // reason already states the cause; no generic remedy clause (it varies per reason and was misleading).
        if (reflectiveEmitted && reason is not null)
            c.Info($"{{Binding}} for '{xm.Name}' stays reflective ({reason}) — it works, but is not the AOT-optimal compiled form.");
    }

    // Emits a typed, reflection-free CompiledBinding when the binding is an x:DataType-rooted, DataContext-relative,
    // compilable path. Returns true when it emitted; false when it declined, with <paramref name="reason"/> set to
    // a human phrase for the CURG2002 info (null when there was no x:DataType in scope — not a candidate at all).
    private static bool TryEmitCompiledBinding(
        Context c, string varExpr, INamedTypeSymbol owner, XamlMember xm, MarkupExtensionNode node, INamedTypeSymbol? dataType, out string? reason)
    {
        if (!TryBuildCompiledBindingExpr(c, node, dataType, selfAnchorType: owner, out var expression, out var deferInstall, out reason))
            return false;

        var install = $"global::Cursorial.UI.Data.BindingOperations.Install({varExpr}, {Global(owner)}.{xm.Name}Property, {expression});";

        // Name- and ancestor-anchored installs defer to the end-of-tree flush: a forward-referenced
        // name registers after this element initializes, and a FindAncestor chain only exists once the
        // tree is fully linked. (Self and Source anchors resolve from the install site and stay inline.)
        if (deferInstall)
            c.DeferredScopeLines.Add(install);
        else
            c.Line(install);

        return true;
    }

    /// <summary>
    /// The descriptor half of the compiled lane (WS-PP3): builds the full
    /// <c>new CompiledBinding&lt;…&gt;(…){…}</c> EXPRESSION — everything except the Install — so
    /// non-install positions (a <c>DataCondition.Binding</c>, armed through
    /// <c>BindingOperations.Watch</c>) share the exact same lane. <paramref name="deferInstall"/>
    /// tells an INSTALLING caller the anchor resolves against end-of-tree state; watch-armed callers
    /// may ignore it (a watch arms at style apply, when the scope is complete).
    /// </summary>
    private static bool TryBuildCompiledBindingExpr(
        Context c, MarkupExtensionNode node, INamedTypeSymbol? dataType, INamedTypeSymbol? selfAnchorType,
        out string? expression, out bool deferInstall, out string? reason)
    {
        expression = null;
        deferInstall = false;
        reason = null;

        // Anchored roots (WS-PP2): the shared parser plus typed anchors make several previously-
        // reflective forms compilable — ElementName (the named element's document type; DataContext
        // drilling through its x:DataType), Source={x:Reference} (the same, by name), Source={x:Static}
        // (the chain's resolved value type), and RelativeSource Self / FindAncestor-with-AncestorType.
        // Exactly one anchor may be present; anything unresolvable stays reflective, accurately named.
        INamedTypeSymbol? anchorRootType = null;
        string? anchorInit = null;
        INamedTypeSymbol? sourceElementDataType = null;

        var anchorCount = (HasNamed(node, "Source") ? 1 : 0) +
                          (HasNamed(node, "ElementName") ? 1 : 0) +
                          (HasNamed(node, "RelativeSource") ? 1 : 0);
        if (anchorCount > 1)
        {
            reason = "it has more than one of Source/ElementName/RelativeSource";
            return false;
        }
        var deferAnchoredInstall = false;
        var anchorUntyped = false;
        if (anchorCount == 1 &&
            !TryResolveAnchoredRoot(c, node, selfAnchorType, out anchorRootType, out anchorInit, out sourceElementDataType,
                                    out deferAnchoredInstall, out reason))
        {
            return false;
        }

        // An anchor whose ROOT TYPE could not be determined is still perfectly expressible (the same
        // inits the reflective lane emits) — and a `(Owner.Property)` first segment needs no root type
        // at all: any UIObject answers GetValue. The walk roots at UIObject; a path that needs real
        // type knowledge declines there instead.
        if (anchorCount == 1 && anchorRootType is null)
            anchorUntyped = true;

        // A PRESENT Converter this position can't lower (a fenced/forward resource, an unresolvable static, a
        // fenced custom extension) must DECLINE the whole compiled lane — installing a CompiledBinding with the
        // converter silently dropped would change conversion semantics. The reflective lane shares ConverterInit
        // and owns the accurate CURG3001 fence. ("" = no Converter named — filtered out of the inits below.)
        var converterInit = ConverterInit(c, node);
        if (converterInit is null)
        {
            reason = "its Converter is not lowerable in this position";
            return false;
        }

        var path = BindingPathOf(node);
        if (string.IsNullOrEmpty(path) || path == ".")
            return false; // a whole-DataContext binding has no compiled leaf — not an actionable info (reason stays null)

        // The shared tokenizer (XamlPathParser) handles member, type-qualified, and INDEXER segments —
        // the last-dot qualifier split is the compiled-lane superset (dotted CLR names allowed). Only a
        // malformed path declines here.
        if (!XamlPathParser.TryTokenize(path!, XamlQualifiedSplit.LastDot, out var tokens))
        {
            reason = "its path is not a member/indexer chain this lane can parse";
            return false;
        }

        if (CanonicalMode(node) is not { } modeName)
        {
            reason = "its binding Mode is not recognized";
            return false;
        }

        // Walk the path against the x:DataType (or a STATIC ROOT), threading the running owner type
        // through the shared segment model. Every member hop must be a readable INSTANCE property/field
        // (a static-named hop can't be `prev.Member`, CS0176) — except a `(Type.Member)` FIRST segment
        // whose member only resolves as a public static directly-declared member (the x:Static rule):
        // that is a STATIC-ROOTED chain, compiled with a RelativeSource-Self anchor so it works with no
        // DataContext at all. A type-qualified instance hop resolves its member ON the qualifier type
        // and lowers as an `as`-cast access; an indexer hop resolves through the shared int/enum/string
        // ladder (XamlPathParser.TryResolveIndexer — the same order the reflective AccessorCache walks).
        // Member hops on UIProperty-registered owners carry the registration FIELD onto their step, so
        // the runtime observes the property system directly instead of probing the registry by name.
        var segments = new List<XamlPathSegment>(tokens.Count);
        var staticRoot = false;
        var walkRoot = anchorUntyped ? null : (ITypeSymbol?)anchorRootType ?? dataType;
        ITypeSymbol? runningType = walkRoot;
        INamedTypeSymbol? castNextTo = null; // set after a DataContext hop on an element-rooted walk

        for (int t = 0; t < tokens.Count; t++)
        {
            var token = tokens[t];
            var segment = new XamlPathSegment { Kind = token.Kind };

            if (token.Kind == XamlPathTokenKind.Indexer)
            {
                if (t == 0 || runningType is null)
                {
                    reason = "an indexer segment has nothing to index";
                    return false;
                }
                if (runningType is { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T })
                {
                    reason = "a path hop accesses a Nullable<T> member";
                    return false;
                }
                if (!XamlPathParser.TryResolveIndexer(runningType, token.Key!, token.KeyWasQuoted,
                                                      out var indexer, out var keyKind, out var typedKey, out var keyExpr))
                {
                    reason = $"no matching indexer for key '[{token.Key}]' on '{runningType.ToDisplayString()}'";
                    return false;
                }

                segment.Member = indexer;
                segment.AccessedOn = runningType as INamedTypeSymbol;
                segment.ValueType = indexer!.Type;
                segment.KeyKind = keyKind;
                segment.Key = typedKey;
                segment.KeyExpression = keyExpr;
                segments.Add(segment);
                runningType = indexer.Type;
                continue;
            }

            // A member accessed ON a Nullable<T> isn't compiled: the typed whole-chain read would NRE and
            // the per-hop `is T? __t` step pattern doesn't parse. Bail to the reflective lane.
            if (runningType is { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T })
            {
                reason = "a path hop accesses a Nullable<T> member";
                return false;
            }

            INamedTypeSymbol accessOn;

            if (token.Kind == XamlPathTokenKind.QualifiedMember)
            {
                if (XamlDataTypeScope.ResolveToken(c.Doc, token.TypeToken!, c.Resolver) is not { } qualifierType)
                {
                    reason = $"a type-qualified segment's type '{token.TypeToken}' does not resolve";
                    return false;
                }

                // ANY registration on the qualifier — attached, wrapper-less, or CLR-wrapped alike —
                // takes the property-system lane: `(Owner.Property)` names the registration, which
                // applies to ANY UIObject receiver (no relatedness, no qualifier cast; the reflective
                // UIPropertyAccessor is receiver-type-blind the same way). Reads go through the typed
                // GetValue with the field itself (AttachedProperty<T> derives StyledProperty<T>, so
                // overload resolution types the chain), and a null walk root falls back to UIObject.
                if (XamlPathParser.FindRegisteredPropertyField(qualifierType, token.Member!) is { } attachedField &&
                    XamlPathParser.UIPropertyRegistrationValueType(attachedField) is { } attachedValue)
                {
                    // The qualifier + registration field fully determine the access — the receiver's
                    // STATIC type contributes nothing (GetValue works on any UIObject). With no
                    // x:DataType at all the walk roots at UIObject itself: the runtime `root is TSource`
                    // check stands in for the type knowledge we don't have, and a non-UIObject
                    // DataContext leaves the binding inert. (The runtime's by-name fallback could bind a
                    // same-named CLR member on a POCO there — the `(Owner.Property)` spelling explicitly
                    // names the property system, so that divergence is the accepted qualified-cast family.)
                    if (runningType is null)
                    {
                        if (c.Resolver.Resolve(XamlSymbolResolver.CursorialUiNamespace, "UIObject", out _) is not { } uiObjectType)
                        {
                            reason = "the UIObject root type does not resolve";
                            return false;
                        }
                        walkRoot = uiObjectType;
                        runningType = uiObjectType;
                    }

                    segment.MemberName = token.Member;
                    segment.Member = attachedField;
                    segment.AccessedOn = qualifierType;
                    segment.ValueType = attachedValue;
                    segment.UIPropertyField = attachedField;
                    segment.UIPropertyOnly = true;
                    segment.IsDirect = XamlPathParser.IsDirectUIPropertyType(attachedField.Type);
                    segments.Add(segment);
                    runningType = attachedValue;
                    continue;
                }

                // FIRST segment only: when the member does not resolve as an instance member of a
                // qualifier related to the data type, try the STATIC interpretation (x:Static rule 1 —
                // public static, directly declared). `(media:Palette.Default).Name` roots the chain at
                // the static value; no DataContext is consulted.
                var instanceViable =
                    t > 0 ||
                    (runningType is not null &&
                     qualifierType.IsReferenceType &&
                     runningType.IsReferenceType &&
                     AreRelatedTypes(runningType, qualifierType) &&
                     XamlDataTypeScope.FindMember(qualifierType, token.Member!) is { IsStatic: false });

                if (!instanceViable)
                {
                    if (t == 0 && anchorInit is null && XamlPathParser.StaticMemberType(qualifierType, token.Member!) is { } staticType)
                    {
                        staticRoot = true;
                        segment.Qualified = true;
                        segment.IsStaticRoot = true;
                        segment.MemberName = token.Member;
                        segment.AccessedOn = qualifierType;
                        segment.ValueType = staticType;
                        segments.Add(segment);
                        runningType = staticType;
                        continue;
                    }

                    reason = runningType is null
                        ? "the walk has no typed root (no x:DataType, or an untypeable anchor), and the first segment is not a static member or registered property"
                        : $"a type-qualified segment's type '{token.TypeToken}' is unrelated to the hop's static type";
                    return false;
                }

                if (!qualifierType.IsReferenceType)
                {
                    reason = "a type-qualified segment's type is not a reference type";
                    return false;
                }

                accessOn = qualifierType;
                segment.Qualified = true;
            }
            else if (castNextTo is { } drillTarget)
            {
                // The hop after a DataContext hop on an element-rooted walk: resolve against the source
                // element's declared x:DataType and emit as a cast-qualified access — the compiled twin
                // of "the runtime binds whatever the DataContext turns out to be".
                castNextTo = null;
                accessOn = drillTarget;
                segment.Qualified = true;
            }
            else
            {
                if (runningType is not INamedTypeSymbol named)
                {
                    reason = runningType is null
                        ? "the walk has no typed root (no x:DataType, or an untypeable anchor), so only a static-, anchor-, or UIProperty-rooted path can compile"
                        : "an intermediate path hop is not a named type";
                    return false;
                }
                accessOn = named;
            }

            if (XamlDataTypeScope.FindMember(accessOn, token.Member!) is not { IsStatic: false } member ||
                !XamlDataTypeScope.IsReadable(member) ||
                XamlDataTypeScope.MemberType(member) is not { } hopType)
            {
                // A wrapper-less registration on the running type itself compiles the same way an
                // attached hop does: through GetValue with the field.
                if (!segment.Qualified &&
                    XamlPathParser.FindRegisteredPropertyField(accessOn, token.Member!) is { } regField &&
                    XamlPathParser.UIPropertyRegistrationValueType(regField) is { } regValue &&
                    DerivesFromUIObjectChain(accessOn))
                {
                    segment.MemberName = token.Member;
                    segment.Member = regField;
                    segment.AccessedOn = accessOn;
                    segment.ValueType = regValue;
                    segment.UIPropertyField = regField;
                    segment.UIPropertyOnly = true;
                    segment.IsDirect = XamlPathParser.IsDirectUIPropertyType(regField.Type);
                    segments.Add(segment);
                    runningType = regValue;
                    continue;
                }

                // A not-found member is the path validator's CURG2001 (don't also raise CURG2002); a
                // qualified miss names itself (the validator skips paren paths, so CURG2001 never fires).
                if (segment.Qualified)
                    reason = $"the type-qualified member '{token.Member}' was not found on '{token.TypeToken}'";
                return false;
            }

            segment.MemberName = token.Member;
            segment.Member = member;
            segment.AccessedOn = accessOn;
            segment.ValueType = hopType;
            segment.UIPropertyField = XamlPathParser.FindRegisteredPropertyField(accessOn, token.Member!);

            // The property SYSTEM is the contract: any styled/attached-registered member reads and writes
            // through GetValue/SetValue even when a CLR wrapper exists — a wrapper is convenience and may
            // coerce, cache, or drift from the store; GetValue cannot. A DirectProperty rides the same
            // lane (its wrapper, if any, is bypassed too), but reads/writes route through the typed no-box
            // GetDirect/SetDirect instead of GetValue — DirectProperty has no typed GetValue overload; the
            // IsDirect flag carries that to emission. The registration's type parameter is the value-type
            // truth the chain continues on.
            if (segment.UIPropertyField is { } styledField &&
                XamlPathParser.UIPropertyRegistrationValueType(styledField) is { } styledValue &&
                DerivesFromUIObjectChain(accessOn))
            {
                segment.UIPropertyOnly = true;
                segment.IsDirect = XamlPathParser.IsDirectUIPropertyType(styledField.Type);
                segment.ValueType = styledValue;
                runningType = styledValue;
                segments.Add(segment);

                if (sourceElementDataType is not null && t + 1 < tokens.Count &&
                    token.Kind == XamlPathTokenKind.Member && token.Member == "DataContext")
                {
                    castNextTo = sourceElementDataType;
                }

                continue;
            }

            segments.Add(segment);
            runningType = hopType;

            // A DataContext hop on an element-rooted walk types the NEXT hop from the source element's
            // declared x:DataType (the object-typed DataContext itself carries no members to walk).
            if (sourceElementDataType is not null && t + 1 < tokens.Count &&
                token.Kind == XamlPathTokenKind.Member && token.Member == "DataContext")
            {
                castNextTo = sourceElementDataType;
            }
        }

        var last = segments.Count - 1;
        var leaf = segments[last];
        var leafWritable = leaf.Kind != XamlPathTokenKind.Indexer &&
                           !leaf.IsStaticRoot &&
                           (leaf.UIPropertyOnly || (leaf.Member is not null && XamlDataTypeScope.IsWritable(leaf.Member)));

        var leafType = leaf.ValueType;
        string data = staticRoot ? "object" : Global(walkRoot!);
        string value = Global(leafType);

        // Getter — a null-safe whole-chain read: `?.` after each reference-typed hop so a null
        // intermediate yields default(leaf), never an NRE (the pinned B188 semantics). Indexer hops use
        // `?[key]` the same way — but a key the collection does not HOLD throws, exactly as the runtime
        // lambda-analysis factory's constant-index steps do: the same opt-in divergence family from the
        // reflective lane's degrade-to-unset. A static-rooted chain starts at the static member itself
        // and ignores the (RelativeSource-Self) root argument entirely.
        var chain = staticRoot
            ? $"{Global(segments[0].AccessedOn!, false)}.{EscapeId(segments[0].MemberName!)}"
            : "__s";
        var conditional = false;

        for (int h = staticRoot ? 1 : 0; h < segments.Count; h++)
        {
            var seg = segments[h];
            var prevIsReference = h == 0 ? walkRoot!.IsReferenceType : segments[h - 1].ValueType.IsReferenceType;

            // A preceding direct hop yields the nullable-lifted T? (its `is Owner ? GetDirect : default`
            // ternary), so THIS hop must chain with `?.` even off a value-typed direct value — `?.` lifts
            // through Nullable<T> where `.` would not compile. (A reference-typed prior hop is already
            // nullable; this only adds the value-typed direct case.)
            var prevNullable = prevIsReference || (h > 0 && segments[h - 1].IsDirect);

            if (seg.Kind == XamlPathTokenKind.Indexer)
            {
                if (prevNullable) conditional = true;
                chain += prevNullable ? $"?[{seg.KeyExpression}]" : $"[{seg.KeyExpression}]";
            }
            else if (seg.IsDirect)
            {
                // A DirectProperty<TOwner, T> read: its only GetValue overload is the untyped one (returns
                // object?), which won't type the Func<TSource, TValue> chain. Route the typed no-box
                // Extensions.GetDirect instead — invoked STATICALLY, because an extension member cannot be
                // null-conditional (`?.GetDirect` is illegal). The `is TOwner __d` pattern does the work a
                // `(chain as TOwner)?.` would: it null-checks AND type-checks, binding the exact invariant
                // TOwner the property demands; a null-or-wrong receiver falls to the default arm (the
                // qualified-hop graceful degrade). The ternary lifts to T?, so the chain stays conditional.
                var fieldRef = $"{Global(seg.UIPropertyField!.ContainingType, false)}.{seg.UIPropertyField.Name}";
                var owner = Global(((INamedTypeSymbol)seg.UIPropertyField.Type).TypeArguments[0], false);
                var nullableValue = Global(seg.ValueType, false);
                if (!nullableValue.EndsWith("?", StringComparison.Ordinal)) nullableValue += "?";
                chain = $"({chain} is {owner} __d{h} ? global::Cursorial.UI.Extensions.GetDirect(__d{h}, {fieldRef}) : default({nullableValue}))";
                conditional = true;
            }
            else if (seg.UIPropertyOnly)
            {
                var fieldRef = $"{Global(seg.UIPropertyField!.ContainingType, false)}.{seg.UIPropertyField.Name}";
                var prevType = h == 0 ? walkRoot! : segments[h - 1].ValueType;

                if (seg.Qualified && seg.Member is not IFieldSymbol)
                {
                    // A CLR-wrapped registered member on a qualifier type: the qualifier cast supplies
                    // the receiver; an incompatible instance degrades through the null-conditional.
                    chain = $"({chain} as {Global(seg.AccessedOn!, false)})?.GetValue({fieldRef})";
                    conditional = true;
                }
                else if (!DerivesFromUIObjectChain(prevType))
                {
                    // The receiver's static type is not a UIObject (an object-typed hop, an untyped
                    // DataContext): GetValue needs one, and `as UIObject` degrades null-gracefully.
                    chain = $"({chain} as global::Cursorial.UI.UIObject)?.GetValue({fieldRef})";
                    conditional = true;
                }
                else
                {
                    var accessor = h == 0 ? "." : (prevNullable ? "?." : ".");
                    if (accessor == "?.") conditional = true;
                    chain += accessor + $"GetValue({fieldRef})";
                }
            }
            else if (seg.Qualified)
            {
                // A qualified hop reads through an `as`-cast: an incompatible runtime instance yields
                // null and the conditional chain reads default(leaf) — the runtime's graceful degrade.
                chain = $"({chain} as {Global(seg.AccessedOn!, false)})?.{EscapeId(seg.MemberName!)}";
                conditional = true;
            }
            else
            {
                var accessor = h == 0 ? "." : (prevNullable ? "?." : ".");
                if (accessor == "?.") conditional = true;
                chain += accessor + EscapeId(seg.MemberName!);
            }
        }

        // A conditional chain can read null for a leaf whose type says it can't — the `?? default(TValue)`
        // null-intermediate arm — so TValue gains a forced `?` (CS8603 in the getter otherwise). The TwoWay
        // setter forgives it back with `__v!` below. Value-typed leaves keep their exact TValue: the `??`
        // arm UNWRAPS the chain's lifted `T?` back to `T`.
        var forcedNullable = conditional && leafType.IsReferenceType && !value.EndsWith("?", StringComparison.Ordinal);
        if (forcedNullable)
            value += "?";

        var getter = conditional ? $"static __s => ({chain}) ?? default({value})" : $"static __s => {chain}";

        // One CompiledPathStep per segment — an object-typed reader for subscription rewiring (the typed
        // Getter does the value reads). Member steps on UIProperty-registered owners CARRY the
        // registration field, so the runtime observes the property system without a name probe; indexer
        // steps use the "Item[]" INPC-convention label; a static root reads the static afresh each rewire.
        var steps = new List<string>(segments.Count);
        for (int h = 0; h < segments.Count; h++)
        {
            var seg = segments[h];

            if (seg.IsStaticRoot)
            {
                steps.Add($"new global::Cursorial.UI.Data.CompiledPathStep(\"{Escape(seg.MemberName!)}\", " +
                          $"static __o => (object?){Global(seg.AccessedOn!, false)}.{EscapeId(seg.MemberName!)})");
            }
            else if (seg.Kind == XamlPathTokenKind.Indexer)
            {
                steps.Add($"new global::Cursorial.UI.Data.CompiledPathStep(\"Item[]\", " +
                          $"static __o => __o is {Global(seg.AccessedOn!, false)} __t ? (object?)__t[{seg.KeyExpression}] : null)");
            }
            else if (seg.UIPropertyOnly)
            {
                var fieldRef = $"{Global(seg.UIPropertyField!.ContainingType, false)}.{seg.UIPropertyField.Name}";
                if (seg.Qualified)
                    steps.Add($"new global::Cursorial.UI.Data.CompiledPathStep(\"{Escape(seg.MemberName!)}\", " +
                              $"static __o => __o is {Global(seg.AccessedOn!, false)} __t ? (object?)__t.GetValue({fieldRef}) : null)" +
                              $" {{ UIProperty = {fieldRef} }}");
                else
                    // Descriptor-only: the runtime materializes through the carried registration
                    // (HostType-guarded property-store read) — no step closure to emit at all.
                    steps.Add($"new global::Cursorial.UI.Data.CompiledPathStep(\"{Escape(seg.MemberName!)}\") {{ UIProperty = {fieldRef} }}");
            }
            else
            {
                var carry = seg.UIPropertyField is { } field
                    ? $" {{ UIProperty = {Global(field.ContainingType, false)}.{field.Name} }}"
                    : "";
                steps.Add($"new global::Cursorial.UI.Data.CompiledPathStep(\"{Escape(seg.MemberName!)}\", " +
                          $"static __o => __o is {Global(seg.AccessedOn!, false)} __t ? (object?)__t.{EscapeId(seg.MemberName!)} : null){carry}");
            }
        }

        // Setter (TwoWay) — only when the leaf is a writable member whose owner is a reference type
        // (writing through a value-typed owner mutates a copy — degrade to OneWay/null, B152). Indexer
        // and static-root leaves never write. Multi-hop is null-guarded (a broken chain is a no-op write).
        //
        // UIProperty leaves write SetValue (LocalValue), NOT SetCurrentValue — deliberately (2026-08-19):
        // a write-back is a DATA push and must be as durable as a ViewModel write, or a style reflow
        // would strip the graft, reclaim the source, and push the reclaimed value back over the user's
        // edit — breaking the TwoWay equality contract on an unrelated lane pulse. The WPF footgun that
        // motivates SetCurrentValue there does not exist here: SetValue never kills a binding entry (A9),
        // so a source whose property carries its own binding keeps producing and reclaims on its next
        // push. SetCurrentValue stays a control-authoring mouth for presentation-state grafts.
        var setter = "null";
        if (leafWritable && leaf.AccessedOn is { IsReferenceType: true })
        {
            var leafPattern = leaf.UIPropertyOnly
                ? (leaf.Qualified ? Global(leaf.AccessedOn, false) : "global::Cursorial.UI.UIObject")
                : leaf.Qualified ? Global(leaf.AccessedOn, false) : "{ }";
            var write = forcedNullable ? "__v!" : "__v";
            var leafFieldRef = leaf.UIPropertyOnly
                ? $"{Global(leaf.UIPropertyField!.ContainingType, false)}.{leaf.UIPropertyField.Name}"
                : null;
            if (segments.Count == 1 && !staticRoot)
            {
                setter = leaf.IsDirect
                    ? $"static (__s, __v) => {{ if (__s is {Global(((INamedTypeSymbol)leaf.UIPropertyField!.Type).TypeArguments[0], false)} __o) global::Cursorial.UI.Extensions.SetDirect(__o, {leafFieldRef}, {write}); }}"
                    : leaf.UIPropertyOnly
                    ? (leaf.Qualified
                        ? $"static (__s, __v) => {{ if (__s is {Global(leaf.AccessedOn, false)} __o) __o.SetValue({leafFieldRef}, {write}); }}"
                        : $"static (__s, __v) => __s.SetValue({leafFieldRef}, {write})")
                    : leaf.Qualified
                        ? $"static (__s, __v) => {{ if (__s is {Global(leaf.AccessedOn, false)} __o) __o.{EscapeId(leaf.MemberName!)} = {write}; }}"
                        : $"static (__s, __v) => __s.{EscapeId(leaf.MemberName!)} = {write}";
            }
            else
            {
                var ownerChain = staticRoot
                    ? $"{Global(segments[0].AccessedOn!, false)}.{EscapeId(segments[0].MemberName!)}"
                    : "__s";
                for (int h = staticRoot ? 1 : 0; h < last; h++)
                {
                    var seg = segments[h];
                    var prevIsReference = h == 0 ? walkRoot!.IsReferenceType : segments[h - 1].ValueType.IsReferenceType;

                    if (seg.Kind == XamlPathTokenKind.Indexer)
                        ownerChain += prevIsReference ? $"?[{seg.KeyExpression}]" : $"[{seg.KeyExpression}]";
                    else if (seg.Qualified)
                        ownerChain = $"({ownerChain} as {Global(seg.AccessedOn!, false)})?.{EscapeId(seg.MemberName!)}";
                    else
                        ownerChain += (h == 0 ? "." : (prevIsReference ? "?." : ".")) + EscapeId(seg.MemberName!);
                }
                setter = leaf.IsDirect
                    ? $"static (__s, __v) => {{ if (({ownerChain}) is {Global(((INamedTypeSymbol)leaf.UIPropertyField!.Type).TypeArguments[0], false)} __o) global::Cursorial.UI.Extensions.SetDirect(__o, {leafFieldRef}, {write}); }}"
                    : leaf.UIPropertyOnly
                    ? $"static (__s, __v) => {{ if (({ownerChain}) is {leafPattern} __o) __o.SetValue({leafFieldRef}, {write}); }}"
                    : $"static (__s, __v) => {{ if (({ownerChain}) is {leafPattern} __o) __o.{EscapeId(leaf.MemberName!)} = {write}; }}";
            }
        }

        var inits = new List<string>(ModeInit(modeName))
                    {
                        converterInit, // non-null — a null (present-but-unlowerable) declined the lane above
                        StringInit("StringFormat", NamedText(node, "StringFormat")),
                        StringInit("FallbackValue", NamedText(node, "FallbackValue")),
                        StringInit("TargetNullValue", NamedText(node, "TargetNullValue"))
                    };

        // A static-rooted chain anchors on the TARGET element (RelativeSource Self): the root argument is
        // ignored by the getter, and the binding works with no DataContext at all. An anchored root
        // carries its own init (ElementName / Source / RelativeSource) — mutually exclusive by the gate.
        if (staticRoot)
            inits.Add("RelativeSource = global::Cursorial.UI.Data.RelativeSource.Self");
        else if (anchorInit is not null)
            inits.Add(anchorInit);

        expression =
            $"new global::Cursorial.UI.Data.CompiledBinding<{data}, {value}>({getter}, {setter}, " +
            $"new global::Cursorial.UI.Data.CompiledPathStep[] {{ {string.Join(", ", steps)} }}, \"{Escape(path!)}\"){Initializers(inits)}";
        deferInstall = deferAnchoredInstall;
        return true;
    }

    /// <summary>
    /// Resolves a single-anchor binding's ROOT type + its emitted anchor init (WS-PP2). ElementName and
    /// Source={x:Reference} type the walk from the named element's document record (and surface its
    /// declared x:DataType for DataContext drilling); Source={x:Static} types it from the chain's value;
    /// RelativeSource Self uses the target property's owner and FindAncestor its resolved AncestorType.
    /// False = stay reflective; <paramref name="reason"/> is set when actionable.
    /// </summary>
    private static bool TryResolveAnchoredRoot(
        Context c, MarkupExtensionNode node, INamedTypeSymbol? selfAnchorType,
        out INamedTypeSymbol? rootType, out string? anchorInit, out INamedTypeSymbol? elementDataType,
        out bool deferInstall, out string? reason)
    {
        rootType = null;
        anchorInit = null;
        elementDataType = null;
        deferInstall = false;
        reason = null;

        // Name anchors compile in ANY scope: the runtime resolves the string against the target's
        // enclosing scope (FindEnclosing — the template's own scope inside a factory, the document
        // scope outside; no chaining), and the STATIC typing below is scoped the same way, so the
        // typed root always matches the element the runtime would find.
        if (NamedText(node, "ElementName") is { Length: > 0 } elementName)
        {
            // An unresolvable/ambiguous name still anchors at RUNTIME through the scope — the init is
            // expressible; only the TYPE is unknown (a UIProperty-rooted path can still compile).
            TryResolveNamedElement(c, elementName, out rootType, out elementDataType);
            anchorInit = $"ElementName = \"{Escape(elementName)}\"";
            deferInstall = true; // the name scope completes at end-of-tree (forward references)
            return true;
        }

        if (node.FindNamed("Source") is { } source)
        {
            if (source.IsNested && source.Nested!.Name is "x:Reference" or "Reference" &&
                FirstPositionalText(source.Nested!) is { Length: > 0 } referenceName)
            {
                // The runtime name-scope anchor gives x:Reference-as-Source the same semantics with no
                // ordering constraint; an unresolvable name leaves only the TYPE unknown.
                TryResolveNamedElement(c, referenceName, out rootType, out elementDataType);
                anchorInit = $"ElementName = \"{Escape(referenceName)}\"";
                deferInstall = true;
                return true;
            }

            if (source.IsNested && source.Nested!.Name is "x:Static" or "Static" &&
                FirstPositionalText(source.Nested!) is { Length: > 0 } staticPath &&
                SplitStaticPath(c, staticPath, out var staticNs, out var staticMembers) &&
                XamlPathParser.TryResolveStaticChain(c.Resolver, staticNs, staticMembers, out var staticExpr, out var staticType))
            {
                if (staticType is not INamedTypeSymbol namedStatic)
                {
                    reason = "the Source={x:Static} value type is not a named type";
                    return false;
                }

                rootType = namedStatic;
                anchorInit = $"Source = {staticExpr}";
                return true;
            }

            // A backward-visible same-document {StaticResource}: the emitter CONSTRUCTED the resource, so
            // its type is known and the local var itself anchors the binding — inline install, the var is
            // in scope and already built by ordering. Forward/fenced/cross-scope keys keep declining.
            if (source.IsNested && source.Nested!.Name is "StaticResource" &&
                FirstPositionalText(source.Nested!) is { Length: > 0 } resourceKey &&
                ResolveVisibleResourceVar(c, $"\"{Escape(resourceKey)}\"", out _, out var resourceType) is { } resourceVar)
            {
                rootType = resourceType; // may be null — the var still anchors, UIProperty paths still compile
                anchorInit = $"Source = {resourceVar}";
                return true;
            }

            // The reflective lane's own source shapes (a custom extension, a fenced form NestedSourceExpr
            // can express) anchor the binding without a static type.
            if (source.IsNested && NestedSourceExpr(c, source.Nested!) is { } sourceExpr)
            {
                anchorInit = $"Source = {sourceExpr}";
                return true;
            }

            reason = "its Source is not expressible in this position";
            return false;
        }

        // RelativeSource: Self roots at the target property's owner when installing (the element IS-A
        // owner for a non-attached target; mismatches degrade through the runtime root check).
        if (node.FindNamed("RelativeSource") is { } relative)
        {
            string? mode = relative.IsNested
                ? FirstPositionalText(relative.Nested!) ?? NamedText(relative.Nested!, "Mode")
                : relative.Text;

            if (mode == "Self")
            {
                // Null in non-install positions (a DataCondition): expressible-but-untypeable — a
                // UIProperty-rooted path still compiles against the UIObject root.
                rootType = selfAnchorType;
                anchorInit = "RelativeSource = global::Cursorial.UI.Data.RelativeSource.Self";
                return true;
            }

            // Inside a control/items-panel template the templated parent's type IS the statically-known
            // TargetType (the same fact {TemplateBinding} lowers against); the anchor itself resolves at
            // template application/attach, exactly as TemplateBinding does — inline install.
            if (mode == "TemplatedParent")
            {
                rootType = c.TemplatedParentType; // null outside a template — UIProperty-rooted paths still compile
                anchorInit = "RelativeSource = global::Cursorial.UI.Data.RelativeSource.TemplatedParent";
                return true;
            }

            if (mode == "FindAncestor" && relative.IsNested &&
                relative.Nested!.FindNamed("AncestorType") is { } ancestorArg)
            {
                var typeName = ancestorArg.IsNested
                    ? (ancestorArg.Nested!.PositionalArguments.Count > 0 ? ancestorArg.Nested.PositionalArguments[0].Text : null)
                    : ancestorArg.Text;

                if (!string.IsNullOrEmpty(typeName) &&
                    XamlDataTypeScope.ResolveToken(c.Doc, typeName!, c.Resolver) is { } ancestorType &&
                    FindAncestorInit(c, relative.Nested!) is { } init)
                {
                    rootType = ancestorType;
                    anchorInit = init;
                    deferInstall = true; // the ancestor chain only exists once the tree is fully linked
                    return true;
                }

                reason = "the FindAncestor AncestorType does not resolve";
                return false;
            }

            reason = "its RelativeSource mode is not compilable (Self and FindAncestor-with-AncestorType are)";
            return false;
        }

        return false; // unreachable under the anchorCount == 1 gate
    }

    /// <summary>
    /// The document element named <paramref name="name"/>: its type symbol and (when declared) its direct
    /// x:DataType. Exactly-one matching: a duplicated name declines rather than guessing which element the
    /// runtime scope would hand back.
    /// </summary>
    private static bool TryResolveNamedElement(
        Context c, string name, out INamedTypeSymbol? type, out INamedTypeSymbol? dataType)
    {
        type = null;
        dataType = null;

        // Scope-CHAIN matching (full lowered/runtime parity): the runtime consults the binding
        // site's own scope first, then — for data-template scopes only — chains outward through the
        // host's enclosing scopes (NameScopeDictionary's lazy chain; PD24). Control-template scopes
        // stay isolated (BD21). The scan mirrors that exactly: nearest scope with a match wins;
        // a duplicate within the WINNING scope is ambiguous (untyped); names in sibling scopes never
        // collide.
        if (c.NameScopeRoots is null)
        {
            var (roots, slices) = BuildNameScopeMap(c.Doc);
            c.NameScopeRoots = roots;
            c.NameScopeSliceInfo = slices;
        }

        var scopes = c.NameScopeRoots;
        var sliceInfo = c.NameScopeSliceInfo!;

        int found = -1;

        for (var searchScope = c.CurrentFactorySliceHead;;)
        {
            for (int o = 0; o < c.Doc.Objects.Length; o++)
            {
                if (scopes[o] != searchScope)
                    continue;

                ref readonly var obj = ref c.Doc.Objects[o];

                for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
                {
                    ref readonly var member = ref c.Doc.Members[m];

                    if (member.Kind == XamlValueKind.Directive &&
                        member.DirectiveKind == (int) XamlDirectiveKind.Name &&
                        c.Doc.Strings[member.ValueIndex] == name)
                    {
                        if (found >= 0)
                            return false; // duplicate within the winning scope — ambiguous, stay untyped

                        found = o;
                    }
                }
            }

            if (found >= 0 || searchScope < 0)
                break;

            if (!sliceInfo.TryGetValue(searchScope, out var info) || !info.Chains)
                break; // an isolated (control-template) scope ends the search — runtime parity

            searchScope = info.Parent;
        }

        if (found < 0 || TypeSymbolOf(c.Doc, c.Doc.Objects[found].TypeId) is not {} symbol)
            return false;

        type = symbol;
        dataType = XamlDataTypeScope.ForObject(c.Doc, in c.Doc.Objects[found], c.Resolver);
        return true;
    }

    /// <summary>
    /// Computes each object's name-scope root: the slice-head object index of the innermost
    /// <see cref="XamlValueKind.Deferred"/> template content containing it, or -1 for the document
    /// scope. Order-independent: every Deferred member seeds a subtree walk, and a nested template's
    /// own walk overwrites its subtree with the inner head (innermost wins), no matter which member
    /// the outer iteration visits first.
    /// </summary>
    private static int[] BuildNameScopeRoots(XamlDocument doc)
        => BuildNameScopeMap(doc).Scopes;

    private static (int[] Scopes, Dictionary<int, (int Parent, bool Chains)> Slices) BuildNameScopeMap(XamlDocument doc)
    {
        var scopes = new int[doc.Objects.Length];
        for (int i = 0; i < scopes.Length; i++)
            scopes[i] = -1;

        for (int o = 0; o < doc.Objects.Length; o++)
        {
            ref readonly var obj = ref doc.Objects[o];
            for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
            {
                ref readonly var member = ref doc.Members[m];
                if (member.Kind == XamlValueKind.Deferred)
                    MarkScope(doc, scopes, member.ValueIndex, member.ValueIndex);
            }
        }

        // Second pass (marks are final): each Deferred slice's ENCLOSING scope is its template
        // OBJECT's scope, and chaining mirrors the runtime — a ControlTemplate's per-apply scope is
        // isolated (BD21 part contract); every other deferred body (DataTemplate &c.) chains to its
        // host's enclosing scopes (PD24 — inline-authoring equivalence).
        var slices = new Dictionary<int, (int Parent, bool Chains)>();
        for (int o = 0; o < doc.Objects.Length; o++)
        {
            ref readonly var obj = ref doc.Objects[o];
            for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
            {
                ref readonly var member = ref doc.Members[m];
                if (member.Kind != XamlValueKind.Deferred)
                    continue;
                var isControlTemplate = TypeSymbolOf(doc, obj.TypeId) is { Name: "ControlTemplate", ContainingNamespace.Name: "Controls" };
                slices[member.ValueIndex] = (scopes[o], !isControlTemplate);
            }
        }

        return (scopes, slices);

        static void MarkScope(XamlDocument doc, int[] scopes, int objectIndex, int head)
        {
            scopes[objectIndex] = head;
            ref readonly var obj = ref doc.Objects[objectIndex];
            for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
            {
                ref readonly var member = ref doc.Members[m];
                switch (member.Kind)
                {
                    case XamlValueKind.Object:
                        MarkScope(doc, scopes, member.ValueIndex, head);
                        break;
                    case XamlValueKind.Items:
                        for (int i = 0; i < member.ItemCount; i++)
                            MarkScope(doc, scopes, member.ValueIndex + i, head);
                        break;
                    case XamlValueKind.Deferred:
                        MarkScope(doc, scopes, member.ValueIndex, member.ValueIndex); // inner template = its own scope
                        break;
                }
            }
        }
    }

