using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;

using Cursorial.UI.Xaml; // frontend node graph (internals via InternalsVisibleTo)

using Microsoft.CodeAnalysis;

namespace Cursorial.UI.Xaml.Generator;

/// <summary>
/// WS-X5 — the full-lowering code-behind generator. Where <see cref="CodeBehindEmitter"/> (X4 v1) emits an
/// <c>InitializeComponent</c> that calls the runtime loader, this emits the object graph as straight-line
/// C# — element construction, property/collection assignment, x:Name fields — so there is NO runtime parse
/// or reflection (the reflection-free / zero-AOT-warning route). Driven by the symbol-backed parse
/// (<see cref="RoslynXamlMetadata"/>) so resolved types/members carry their Roslyn symbols.
/// </summary>
/// <remarks>
/// SPINE scope (this workstream): element construction, registered-<c>UIProperty</c> <c>SetValue</c> and CLR
/// property sets for <c>object</c>/<c>string</c> values, content-property single + collection assignment, and
/// typed <c>x:Name</c> fields + name scope. Value conversion (typed literals), attached properties, events,
/// markup extensions, templates, and resources are later X5 workstreams — a member this spine can't yet
/// lower is emitted as a <c>// TODO X5</c> marker rather than wrong code.
/// </remarks>
internal static class LoweringEmitter
{
    public static LoweringResult? Emit(XamlDocument document, string xamlPath, string xamlRelativePath, XamlSymbolResolver resolver, string? assemblyName = null)
    {
        if (!document.HasObjects)
            return null;

        // The machine-independent identity generated output carries (deterministic builds) and the
        // base that relative ResourceDictionary.Source references resolve against at compile time.
        var sourceUri = CodeBehindEmitter.SourceUriFor(assemblyName, xamlRelativePath, xamlPath);

        var (rootClass, named) = CodeBehindEmitter.Collect(document);
        if (rootClass is { Length: > 0 })
            return EmitCodeBehind(document, sourceUri, resolver, rootClass, named);

        // A no-x:Class <ResourceDictionary> root (a theme / resource document) lowers to a builder method
        // returning the populated dictionary — no InitializeComponent, no runtime parse (WS-X5.4f).
        if (IsResourceDictionaryRoot(document))
            return EmitResourceDictionaryBuilder(document, sourceUri, resolver);

        return null;
    }

    // The X4.6/X5 x:Class path: a partial class with typed x:Name fields + InitializeComponent.
    private static LoweringResult EmitCodeBehind(XamlDocument document, string sourceUri, XamlSymbolResolver resolver, string rootClass,
                                                 IReadOnlyList<CodeBehindEmitter.NamedElement> named)
    {
        int dot = rootClass.LastIndexOf('.');
        string? ns = dot > 0 ? rootClass.Substring(0, dot) : null;
        string className = dot > 0 ? rootClass.Substring(dot + 1) : rootClass;
        string indent = ns is null ? "    " : "        ";

        var ctx = new Context(document, indent, resolver) { SourceUri = sourceUri, HasRootElement = true, HasDocumentScope = named.Count > 0 };

        // Build the InitializeComponent body first (it determines whether a name scope is needed).
        if (named.Count > 0)
        {
            ctx.Line("var __scope = new global::Cursorial.UI.NameScopeDictionary();");
            ctx.Line("global::Cursorial.UI.NameScope.SetNameScope(this, __scope);");
        }
        EmitObject(ctx, objectIndex: 0, varExpr: "this", isRoot: true, hasScope: named.Count > 0, dataType: null);

        // {StaticResource} resolves EAGERLY but only once the whole tree is built + attached and every
        // <X.Resources> is populated — for a self-contained inline document the lexical scope chain IS the
        // live ancestor chain, so el.FindResource (a throw-on-miss live walk, matching the loader) is faithful.
        // Deferring to the end of InitializeComponent is the single point where both invariants hold.
        EmitDeferredStaticResources(ctx);
        EmitDeferredReferences(ctx); // {x:Reference} — same end-of-tree point (the name scope is now complete)

        // Template factory local functions go at the end of InitializeComponent (hoisted — the
        // FuncTemplateContent(...) references emitted above resolve to them).
        foreach (var factory in ctx.Factories)
            ctx.Body.Append(factory);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> Cursorial.UI.Xaml.Generator — full-lowering code-behind (WS-X5)");
        sb.AppendLine($"// source: {sourceUri}");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        if (ns is not null)
        {
            sb.AppendLine($"namespace {ns}");
            sb.AppendLine("{");
        }

        string ci = ns is null ? string.Empty : "    ";
        // The generated half declares the base type from the document's root element — same
        // contract as CodeBehindEmitter (the X4-v1 path), so the two pipelines can't drift and
        // a hand-written base list is optional in BOTH modes.
        var rootBase = CodeBehindEmitter.RootBaseType(document);
        sb.AppendLine($"{ci}partial class {className}{(rootBase is null ? string.Empty : $" : {rootBase}")}");
        sb.AppendLine($"{ci}{{");
        // The array-aware field type (T[] for an <x:Array>) + a value-type-safe `default!` initializer — shared with
        // CodeBehindEmitter (the X4-v1 path) so the two code-behind pipelines can't drift (CS0029/CS0037 otherwise).
        foreach (var ne in named)
            sb.AppendLine($"{ci}    internal {CodeBehindEmitter.FieldType(ne)} {ne.Name} = default!;");
        if (named.Count > 0)
            sb.AppendLine();
        sb.AppendLine($"{ci}    private bool __contentLoaded;");
        sb.AppendLine();
        sb.AppendLine($"{ci}    internal void InitializeComponent()");
        sb.AppendLine($"{ci}    {{");
        sb.AppendLine($"{ci}        if (__contentLoaded) return;");
        sb.AppendLine($"{ci}        __contentLoaded = true;");
        sb.Append(ctx.Body);
        sb.AppendLine($"{ci}    }}");

        if (ctx.UsesConverter)
        {
            // The (hand-written, AOT-clean) converter ladder for typed literals. No reflection except the
            // named-color/TypeDescriptor edges in the ladder itself (tracked for later AOT-hardening).
            sb.AppendLine();
            sb.AppendLine($"{ci}    private static object? __ConvertXamlValue(global::System.Type targetType, string text)");
            sb.AppendLine($"{ci}        => global::Cursorial.UI.Xaml.XamlConverters.For(targetType) is {{ }} __c");
            sb.AppendLine($"{ci}            ? __c.ConvertFromString(text, new global::Cursorial.UI.Xaml.XamlValueContext(");
            sb.AppendLine($"{ci}                global::System.Globalization.CultureInfo.InvariantCulture, null, targetType, null, 0, 0))");
            sb.AppendLine($"{ci}            : text;");
        }

        sb.AppendLine($"{ci}}}");
        if (ns is not null)
            sb.AppendLine("}");

        return new LoweringResult(sb.ToString(), ctx.Unlowered, ctx.Infos, ctx.Errors);
    }

    // ── WS-X5.4f — ResourceDictionary-root lowering (no x:Class) ──────────────────────────────────────

    private static bool IsResourceDictionaryRoot(XamlDocument document)
        => TypeSymbolOf(document, document.Objects[0].TypeId) is { } root && SymbolXamlModel.IsResourceDictionary(root);

    // A no-x:Class <ResourceDictionary> document → an internal static builder returning the populated dictionary,
    // in a per-assembly `partial class GeneratedXamlLoaders`. Hand-written same-assembly code (e.g.
    // CursorialXamlTheme) calls Build<File>() instead of XamlLoader.Shared.Load — no parse, no provider.
    private static LoweringResult EmitResourceDictionaryBuilder(XamlDocument document, string sourceUri, XamlSymbolResolver resolver)
    {
        var ctx = new Context(document, "            ", resolver) { SourceUri = sourceUri }; // namespace(0) → class(4) → method(8) → body(12)
        ctx.Line("var __root = new global::Cursorial.UI.ResourceDictionary();");
        ctx.AmbientScopeStack.Add(new ResourceScope("__root")); // the root dictionary's own lexical scope (same-dict {StaticResource}/BasedOn vars)
        EmitResourceDictionaryBody(ctx, "__root", objectIndex: 0);
        EmitDeferredStaticResources(ctx); // RD entries aren't UIElements ⇒ {StaticResource} bails to TODO, not here
        foreach (var factory in ctx.Factories)
            ctx.Body.Append(factory);

        // The builder method name derives from the document's path WITHIN the source URI
        // (cursorial://assembly/Views/Res.xaml → "Views/Res.xaml" → BuildViewsRes).
        var sourcePath = sourceUri;
        var schemeEnd = sourcePath.IndexOf("://", StringComparison.Ordinal);
        if (schemeEnd >= 0)
        {
            var afterAuthority = sourcePath.IndexOf('/', schemeEnd + 3);
            if (afterAuthority >= 0)
                sourcePath = sourcePath.Substring(afterAuthority + 1);
        }

        string pathPrefix = Path.GetDirectoryName(sourcePath)
                               ?.Replace($"{Path.DirectorySeparatorChar}", "")
                                .Replace($"{Path.AltDirectorySeparatorChar}", "")
                            ?? "";

        var method = "Build" + ToPascalIdentifier(pathPrefix + Path.GetFileNameWithoutExtension(sourcePath));

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> Cursorial.UI.Xaml.Generator — full-lowering resource-dictionary builder (WS-X5.4f)");
        sb.AppendLine($"// source: {sourceUri}");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace Cursorial.UI.Xaml.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    internal static partial class GeneratedXamlLoaders");
        sb.AppendLine("    {");
        sb.AppendLine($"        /// <summary>Builds <c>{sourceUri}</c> into a ResourceDictionary (reflection-free, no runtime parse).</summary>");
        sb.AppendLine($"        internal static global::Cursorial.UI.ResourceDictionary {method}()");
        sb.AppendLine("        {");
        sb.Append(ctx.Body);
        sb.AppendLine("            return __root;");

        if (ctx.UsesConverter)
        {
            // A method-scoped local function (each builder owns its own) — a shared static would duplicate
            // across the per-file partial fragments (CS0111). Declared after the return (hoisted, legal).
            sb.AppendLine("            static object? __ConvertXamlValue(global::System.Type targetType, string text)");
            sb.AppendLine("                => global::Cursorial.UI.Xaml.XamlConverters.For(targetType) is { } __c");
            sb.AppendLine("                    ? __c.ConvertFromString(text, new global::Cursorial.UI.Xaml.XamlValueContext(");
            sb.AppendLine("                        global::System.Globalization.CultureInfo.InvariantCulture, null, targetType, null, 0, 0))");
            sb.AppendLine("                    : text;");
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return new LoweringResult(sb.ToString(), ctx.Unlowered, ctx.Infos, ctx.Errors);
    }

    // Mirrors XamlObjectGraphBuilder.FillResourceDictionaryMembers: Source / MergedDictionaries /
    // ThemeDictionaries / Styles + the implicit keyed-entry content.
    private static void EmitResourceDictionaryBody(Context c, string dictVar, int objectIndex)
    {
        ref readonly var obj = ref c.Doc.Objects[objectIndex];

        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            c.CurrentLineInfo = member.PackedLineInfo;

            if (member.Kind == XamlValueKind.Directive)
                continue; // x:Key on the dict element itself (when nested) is read by the caller

            var xm = member.MemberId >= 0 ? c.Doc.ResolvedMembers[member.MemberId] : null;

            switch (xm?.Name)
            {
                case "Source":
                    if (member.Kind == XamlValueKind.Text)
                        c.Line($"{dictVar}.Source = new global::System.Uri(\"{Escape(ResolveSourceUri(c.Doc.Strings[member.ValueIndex], c.SourceUri))}\", global::System.UriKind.RelativeOrAbsolute);");
                    else
                        c.Todo("<ResourceDictionary.Source> with a non-literal value not yet lowered");
                    break;

                case "MergedDictionaries":
                    foreach (int idx in ResourceItems(c, member))
                    {
                        var sub = c.NextVar();
                        c.Line($"var {sub} = new global::Cursorial.UI.ResourceDictionary();");
                        EmitSubDictionaryBody(c, sub, idx);
                        c.Line($"{dictVar}.MergedDictionaries.Add({sub});");
                    }
                    break;

                case "ThemeDictionaries":
                    foreach (int idx in ResourceItems(c, member))
                    {
                        if (RawKey(c, idx) is not { } variantKey || variantKey.StartsWith("{", System.StringComparison.Ordinal))
                        {
                            c.Todo("ThemeDictionaries entry without a plain-string variant x:Key not yet lowered");
                            continue;
                        }
                        var sub = c.NextVar();
                        c.Line($"var {sub} = new global::Cursorial.UI.ResourceDictionary();");
                        EmitSubDictionaryBody(c, sub, idx);
                        c.Line($"{dictVar}.ThemeDictionaries[\"{Escape(variantKey)}\"] = {sub}; // ThemeVariantKey.Parse");
                    }
                    break;

                case "Styles":
                    foreach (int idx in ResourceItems(c, member))
                    {
                        var styleVar = c.NextVar();
                        EmitObject(c, idx, styleVar, isRoot: false, hasScope: false, dataType: null); // → EmitStyle
                        c.Line($"{dictVar}.Styles ??= new global::Cursorial.UI.Styles();");
                        c.Line($"{dictVar}.Styles.Add({styleVar});");
                    }
                    break;

                default:
                    // The implicit content: keyed entries (or a nested <ResourceDictionary> that folds in).
                    // A resolved NON-object member reaching here (a Text attribute this pass doesn't know)
                    // has no items to enumerate — fence it rather than silently dropping (the
                    // never-silently-drop invariant); the object funnel below matches the loader's.
                    if (xm is not null && member.Kind is not (XamlValueKind.Object or XamlValueKind.Items))
                    {
                        c.Todo($"<ResourceDictionary> member '{xm.Name}' ({member.Kind}) not yet lowered");
                        break;
                    }
                    foreach (int idx in ResourceItems(c, member))
                        EmitDictionaryEntry(c, dictVar, idx);
                    break;
            }
        }
    }

    // Fills a MergedDictionaries / ThemeDictionaries sub-dictionary in its OWN pushed resource scope, so its
    // entries are lexically isolated — a {StaticResource} in the HOST dictionary does not see them
    // (own-entries-only, mirroring the loader's LoadResourceDictionary push/pop), while the sub's own
    // back-references resolve against [sub, …outer]. Without this the sub's entry vars leaked into the host
    // scope's map and a host-level key wrongly resolved to a merged/theme child.
    private static void EmitSubDictionaryBody(Context c, string sub, int objectIndex)
    {
        c.AmbientScopeStack.Add(new ResourceScope(sub));
        EmitResourceDictionaryBody(c, sub, objectIndex);
        c.AmbientScopeStack.RemoveAt(c.AmbientScopeStack.Count - 1);
    }

    // A lexical resource scope: the dictionary's local var, plus the key-expression → entry-var map for its own
    // entries. Pushed innermost-last onto Context.AmbientScopeStack, popped when the scope's subtree is done.
    private sealed class ResourceScope(string dictVar)
    {
        public string DictVar { get; } = dictVar;
        public Dictionary<string, string> KeyExprToVar { get; } = new(System.StringComparer.Ordinal);
    }

    // Resolves a {StaticResource} key expression to a same-document entry's local var, walking the enclosing
    // resource scopes INNERMOST-FIRST (correct lexical shadowing) over the scopes CURRENTLY in effect — an
    // inner-scope entry has already been popped by the time an outer/sibling element is emitted, so it is not
    // visible. Null when no visible scope holds the key. Referencing an entry below the template-factory floor
    // (an outer method's local) forces the factory non-static so it may capture it.
    private static string? ResolveVisibleResourceVar(Context c, string keyExpr)
    {
        for (int i = c.AmbientScopeStack.Count - 1; i >= 0; i--)
            if (c.AmbientScopeStack[i].KeyExprToVar.TryGetValue(keyExpr, out var v))
            {
                if (c.InTemplate) c.CurrentFactoryCaptures = true; // references an enclosing entry var ⇒ factory not static
                return v;
            }
        return null;
    }

    // The visible ambient <X.Resources> dictionary locals as trailing `, __inner, …, __outer` params-args for
    // ResourceScopes.ResolveStatic — innermost-first, above the template-factory floor. "" when none.
    private static string AmbientDictsArgs(Context c)
    {
        if (c.AmbientScopeStack.Count <= c.AmbientScopeFloor)
            return string.Empty;

        var sb = new StringBuilder();
        for (int i = c.AmbientScopeStack.Count - 1; i >= c.AmbientScopeFloor; i--)
            sb.Append(", ").Append(c.AmbientScopeStack[i].DictVar);
        return sb.ToString();
    }

    // An EAGER {StaticResource} whose key is NOT a same-document visible entry var → a runtime
    // ResourceScopes.ResolveStatic call against the enclosing lexical dictionaries + the application tail (the
    // loader's XamlResourceScopeStack.TryResolve, exactly). Returns null (the caller fences) for a key that IS a
    // not-yet-built intra-document entry (a forward/init-only reference the eager build can't reproduce) or one
    // reached inside a template factory (whose full captured chain — outer document dicts — is a later phase).
    private static string? ExternalStaticResolveExpr(Context c, string keyExpr)
    {
        if (DocumentResourceKeys(c).Contains(keyExpr))
            return null; // forward/not-yet-built intra-document — fence, never fail-open
        if (c.InTemplate)
            return null; // in-template external needs the full captured chain (deferred to a later phase)

        return $"global::Cursorial.UI.ResourceScopes.ResolveStatic({keyExpr}{AmbientDictsArgs(c)})";
    }

    private static void EmitDictionaryEntry(Context c, string dictVar, int childIndex)
    {
        if (TypeSymbolOf(c.Doc, c.Doc.Objects[childIndex].TypeId) is { } t && SymbolXamlModel.IsResourceDictionary(t))
        {
            EmitResourceDictionaryBody(c, dictVar, childIndex); // <Foo.Resources><ResourceDictionary>…: fold
            return;
        }

        if (ResourceKeyExpr(c, childIndex) is not { } keyExpr)
        {
            c.Todo("resource entry with no plain/x:Static/x:Type x:Key not yet lowered");
            return;
        }

        // A markup extension in element form as a dictionary entry (resource aliasing:
        // <DynamicResource x:Key="Fg" ResourceKey="OnAccent"/>): the entry value is the extension's
        // standalone value (a folded constant or a DynamicResource carrier), added under its key.
        ref readonly var childRecord = ref c.Doc.Objects[childIndex];
        if (childRecord.HasFlag(ObjectFlags.IsMarkupExtension))
        {
            if (MarkupExtensionEntryExpr(c, in childRecord) is not { } entryExpr)
            {
                c.Todo("element-form markup-extension dictionary entry (only x:Null/x:Type/x:Static and DynamicResource) not yet lowered");
                return;
            }

            c.Line($"{dictVar}.Add({keyExpr}, {entryExpr});");
            return;
        }

        var childVar = c.NextVar();
        EmitObject(c, childIndex, childVar, isRoot: false, hasScope: false, dataType: null);
        c.Line($"{dictVar}.Add({keyExpr}, {childVar});");

        // Track the built entry by its lowered KEY EXPRESSION in the CURRENT (innermost) scope, so a
        // same-dictionary {StaticResource key} — a string, or a nested {x:Type}/{x:Static} (control themes;
        // Style.BasedOn) — resolves to this var, and an outer/sibling scope does NOT see it (lexical shadowing).
        if (c.AmbientScopeStack.Count > 0)
            c.AmbientScopeStack[c.AmbientScopeStack.Count - 1].KeyExprToVar[keyExpr] = childVar;
    }

    // The object indices of a member's value run (Items → each; Object → the one), else empty.
    private static IEnumerable<int> ResourceItems(Context c, MemberRecord member)
    {
        if (member.Kind == XamlValueKind.Items)
        {
            int idx = member.ValueIndex;
            for (int i = 0; i < member.ItemCount; i++)
            {
                yield return idx;
                idx += c.Doc.Objects[idx].SubtreeLength;
            }
        }
        else if (member.Kind == XamlValueKind.Object)
        {
            yield return member.ValueIndex;
        }
    }

    // The raw x:Key directive string on an object, or null.
    private static string? RawKey(Context c, int objectIndex)
    {
        ref readonly var obj = ref c.Doc.Objects[objectIndex];
        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            if (member.Kind == XamlValueKind.Directive && member.DirectiveKind == (int) XamlDirectiveKind.Key)
                return c.Doc.Strings[member.ValueIndex];
        }
        return null;
    }

    // The C# key expression for a dictionary entry's x:Key: a string literal, an {x:Static} global:: reference,
    // or a {x:Type} typeof(...). Null when there's no key or an unsupported extension key.
    private static string? ResourceKeyExpr(Context c, int objectIndex)
    {
        if (RawKey(c, objectIndex) is not { } raw)
            return ImplicitResourceKeyExpr(c, objectIndex); // no x:Key → an implicit Style/DataTemplate key, or null

        if (!raw.StartsWith("{", System.StringComparison.Ordinal))
            return $"\"{Escape(raw)}\"";

        // {x:Static Type.Member} → the resolved static reference (the actual key object, not a string).
        if (TryExtractIntrinsic(raw, "x:Static", out var staticPath))
            return ResolveStaticPath(c, staticPath);

        // {x:Type T} → typeof(global::T).
        if (TryExtractIntrinsic(raw, "x:Type", out var typeToken) &&
            XamlDataTypeScope.ResolveToken(c.Doc, typeToken, c.Resolver) is { } typeSym)
            return $"typeof({Global(typeSym)})";

        return null;
    }

    // The implicit dictionary key for an unkeyed entry (matrix X137/X138 — the loader's TryGetImplicitKey):
    // a Style with a TargetType keys by its type-selector form "Style:<raw target-type text>" (the RAW
    // attribute text, so the key matches the loader's byte-for-byte — the styling engine matches on Selector,
    // the key is only the dictionary identity); a DataTemplate with a DataType keys by
    // new DataTemplateKey(typeof(DataType)). Null when the entry has neither an x:Key nor an implicit key.
    private static string? ImplicitResourceKeyExpr(Context c, int objectIndex)
    {
        ref readonly var obj = ref c.Doc.Objects[objectIndex];
        var type = TypeSymbolOf(c.Doc, obj.TypeId);

        if (IsStyleType(type) && RawTextMember(c, in obj, "TargetType") is { } targetText)
            return $"\"Style:{Escape(targetText)}\"";

        if (IsDataTemplateSymbol(type) && DataTemplateDataType(c, in obj) is { } dataType)
            return $"new global::Cursorial.UI.DataTemplateKey(typeof({Global(dataType)}))";

        return null;
    }

    // The raw text of a Text-valued member by name (mirrors the loader's TryGetStyleStringMember Kind==Text
    // guard — a non-Text form is not a string member), or null.
    private static string? RawTextMember(Context c, in ObjectRecord obj, string memberName)
    {
        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            if (member.Kind != XamlValueKind.Text || member.MemberId < 0)
                continue;
            if (c.Doc.ResolvedMembers[member.MemberId]?.Name == memberName)
                return c.Doc.Strings[member.ValueIndex];
        }
        return null;
    }

    // The DataTemplate's DataType as a resolved symbol (mirrors the loader's TryGetDataType): the x:DataType
    // directive, or a CLR DataType member (a folded Type constant or a Text token), resolved via the document
    // xmlns. Null when absent / unresolvable.
    private static INamedTypeSymbol? DataTemplateDataType(Context c, in ObjectRecord obj)
    {
        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];

            if (member is { Kind: XamlValueKind.Directive, DirectiveKind: (int) XamlDirectiveKind.DataType })
                return XamlDataTypeScope.ResolveToken(c.Doc, c.Doc.Strings[member.ValueIndex], c.Resolver);

            if (member.MemberId >= 0 && c.Doc.ResolvedMembers[member.MemberId]?.Name == "DataType")
            {
                if (member.Kind == XamlValueKind.Folded && c.Doc.Constants[member.ValueIndex] is System.Type)
                    return null; // a folded System.Type constant isn't a Roslyn symbol here — fall through to fence
                if (member.Kind == XamlValueKind.Text)
                    return XamlDataTypeScope.ResolveToken(c.Doc, c.Doc.Strings[member.ValueIndex], c.Resolver);
            }
        }
        return null;
    }

    // True when the symbol is DataTemplate or derives from it (the loader's typeof(DataTemplate).IsAssignableFrom
    // — HierarchicalDataTemplate etc. also key by DataType).
    private static bool IsDataTemplateSymbol(INamedTypeSymbol? type)
    {
        for (var t = type; t is not null; t = t.BaseType)
            if (t is { Name: "DataTemplate", ContainingNamespace.Name: "Controls" })
                return true;
        return false;
    }

    // Pulls the argument out of a single-intrinsic markup-extension string "{name arg}" (e.g. "{x:Static A.B}").
    private static bool TryExtractIntrinsic(string raw, string name, out string arg)
    {
        arg = string.Empty;
        var prefix = "{" + name + " ";
        if (!raw.StartsWith(prefix, System.StringComparison.Ordinal) || !raw.EndsWith("}", System.StringComparison.Ordinal))
            return false;
        arg = raw.Substring(prefix.Length, raw.Length - prefix.Length - 1).Trim();
        return arg.Length > 0;
    }

    private static string ToPascalIdentifier(string name)
    {
        var sb = new StringBuilder(name.Length);
        bool upper = true;
        foreach (var ch in name)
        {
            if (char.IsLetterOrDigit(ch)) { sb.Append(upper ? char.ToUpperInvariant(ch) : ch); upper = false; }
            else upper = true;
        }
        if (sb.Length == 0 || char.IsDigit(sb[0])) sb.Insert(0, '_');
        return sb.ToString();
    }

    // ── WS-X5.4g — Style + Setter lowering ───────────────────────────────────────────────────────────

    private static bool IsStyleType(INamedTypeSymbol? type)
        => type is { Name: "Style", ContainingNamespace.Name: "UI", ContainingNamespace.ContainingNamespace.Name: "Cursorial" };

    // A <Style>: new Style(selector) { BasedOn, Key } + Setters.Add(new Setter(prop, value)). The selector is a
    // ctor arg (TargetType → Selectors.OfType; an explicit Selector="" string is baked in a later sub-workstream).
    // TargetType/Selector members are consumed here (mirroring the loader's activation), not the member loop.
    private static void EmitStyle(Context c, int objectIndex, string varExpr)
    {
        ref readonly var obj = ref c.Doc.Objects[objectIndex];

        INamedTypeSymbol? targetType = null;
        string? selectorText = null;
        string? basedOnExpr = null;
        string? keyExpr = null;
        string? requiresExpr = null;
        int settersMember = -1;
        int childrenMember = -1;
        int whenMember = -1;

        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];

            if (member.Kind == XamlValueKind.Directive)
            {
                if (member.DirectiveKind == (int) XamlDirectiveKind.Key)
                {
                    // Style.Key is string? (diagnostics/placement identity). LOADER PARITY: only a literal
                    // key transfers — the loader leaves Key null for extension-form keys (x:Key="{x:Static …}"),
                    // and the structural-parity gate compares Key, so baking the resolved static here would
                    // make the lowered lane observably differ.
                    var k = c.Doc.Strings[member.ValueIndex];
                    keyExpr = k.StartsWith("{", System.StringComparison.Ordinal) ? null : $"\"{Escape(k)}\""; // Style.Key is string?
                }
                continue;
            }

            var xm = member.MemberId >= 0 ? c.Doc.ResolvedMembers[member.MemberId] : null;
            switch (xm?.Name)
            {
                case "TargetType" when member.Kind == XamlValueKind.Text:
                    targetType = XamlDataTypeScope.ResolveToken(c.Doc, c.Doc.Strings[member.ValueIndex], c.Resolver);
                    break;
                case "Selector" when member.Kind == XamlValueKind.Text:
                    selectorText = c.Doc.Strings[member.ValueIndex];
                    break;
                case "TargetType":
                case "Selector":
                    break; // non-Text forms: the loader's TryGetStyleStringMember has the identical Kind==Text guard — ignored in both lanes
                case "BasedOn":
                    basedOnExpr = BasedOnExpr(c, in member);
                    if (basedOnExpr is null)
                    {
                        // Fail CLOSED (the RequiresCapabilities precedent): emitting the style WITHOUT its
                        // base silently drops every inherited setter — the one outcome neither lane may
                        // have. Reached for a forward/intra-document base (the inline probe can't defer an
                        // init-only property), an anchorless document (a ResourceDictionary builder), or an
                        // unsupported value form.
                        DropStyle(c, varExpr, "<Style> BasedOn is not lowerable here (a forward/intra-document base, or no root element to anchor the live-chain probe) — style dropped");
                        return;
                    }
                    break;
                case "Setters":
                    settersMember = m;
                    break;
                case "Children":
                    childrenMember = m;
                    break;
                case "When":
                    whenMember = m;
                    break;
                case "RequiresCapabilities" when member.Kind == XamlValueKind.Text:
                    requiresExpr = BakeCapabilities(c, c.Doc.Strings[member.ValueIndex]);
                    if (requiresExpr is null)
                    {
                        // Fail CLOSED like the unbaked-selector path: emitting the style WITHOUT its gate
                        // would turn a tier-conditional rule into an unconditional one (the unsafe
                        // degradation direction — the occlusion-everywhere failure class).
                        DropStyle(c, varExpr, $"<Style> RequiresCapabilities \"{Escape(c.Doc.Strings[member.ValueIndex])}\" has an unknown member");
                        return;
                    }
                    break;
                case "RequiresCapabilities" when member.Kind == XamlValueKind.Folded:
                    // A parse-folded {x:Static} constant (enum members are consts) → the typed cast.
                    requiresExpr = BakeFoldedCapabilities(c, c.Doc.Constants[member.ValueIndex]);
                    if (requiresExpr is null)
                    {
                        DropStyle(c, varExpr, "<Style> RequiresCapabilities folded to a value outside StyleCapabilities");
                        return;
                    }
                    break;
                case "RequiresCapabilities" when member.Kind == XamlValueKind.Extension &&
                                                 c.Doc.Extensions[member.ValueIndex] is { Kind: ExtensionKind.Static, PayloadIsParsedExtension: false }:
                    // An unfolded {x:Static Type.Member} (e.g. a static readonly): emit the member-access
                    // REFERENCE — no generate-time evaluation; the C# compiler resolves it (and constant-
                    // folds a const). Type resolution mirrors the resource-key x:Static path.
                    requiresExpr = ResolveStaticPath(c, c.Doc.Strings[c.Doc.Extensions[member.ValueIndex].Payload]);
                    if (requiresExpr is null)
                    {
                        DropStyle(c, varExpr, "<Style> RequiresCapabilities {x:Static} target could not be resolved");
                        return;
                    }
                    break;
                case "RequiresCapabilities":
                    // Any other form (a non-Static extension, a property element with a live object) —
                    // fail closed rather than silently dropping the capability gate.
                    DropStyle(c, varExpr, "<Style> RequiresCapabilities uses a form not yet baked");
                    return;
                default:
                    if (xm is not null)
                    {
                        // A future XAML-authorable Style member (an Enter/Exit action collection, say) must
                        // fence, never silently drop — the style would apply with different behavior than
                        // authored. Unknown-name members surface the frontend's own diagnostics.
                        DropStyle(c, varExpr, $"<Style> member '{xm.Name}' not yet lowered — style dropped");
                        return;
                    }
                    break;
            }
        }

        // The selector: an explicit Selector="…" is baked (it wins; a co-present TargetType is only the
        // Setter-property resolution hint); else TargetType → an exact-type selector; else selector-less.
        string ctor;
        if (selectorText is { } st)
        {
            if (BakeSelector(c, st) is not { } sel)
            {
                DropStyle(c, varExpr, $"<Style> selector \"{Escape(st)}\" uses a construct not yet baked");
                return;
            }
            ctor = $"new global::Cursorial.UI.Style({sel})";
        }
        else if (targetType is { } tt)
        {
            ctor = $"new global::Cursorial.UI.Style(global::Cursorial.UI.Selectors.OfType(null, typeof({Global(tt)})))";
        }
        else
        {
            ctor = "new global::Cursorial.UI.Style()"; // selector-less (an explicit element Style)
        }

        // <Style.When> — the DataCondition conjunction that gates the whole style (the DataTrigger
        // equivalent). Buffered BEFORE the ctor line so one unlowerable condition drops the WHOLE style
        // (fail closed): a style missing one of its When conditions applies more broadly than authored —
        // the fail-open direction, inconsistent with the RequiresCapabilities/BasedOn discipline.
        StringBuilder? whenBuf = null;
        if (whenMember >= 0)
        {
            whenBuf = new StringBuilder();
            var savedBuffer = c.SwapBuffer(whenBuf);
            // Snapshot the deferred-work lists: a condition subtree can record end-of-scope work
            // ({x:Reference}, a deferred {StaticResource}, a Source={x:Reference} install) whose target
            // LOCAL lives in whenBuf. If we drop the style, whenBuf is discarded — so those records must
            // roll back too, else the document-end flush emits a reference to a never-declared local (CS0103).
            var savedRefs = c.References.Count;
            var savedStatics = c.StaticResources.Count;
            var savedScopeLines = c.DeferredScopeLines.Count;

            var conditionsOk = true;
            foreach (int idx in ResourceItems(c, c.Doc.Members[whenMember]))
                conditionsOk &= EmitDataCondition(c, varExpr, idx);
            c.SwapBuffer(savedBuffer);

            if (!conditionsOk)
            {
                Truncate(c.References, savedRefs);
                Truncate(c.StaticResources, savedStatics);
                Truncate(c.DeferredScopeLines, savedScopeLines);
                // The specific condition Todo was recorded (its marker was buffered away); this marker
                // states the consequence at the style site.
                DropStyle(c, varExpr, "<Style> dropped: a <Style.When> condition is not lowerable (the conditions gate the whole style)");
                return;
            }
        }

        var inits = new List<string>();
        if (basedOnExpr is not null) inits.Add($"BasedOn = {basedOnExpr}");
        if (keyExpr is not null) inits.Add($"Key = {keyExpr}");
        if (requiresExpr is not null) inits.Add($"RequiresCapabilities = {requiresExpr}");
        c.Line($"var {varExpr} = {ctor}{Initializers(inits)};");

        if (whenBuf is not null)
            c.Flush(whenBuf); // condition locals precede their When.Add within the buffer; all follow the ctor here

        if (settersMember >= 0)
            foreach (int idx in ResourceItems(c, c.Doc.Members[settersMember]))
                EmitSetter(c, varExpr, idx, targetType);

        // Nested <Style.Children> (^-rooted rules): each builds via EmitObject → EmitStyle and is added.
        if (childrenMember >= 0)
            foreach (int idx in ResourceItems(c, c.Doc.Members[childrenMember]))
            {
                var childVar = c.NextVar();
                EmitObject(c, idx, childVar, isRoot: false, hasScope: false, dataType: null);
                c.Line($"{varExpr}.Children.Add({childVar});");
            }
    }

    // Bakes a RequiresCapabilities attribute ("NoColor" / "NoColor, Motion") into a StyleCapabilities
    // flags expression — names case-insensitive (XAML enum parity); an unknown member returns null (→ TODO
    // diagnostic at the call site, mirroring the unbaked-selector path). The member names and bit coverage
    // derive from the COMPILATION's StyleCapabilities symbol, so a future flag bakes without touching the
    // generator; the hardcoded fallback only serves a resolver miss.
    private static string? BakeCapabilities(Context c, string text)
    {
        var (names, allBits) = CapabilityMembers(c);

        // Loader parity: a bare integral value is legal XAML for an enum (X90/X92) — bake the cast when
        // the bits are covered by the defined members (the same rule the runtime converter applies).
        if (long.TryParse(text, System.Globalization.NumberStyles.Integer, System.Globalization.CultureInfo.InvariantCulture, out long numeric))
        {
            return numeric != 0 && (numeric & ~allBits) == 0
                       ? $"(global::Cursorial.UI.StyleCapabilities){numeric}"
                       : null;
        }

        var terms = new List<string>();

        foreach (var raw in text.Split(','))
        {
            var name = raw.Trim();
            string? match = null;

            foreach (var candidate in names)
            {
                if (string.Equals(candidate, name, System.StringComparison.OrdinalIgnoreCase))
                {
                    match = candidate;
                    break;
                }
            }

            if (match is null)
                return null;

            terms.Add($"global::Cursorial.UI.StyleCapabilities.{match}");
        }

        return terms.Count == 0 ? null : string.Join(" | ", terms);
    }

    // A parse-folded {x:Static}: the frontend folds to a XamlStaticReference PLACEHOLDER carrying the
    // member path — bake the member-access REFERENCE and let the C# compiler resolve it (and constant-fold
    // a const; reading a static field is neither parsing nor reflection). A genuinely numeric constant
    // bakes as the typed cast under the coverage rule.
    private static string? BakeFoldedCapabilities(Context c, object? constant)
    {
        if (constant is XamlStaticReference staticRef)
            return ResolveStaticPath(c, staticRef.MemberPath);

        if (constant is null)
            return null;

        long bits;

        try
        {
            bits = System.Convert.ToInt64(constant, System.Globalization.CultureInfo.InvariantCulture);
        }
        catch (System.Exception)
        {
            return null;
        }

        var (_, allBits) = CapabilityMembers(c);
        return bits != 0 && (bits & ~allBits) == 0
                   ? $"(global::Cursorial.UI.StyleCapabilities){bits}"
                   : null;
    }

    /// <summary>The StyleCapabilities member names + folded bit mask, resolved from the referenced
    /// compilation (a future flag bakes automatically); the literal fallback covers a resolver miss.</summary>
    private static (IReadOnlyList<string> Names, long AllBits) CapabilityMembers(Context c)
    {
        if (c.Resolver.Resolve(XamlSymbolResolver.CursorialUiNamespace, "StyleCapabilities", out _) is { } symbol)
        {
            var names = new List<string>();
            long bits = 0;

            foreach (var member in symbol.GetMembers())
            {
                if (member is IFieldSymbol { HasConstantValue: true } field)
                {
                    names.Add(field.Name);

                    try
                    {
                        bits |= System.Convert.ToInt64(field.ConstantValue, System.Globalization.CultureInfo.InvariantCulture);
                    }
                    catch (System.Exception)
                    {
                        // an exotic underlying value — leave it out of the coverage mask
                    }
                }
            }

            if (names.Count > 0)
                return (names, bits);
        }

        return (FallbackCapabilityNames, 0xFFF);
    }

    private static readonly string[] FallbackCapabilityNames =
    [
        "None", "Truecolor", "Ansi256", "Ansi16", "NoColor", "Motion", "KittyKeyboard",
        "Images", "ImageClipping", "ImageOcclusion", "NerdFont", "Emoji", "Unicode",
    ];

    // A <Setter Property="P" Value="V"/> → styleVar.Setters.Add(new Setter(Owner.PProperty, value)). A Text value
    // is converted to the property's value type via the converter ladder — the reflection frontend folds a
    // context-free converter at parse (so the loaded Setter holds the typed value; e.g. GlyphSetCarrier), and we
    // match by converting at Build() runtime, so StyleSetterConverter passes the typed value through at Seal rather
    // than choking on a raw string its ladder can't handle. {DynamicResource}→ResourceReference; a same-dictionary
    // {StaticResource}→the built entry's var. The Value is resolved AFTER the loop, once the property's value type
    // is known (member order isn't guaranteed).
    private static void EmitSetter(Context c, string styleVar, int setterIndex, INamedTypeSymbol? targetType)
    {
        ref readonly var setter = ref c.Doc.Objects[setterIndex];
        c.CurrentLineInfo = setter.PackedLineInfo;

        string? propExpr = null;
        ITypeSymbol? propValueType = null;
        int valueMember = -1;

        for (int m = setter.MemberStart; m < setter.MemberStart + setter.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            if (member.Kind == XamlValueKind.Directive)
                continue;

            var xm = member.MemberId >= 0 ? c.Doc.ResolvedMembers[member.MemberId] : null;
            if (xm is null)
                continue;

            if (xm.Name == "Value")
            {
                valueMember = m; // resolved after the loop, once the property's value type is known
                continue;
            }

            // The Property member: its Text value is the property name — for an attached/prefixed setter it's the
            // qualified "Owner.Prop" (e.g. "ToggleGlyph.Glyphs", "input:AccessKeyManager.ShowUnderline"), so the
            // <Name>Property field name is the segment after the last '.'. The owner is xm.Property (the parse-
            // resolved attached owner) or, for a simple name, resolved against the Style's TargetType.
            if (member.Kind == XamlValueKind.Text)
            {
                var name = c.Doc.Strings[member.ValueIndex];
                var propName = name.Substring(name.LastIndexOf('.') + 1);
                var owner = xm.Property as INamedTypeSymbol
                            ?? (targetType is { } tt ? SymbolXamlModel.FindRegisteredPropertyOwner(tt, propName) : null);
                if (owner is not null)
                {
                    propExpr = $"{Global(owner)}.{propName}Property";
                    propValueType = ValueTypeSymbol(xm.ValueType); // the Setter value's conversion target
                }
            }
        }

        if (propExpr is null)
        {
            c.Todo("Setter with an unresolved Property not yet lowered");
            return;
        }

        var valueExpr = "global::Cursorial.UI.UIProperty.UnsetValue"; // valueless unless a Value member is present
        if (valueMember >= 0)
        {
            var value = c.Doc.Members[valueMember];

            // Element-form Setter.Value extension (<Setter Property="…"><DynamicResource …/></Setter>): unwrap
            // the synthetic markup-extension object to its value slot so it lowers exactly as the curly form.
            if (value.Kind == XamlValueKind.Object && c.Doc.Objects[value.ValueIndex].HasFlag(ObjectFlags.IsMarkupExtension))
                value = ExtensionValueMember(c, in c.Doc.Objects[value.ValueIndex]);

            if (value.Kind == XamlValueKind.Object)
            {
                // An inline object Setter.Value — e.g. <Setter Property="ItemsPanel"><ItemsPanelTemplate>…</…>.
                // Build it into a local and use that var (the reflective loader builds it the same way; a
                // {StaticResource}-keyed value takes the same-dict var path via SetterValueExpr instead). The Style's
                // TargetType is the templated-parent type so a {TemplateBinding} inside an inline template resolves
                // ({Binding RelativeSource=TemplatedParent} — what VirtualizingItemsPanelTemplate uses — resolves at
                // runtime regardless).
                var v = c.NextVar();
                var savedTpt = c.TemplatedParentType;
                c.TemplatedParentType = targetType;
                EmitObject(c, value.ValueIndex, v, isRoot: false, hasScope: false, dataType: null);
                c.TemplatedParentType = savedTpt;
                valueExpr = v;
            }
            else if (SetterValueExpr(c, in value, propValueType) is { } v)
                valueExpr = v;
            else
            {
                c.Todo("Setter Value (only literal / {x:Static} / {x:Null} / {DynamicResource} / same-dict {StaticResource} / inline object supported)");
                return;
            }
        }

        c.Line($"{styleVar}.Setters.Add(new global::Cursorial.UI.Setter({propExpr}, {valueExpr}));");
    }

    // A <DataCondition> inside <Style.When> → styleVar.When.Add(new DataCondition { Binding = <descriptor>,
    // Value = <v>, Negate = <b> }). Binding is a {Binding} DESCRIPTOR (ReflectiveBindingExpr — the object, not a
    // live install); Value is a typed element (<x:Boolean>…</> → an object local), a folded {x:Null}, or a literal;
    // A style the lowering must DROP (fail closed) still declares its pre-allocated var as an EMPTY,
    // selector-less placeholder: callers reference the var unconditionally (entry .Add / Styles.Add), and a
    // zero-setter style emits zero compiled rules — inert in every channel, exactly as absent would behave
    // except the key exists. The // TODO + CURG3001 mark the gap; behavior never ships half-lowered.
    private static void DropStyle(Context c, string varExpr, string message)
    {
        c.Todo(message);
        c.Line($"var {varExpr} = new global::Cursorial.UI.Style();");
    }

    // Negate is a bool literal. Only the equality form is XAML-expressible (a predicate needs a Func — code-only).
    // Returns FALSE when the condition isn't lowerable (a specific // TODO was emitted) — the caller drops the
    // whole style, never shipping it partially gated.
    private static bool EmitDataCondition(Context c, string styleVar, int objectIndex)
    {
        ref readonly var obj = ref c.Doc.Objects[objectIndex];
        c.CurrentLineInfo = obj.PackedLineInfo;

        int bindingMember = -1, valueMember = -1, negateMember = -1;
        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            if (member.Kind == XamlValueKind.Directive)
                continue;

            switch ((member.MemberId >= 0 ? c.Doc.ResolvedMembers[member.MemberId] : null)?.Name)
            {
                case "Binding": bindingMember = m; break;
                case "Value": valueMember = m; break;
                case "Negate": negateMember = m; break;
            }
        }

        // The Binding descriptor resolves FIRST — a Binding-less / non-{Binding} condition is a hard gap (emit
        // nothing but a // TODO, never a partial DataCondition), and resolving it before any Value <x:Boolean>…
        // object is emitted means the // TODO path leaves no dangling local behind.
        string? bindingExpr = null;
        if (bindingMember >= 0)
        {
            ref readonly var bm = ref c.Doc.Members[bindingMember];
            if (bm.Kind == XamlValueKind.Extension &&
                c.Doc.ParsedExtensions[c.Doc.Extensions[bm.ValueIndex].Payload] is { } node)
                bindingExpr = ReflectiveBindingExpr(c, node, "in a DataCondition");
        }
        if (bindingExpr is null)
        {
            c.Todo("DataCondition without a lowerable {Binding} descriptor");
            return false;
        }

        // A PRESENT Value/Negate that can't be lowered is a // TODO (never silently dropped — that would flip the
        // condition's runtime verdict vs the loader). An absent member is fine (Value defaults null, Negate false).
        string? valueExpr = null;
        if (valueMember >= 0)
        {
            valueExpr = DataConditionValueExpr(c, in c.Doc.Members[valueMember]);
            if (valueExpr is null)
            {
                c.Todo("DataCondition Value form not lowerable (literal / <x:Boolean>… / {x:Null} / {x:Static} / {StaticResource} supported)");
                return false;
            }
        }

        string? negateExpr = null;
        if (negateMember >= 0)
        {
            negateExpr = BoolLiteralExpr(c, in c.Doc.Members[negateMember]);
            if (negateExpr is null)
            {
                c.Todo("DataCondition Negate must be a boolean literal");
                return false;
            }
        }

        var inits = new List<string> { $"Binding = {bindingExpr}" };
        if (valueExpr is not null) inits.Add($"Value = {valueExpr}");
        if (negateExpr is not null) inits.Add($"Negate = {negateExpr}");

        c.Line($"{styleVar}.When.Add(new global::Cursorial.UI.DataCondition{Initializers(inits)});");
        return true;
    }

    // A DataCondition.Value (an object-typed slot): a typed element (<x:Boolean>false</x:Boolean> → an emitted
    // object local), a folded {x:Null} (→ null) / {x:Static}, a same-dictionary {StaticResource} resolved eagerly
    // (matching the loader's AttachStaticResource onto the object slot), or a literal string kept verbatim (object
    // slot, no conversion). Null ⇒ the caller emits a // TODO (a {DynamicResource} — which the loader REJECTS on a
    // non-styled slot — or any other unlowerable form).
    private static string? DataConditionValueExpr(Context c, in MemberRecord member) => member.Kind switch
    {
        XamlValueKind.Object => EmitObjectToLocal(c, member.ValueIndex),
        XamlValueKind.Folded => FoldedValueExpr(c, c.Doc.Constants[member.ValueIndex]),
        XamlValueKind.Text => $"\"{Escape(c.Doc.Strings[member.ValueIndex])}\"",
        XamlValueKind.Extension when c.Doc.Extensions[member.ValueIndex].Kind == ExtensionKind.StaticResource
            => ResourceValueExpr(c, in c.Doc.Extensions[member.ValueIndex]),
        _ => null,
    };

    // Emits an object subtree into a fresh local and returns its var (for an inline <x:Boolean>/<x:Int32>/… Value).
    private static string EmitObjectToLocal(Context c, int objectIndex)
    {
        var v = c.NextVar();
        EmitObject(c, objectIndex, v, isRoot: false, hasScope: false, dataType: null);
        return v;
    }

    // A bool member (DataCondition.Negate) as a C# literal: a "True"/"False" text, or a folded bool constant.
    private static string? BoolLiteralExpr(Context c, in MemberRecord member) => member.Kind switch
    {
        XamlValueKind.Text => bool.TryParse(c.Doc.Strings[member.ValueIndex], out var b) ? (b ? "true" : "false") : null,
        XamlValueKind.Folded when c.Doc.Constants[member.ValueIndex] is bool b => b ? "true" : "false",
        _ => null,
    };

    // A Setter.Value expression: a Text value converted to the property's value type (see SetterTextValueExpr), a
    // folded null/{x:Static}, or a *Resource extension. Null = unsupported.
    private static string? SetterValueExpr(Context c, in MemberRecord member, ITypeSymbol? propValueType) => member.Kind switch
    {
        XamlValueKind.Text => SetterTextValueExpr(c, c.Doc.Strings[member.ValueIndex], propValueType),
        XamlValueKind.Folded => FoldedValueExpr(c, c.Doc.Constants[member.ValueIndex]),
        XamlValueKind.Extension => ResourceValueExpr(c, in c.Doc.Extensions[member.ValueIndex]),
        _ => null,
    };

    // A Text Setter value, converted to the property's value type via the (AOT-clean) converter ladder — matching
    // the reflection frontend's parse-time context-free fold. An object/string (or unknown) value type keeps the raw
    // string (StyleSetterConverter converts enum/Color/IBrush/primitives at Seal — the no-converter fallback); a
    // System.Type value → a typeof token (no value converter; cf. ScalarConvertExpr).
    private static string? SetterTextValueExpr(Context c, string text, ITypeSymbol? propValueType)
    {
        if (propValueType is null
            || propValueType.SpecialType is SpecialType.System_String or SpecialType.System_Object)
            return $"\"{Escape(text)}\"";

        if (IsSystemType(propValueType))
            return XamlDataTypeScope.ResolveToken(c.Doc, text, c.Resolver) is { } resolved
                ? $"typeof({Global(resolved)})"
                : null;

        c.UsesConverter = true;
        return $"__ConvertXamlValue(typeof({Global(propValueType)}), \"{Escape(text)}\")";
    }

    // A *Resource extension as a Setter.Value expression: {DynamicResource key} → a ResourceReference carrier (the
    // styling engine resolves it per-element at arm time), key resolved at codegen (literal or {x:Static}); a
    // same-dictionary {StaticResource key} → the already-built entry's var (its load-time snapshot). Other
    // extensions (Binding) or an unresolvable key → null (unsupported).
    private static string? ResourceValueExpr(Context c, in ExtensionRecord ext)
    {
        if (ext.Kind == ExtensionKind.DynamicResource)
            return ResourceKeyArgExpr(c, in ext) is { } keyExpr
                ? $"new global::Cursorial.UI.ResourceReference({keyExpr})"
                : null;

        // A {StaticResource key}: a same-dictionary visible entry → its var (the load-time snapshot); else an
        // external key → an eager ResolveStatic against the lexical chain + app tail (the Setter.Value /
        // DataCondition.Value / standalone-entry slot is object-typed, so no cast). A forward intra-document /
        // in-template key returns null (the caller fences).
        if (ext.Kind == ExtensionKind.StaticResource && ResourceKeyArgExpr(c, in ext) is { } srcKeyExpr)
            return ResolveVisibleResourceVar(c, srcKeyExpr) ?? ExternalStaticResolveExpr(c, srcKeyExpr);

        return null;
    }

    // The key of a *Resource extension as a C# expression: a literal string, an {x:Static} global:: member, or an
    // {x:Type} typeof(...) (the nested-extension key forms — control themes key by {x:Type}). Null when the key is
    // an unsupported nested extension.
    private static string? ResourceKeyArgExpr(Context c, in ExtensionRecord ext)
    {
        if (!ext.PayloadIsParsedExtension)
            return $"\"{Escape(c.Doc.Strings[ext.Payload])}\"";

        // A nested key extension, e.g. {DynamicResource {x:Static ThemeKeys.X}} or {StaticResource {x:Type Foo}}.
        if (c.Doc.ParsedExtensions[ext.Payload] is { } node &&
            node.PositionalArguments.Count > 0 && node.PositionalArguments[0].Text is { } arg)
        {
            if (node.Name is "x:Static" or "Static")
                return ResolveStaticPath(c, arg);

            if (node.Name is "x:Type" or "Type" &&
                XamlDataTypeScope.ResolveToken(c.Doc, arg, c.Resolver) is { } typeSym)
                return $"typeof({Global(typeSym)})";
        }

        return null;
    }

    // A Style's BasedOn: a direct nested <Style> (built + referenced), or a {StaticResource key} resolving to a
    // same-dictionary keyed Style built before this use (the entry's var — its load-time snapshot; the key may be a
    // string or a nested {x:Type}/{x:Static}, as control themes key by {x:Type}). A forward-ref / cross-dictionary
    // {StaticResource} BasedOn stays unlowered (defer — null).
    private static string? BasedOnExpr(Context c, in MemberRecord member)
    {
        if (member.Kind == XamlValueKind.Object)
        {
            var v = c.NextVar();
            EmitObject(c, member.ValueIndex, v, isRoot: false, hasScope: false, dataType: null);
            return v;
        }

        if (member.Kind == XamlValueKind.Extension &&
            c.Doc.Extensions[member.ValueIndex] is { Kind: ExtensionKind.StaticResource } ext &&
            ResourceKeyArgExpr(c, in ext) is { } keyExpr)
        {
            if (ResolveVisibleResourceVar(c, keyExpr) is { } srcVar)
                return srcVar;

            // A key that IS defined in this document but hasn't been built yet is a FORWARD (or
            // outer-dictionary-forward) reference. The loader resolves it — it defers every entry and
            // realizes lazily against the captured lexical stack, so intra-document order doesn't matter
            // (matrix X115). The lowered probe can't: BasedOn is init-only, so it resolves inline during
            // the derived style's construction — before the base entry is built or added — and the probe
            // would walk a still-empty tree and throw. Fail closed (loud) rather than crash at runtime;
            // a document-order-independent lowering of forward BasedOn is a follow-up.
            // Otherwise the base lives OUTSIDE the document (an outer/merged dictionary or the app/theme
            // tail — the BasedOn="{StaticResource {x:Type ListBoxItem}}" app pattern). Resolve eagerly against
            // the enclosing lexical dictionaries + the application tail — the loader's XamlResourceScopeStack
            // exactly (no `this` anchor needed, so it works in a rootless ResourceDictionary builder too). A
            // forward/not-yet-built intra-document key or an in-template reference fences here.
            if (ExternalStaticResolveExpr(c, keyExpr) is { } resolve)
                return $"(global::Cursorial.UI.Style){resolve}!";
        }

        return null;
    }

    // Every resource key EXPRESSION defined anywhere in this document (a keyed object's x:Key lowered the
    // same way ResourceKeyExpr lowers it — a string literal / typeof(...) / {x:Static} ref). Used to tell a
    // forward/intra-document {StaticResource} BasedOn (the loader resolves it lazily; the inline probe can't)
    // from a genuinely external one (probe it). Computed once, lazily.
    private static HashSet<string> DocumentResourceKeys(Context c)
    {
        if (c.DocumentResourceKeysCache is { } cached)
            return cached;

        var keys = new HashSet<string>(System.StringComparer.Ordinal);
        for (int i = 0; i < c.Doc.Objects.Length; i++)
            if (ResourceKeyExpr(c, i) is { } keyExpr)
                keys.Add(keyExpr);

        c.DocumentResourceKeysCache = keys;
        return keys;
    }

    // ── WS-X5.4h — baked selectors (an explicit Selector="…" → a reflection-free Selectors fluent chain) ──

    // Bakes a selector string into a `global::Cursorial.UI.Selectors` fluent-chain expression (mirroring
    // SelectorParser's grammar — type / .class / #name / :pseudo / descendant / > child / /template/ / :is(…) /
    // comma lists / ^-nesting). Returns null for any unsupported/fenced construct (the caller TODOs), so a
    // baked selector is always exact or absent — never wrong.
    private static string? BakeSelector(Context c, string text)
    {
        int pos = 0;
        var branches = new List<string>();

        while (true)
        {
            SelSkipWs(text, ref pos);
            if (BakeBranch(c, text, ref pos) is not { } branch)
                return null;
            branches.Add(branch);
            SelSkipWs(text, ref pos);

            if (pos >= text.Length)
                break;
            if (text[pos] == ',') { pos++; continue; }
            return null; // unexpected trailing character
        }

        var expr = branches[0];
        for (int i = 1; i < branches.Count; i++)
            expr = $"{expr}.Or({branches[i]})"; // a comma list ⇒ branch1.Or(branch2)…
        return expr;
    }

    private static string? BakeBranch(Context c, string text, ref int pos)
    {
        if (BakeCompound(c, text, ref pos, leftmost: true, prev: null) is not { } expr)
            return null;

        while (true)
        {
            int before = pos;
            SelSkipWs(text, ref pos);
            bool ws = pos > before;

            if (pos >= text.Length) { pos = before; break; }

            char ch = text[pos];
            string combinator;
            if (ch == ',') { pos = before; break; }
            else if (ch == '>') { pos++; SelSkipWs(text, ref pos); combinator = ".Child()"; }
            else if (ch == '/')
            {
                if (!SelMatch(text, pos, "/template/")) return null;
                pos += "/template/".Length; SelSkipWs(text, ref pos); combinator = ".Template()";
            }
            else if (ch is '+' or '~') return null; // sibling combinators are fenced
            else if (ws && SelIsCompoundStart(ch)) combinator = ".Descendant()";
            else { pos = before; break; }

            if (BakeCompound(c, text, ref pos, leftmost: false, prev: expr + combinator) is not { } next)
                return null;
            expr = next;
        }

        return expr;
    }

    private static string? BakeCompound(Context c, string text, ref int pos, bool leftmost, string? prev)
    {
        if (pos >= text.Length || !SelIsCompoundStart(text[pos]))
            return null;

        string? expr = prev;
        bool started = false; // whether the compound's first token has been emitted

        if (text[pos] == '^')
        {
            if (!leftmost) return null;
            pos++;
            expr = "global::Cursorial.UI.Selectors.Nesting()";
            started = true;
        }

        // Optional type token: a bare identifier, or :is( type ).
        if (pos < text.Length)
        {
            char c0 = text[pos];
            if (SelIsIdentStart(c0))
            {
                if (BakeTypeToken(c, text, ref pos, expr, isAssignable: false, started) is not { } e) return null;
                expr = e; started = true;
            }
            else if (c0 == ':' && SelMatch(text, pos, ":is("))
            {
                pos += 4; SelSkipWs(text, ref pos);
                if (BakeTypeToken(c, text, ref pos, expr, isAssignable: true, started) is not { } e) return null;
                expr = e; started = true;
                SelSkipWs(text, ref pos);
                if (pos >= text.Length || text[pos] != ')') return null;
                pos++;
            }
        }

        // Simples in declaration order.
        while (pos < text.Length)
        {
            char c1 = text[pos];
            string kind;
            if (c1 == '.') kind = "Class";
            else if (c1 == '#') kind = "Name";
            else if (c1 == ':') kind = "PseudoClass";
            else if (c1 is '[' or '^' or '+' or '~') return null; // fenced / misplaced
            else break;

            pos++;
            var name = SelParseIdent(text, ref pos);
            if (name is null) return null;
            if (kind == "PseudoClass" && IsFencedPseudo(name)) return null;

            expr = started
                       ? $"{expr}.{kind}(\"{Escape(name)}\")"
                       : $"global::Cursorial.UI.Selectors.{kind}({(prev is null ? "null" : prev)}, \"{Escape(name)}\")";
            started = true;
        }

        return started ? expr : null;
    }

    // Emits a type-token start: OfType / Is, chained onto prev (or a fresh Selectors.OfType(prev, typeof(T))).
    private static string? BakeTypeToken(Context c, string text, ref int pos, string? prev, bool isAssignable, bool started)
    {
        var name = SelParseIdent(text, ref pos);
        if (name is null || (pos < text.Length && text[pos] == '|'))
            return null; // a prefix|Type token needs the doc-xmlns resolver — not yet baked

        if (XamlDataTypeScope.ResolveToken(c.Doc, name, c.Resolver) is not { } type)
            return null;

        var method = isAssignable ? "Is" : "OfType";
        return started
                   ? $"{prev}.{method}(typeof({Global(type)}))"
                   : $"global::Cursorial.UI.Selectors.{method}({(prev is null ? "null" : prev)}, typeof({Global(type)}))";
    }

    private static bool IsFencedPseudo(string name)
        => name is "not" or "first-child" or "last-child" || name.StartsWith("nth-", System.StringComparison.Ordinal);

    private static void SelSkipWs(string text, ref int pos)
    {
        while (pos < text.Length && text[pos] is ' ' or '\t') pos++;
    }

    private static bool SelMatch(string text, int pos, string lit)
    {
        if (pos + lit.Length > text.Length) return false;
        for (int i = 0; i < lit.Length; i++)
            if (text[pos + i] != lit[i]) return false;
        return true;
    }

    private static bool SelIsIdentStart(char c) => c is (>= 'A' and <= 'Z') or (>= 'a' and <= 'z') or '_';
    private static bool SelIsIdentPart(char c) => SelIsIdentStart(c) || c is (>= '0' and <= '9') or '-';
    private static bool SelIsCompoundStart(char c) => SelIsIdentStart(c) || c is '^' or '.' or '#' or ':';

    private static string? SelParseIdent(string text, ref int pos)
    {
        if (pos >= text.Length || !SelIsIdentStart(text[pos]))
            return null;
        int start = pos++;
        while (pos < text.Length && SelIsIdentPart(text[pos])) pos++;
        return text.Substring(start, pos - start);
    }

    private static void EmitObject(Context c, int objectIndex, string varExpr, bool isRoot, bool hasScope, INamedTypeSymbol? dataType)
    {
        ref readonly var obj = ref c.Doc.Objects[objectIndex];

        // A markup extension in element form reached in a VALUE position — a collection item, content, a
        // Styles/merged child — is bound to a local from its standalone value expression. (A scalar member
        // value, Setter.Value, and a keyed dictionary entry handle attach / keying BEFORE calling EmitObject,
        // so those never reach here.) An extension with no standalone value (Binding/custom) degrades to a
        // CURG3001 note with a null placeholder so the emitted C# still compiles.
        if (obj.HasFlag(ObjectFlags.IsMarkupExtension))
        {
            var expr = MarkupExtensionEntryExpr(c, in obj);
            if (expr is null)
            {
                // A standalone element-form <Binding>/<TemplateBinding> is input the LOADER hard-rejects
                // (XamlObjectGraphBuilder.Assign Fatal) — the lowered build must fail as loudly, not ship a
                // null placeholder the runtime would never have produced. Other extensions (custom, resource
                // refs) are valid XAML with no standalone lowering yet — a warning-level gap.
                var extValue = ExtensionValueMember(c, in obj);
                if (extValue.Kind == XamlValueKind.Extension &&
                    c.Doc.Extensions[extValue.ValueIndex].Kind is ExtensionKind.Binding or ExtensionKind.TemplateBinding)
                    c.Error("a standalone element-form <Binding>/<TemplateBinding> in a value position is invalid XAML (the runtime loader rejects it)");
                else
                    c.Todo("element-form markup extension in this position (custom/resource entry) not yet lowered");
                expr = "default(object)";
            }

            c.Line($"var {varExpr} = {expr};");
            return;
        }
        c.CurrentLineInfo = obj.PackedLineInfo;

        var objType = TypeSymbolOf(c.Doc, obj.TypeId);

        // <x:Array Type="T"> → a typed T[] built from its items (XD27); objType is the ELEMENT type T.
        if (obj.HasFlag(ObjectFlags.IsArray))
        {
            EmitArray(c, objectIndex, in obj, varExpr, objType, hasScope, dataType);
            return;
        }

        // A built-in primitive element initializes from its content text (XD28): <x:Int32>5</x:Int32> → 5.
        if (!isRoot && objType is { } prim && IsBuiltInPrimitive(prim))
        {
            EmitInitTextPrimitive(c, objectIndex, in obj, varExpr, prim, hasScope);
            return;
        }

        // A <Style> needs dedicated construction (selector-via-ctor, init-only BasedOn/Key, Setter.Property
        // resolution) — route it before the generic object path.
        if (!isRoot && IsStyleType(objType))
        {
            EmitStyle(c, objectIndex, varExpr);
            return;
        }

        // An x:DataType on this object establishes the compiled-binding source type for its whole subtree
        // (B184/B3); otherwise the enclosing scope's type carries down. Computed BEFORE the init-only scan so an
        // init-only property-element's child subtree (built inside the scan) sees the right binding source type.
        dataType = XamlDataTypeScope.ForObject(c.Doc, in obj, c.Resolver) ?? dataType;

        // Init-only CLR value members (e.g. SolidColorBrush.Color, Pen.Brush) can't be set post-construction
        // (CS8852) — they go in the construction object initializer. Pre-scan for them in BOTH forms — an attribute
        // (Text/Folded) and a property element (a single Object value: <Pen.Brush><SolidColorBrush/></Pen.Brush>) —
        // so the `new T { … }` carries them (a property-element child is built into a local first) and the member
        // loop skips them. (The root is `this` — already constructed — so its init-only members can't use an
        // initializer; they fall to the member loop's ClrSetBlocked → TODO.)
        var initMembers = isRoot ? null : ScanInitOnlyMembers(c, in obj, objType, hasScope, dataType);

        if (!isRoot)
        {
            if (objType is null)
            {
                c.Todo($"unresolved element type (object {objectIndex})");
                return;
            }
            var initializer = initMembers is { Entries.Count: > 0 } ? $" {{ {string.Join(", ", initMembers.Entries)} }}" : "()";
            c.CurrentLineInfo = obj.PackedLineInfo; // re-assert (a property-element child build in the scan moved it)
            c.Line($"var {varExpr} = new {Global(objType)}{initializer};");
        }

        // This object's <X.Resources> (pushed by EmitResourcesMember below) is visible to its whole subtree,
        // then popped — the loader's scope Push / PopDownTo(depth) around a resources hop.
        int ambientDepth = c.AmbientScopeStack.Count;

        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            c.CurrentLineInfo = member.PackedLineInfo;
            c.CurrentObjectType = objType; // re-assert per member (child recursion clobbers it)

            if (initMembers is not null && initMembers.Indices.Contains(m))
                continue; // already emitted in the construction object initializer

            if (member.Kind == XamlValueKind.Directive)
            {
                if (member.DirectiveKind == (int)XamlDirectiveKind.Name)
                {
                    var name = c.Doc.Strings[member.ValueIndex];
                    if (c.TemplateContextVar is { } ctx)
                        // Inside a template: register into the per-build template name scope, never the document scope.
                        c.Line($"{ctx}.RegisterName(\"{name}\", {varExpr});");
                    else if (hasScope)
                    {
                        c.Line($"this.{name} = {varExpr};");
                        c.Line($"__scope.Register(\"{name}\", {varExpr});");
                    }
                }
                continue; // x:Class/x:Key/x:DataType: no lowered effect here
            }

            var xm = member.MemberId >= 0 ? c.Doc.ResolvedMembers[member.MemberId] : null;
            if (xm is null)
                continue;

            switch (member.Kind)
            {
                case XamlValueKind.Text:
                    EmitScalarAssign(c, varExpr, xm, c.Doc.Strings[member.ValueIndex]);
                    break;

                case XamlValueKind.Object:
                {
                    // A <Foo.Resources> body — a nested <ResourceDictionary> or a run of keyed entries — folds
                    // through the SAME entry machinery the top-level dictionary uses (the loader's
                    // AddOrMergeResourceChild): nested-RD fold, {x:Static}/{x:Type}/implicit keys, aliasing.
                    // Intercept BEFORE the generic child build (a half-built dict with an unresolved Source
                    // would otherwise leak into the tree).
                    if (IsResourceDictionaryMember(xm))
                    {
                        EmitResourcesMember(c, varExpr, xm, in member);
                        break;
                    }

                    // A markup extension in element form as a scalar member value (<Setter.Value><DynamicResource
                    // …/></Setter.Value>): lower it exactly as the curly attribute form.
                    ref readonly var childObj = ref c.Doc.Objects[member.ValueIndex];
                    if (childObj.HasFlag(ObjectFlags.IsMarkupExtension))
                    {
                        EmitMarkupExtensionMember(c, varExpr, xm, in childObj, dataType);
                        break;
                    }

                    var childVar = c.NextVar();
                    // A ControlTemplate's (or ItemsPanelTemplate's) templated parent is the enclosing control (this
                    // objType); a DataTemplate has none. Establish it for the recursion so a {TemplateBinding} inside
                    // resolves its source.
                    var savedTpt = c.TemplatedParentType;
                    if (IsControlTemplateType(xm.ValueType) || IsItemsPanelTemplateType(xm.ValueType)) c.TemplatedParentType = objType;
                    else if (IsDataTemplateType(xm.ValueType)) c.TemplatedParentType = null;
                    EmitObject(c, member.ValueIndex, childVar, isRoot: false, hasScope, dataType);
                    c.TemplatedParentType = savedTpt;
                    c.CurrentObjectType = objType; // re-assert: the child recursion clobbered it (EmitChildAssign's ClrSetBlocked check reads the PARENT type)
                    EmitChildAssign(c, varExpr, xm, childVar, member.ValueIndex, single: true);
                    break;
                }

                case XamlValueKind.Items:
                {
                    if (IsResourceDictionaryMember(xm))
                    {
                        EmitResourcesMember(c, varExpr, xm, in member);
                        break;
                    }

                    int childIndex = member.ValueIndex;
                    for (int i = 0; i < member.ItemCount; i++)
                    {
                        var childVar = c.NextVar();
                        EmitObject(c, childIndex, childVar, isRoot: false, hasScope, dataType);
                        EmitChildAssign(c, varExpr, xm, childVar, childIndex, single: false);
                        childIndex += c.Doc.Objects[childIndex].SubtreeLength; // depth-first contiguous
                    }
                    break;
                }

                case XamlValueKind.Extension:
                    EmitExtensionAssign(c, varExpr, xm, in c.Doc.Extensions[member.ValueIndex], dataType);
                    break;

                case XamlValueKind.Deferred:
                {
                    // A template body (ControlTemplate/DataTemplate Content): lower the slice to a FuncTemplateContent
                    // factory built fresh per instantiation, and assign it to the ITemplateContent member. The
                    // templated-parent type (for {TemplateBinding} inside) is the ControlTemplate's explicit
                    // TargetType, else the enclosing control established by the Object recursion above, else — for a
                    // keyed shared ControlTemplate (no TargetType, no enclosing control) — the Control base: a
                    // ControlTemplate is always applied to a Control, and the framework {TemplateBinding} sources
                    // (Background/BorderPen/…) are registered on Control, so the resolved UIProperty is the exact
                    // object the runtime resolves by name against the concrete parent at apply-time.
                    var target = ResolveTemplateTargetType(c, in obj) ?? c.TemplatedParentType;
                    if (target is null && objType is { Name: "ControlTemplate", ContainingNamespace.Name: "Controls" })
                        target = c.Control;
                    var factory = EmitTemplateFactory(c, member.ValueIndex, hasScope, target);
                    var content = $"new global::Cursorial.UI.Controls.FuncTemplateContent({factory})";
                    if (RegisteredOwner(xm) is { } owner)
                        c.Line($"{varExpr}.SetValue({Global(owner)}.{xm.Name}Property, {content});");
                    else
                        c.Line($"{varExpr}.{xm.Name} = {content};");
                    break;
                }

                case XamlValueKind.Event:
                    // Click="OnClick" → `__e.Click += this.OnClick;`. The handler is resolved at the consumer's
                    // compile (a missing/mismatched handler is a CS error). The runtime loader no-ops events at
                    // X1, so lowering is strictly more capable here.
                    c.Line($"{varExpr}.{xm.Name} += this.{c.Doc.Strings[member.ValueIndex]};");
                    break;

                case XamlValueKind.Folded:
                    // Under FoldConstants=false the only Folded members are the intrinsic extensions:
                    // {x:Null} (a null constant) and {x:Static} (a XamlStaticReference carrying the member path).
                    EmitFoldedAssign(c, varExpr, xm, c.Doc.Constants[member.ValueIndex]);
                    break;

                default:
                    c.Todo($"member '{xm.Name}' kind {member.Kind} not yet lowered");
                    break;
            }
        }

        if (c.AmbientScopeStack.Count > ambientDepth)
            c.AmbientScopeStack.RemoveRange(ambientDepth, c.AmbientScopeStack.Count - ambientDepth);
    }

    // The XAML2009 built-in (CLR basic) type local names — the set a primitive element initializes from its
    // content text (XD28), mirroring XamlSchemaContext.BuiltInType / XamlSymbolResolver.BuiltInMetadataName.
    private static readonly HashSet<string> BuiltInPrimitiveLocalNames =
    [
        "Object", "Boolean", "Byte", "SByte", "Char", "Decimal", "Single", "Double", "Int16", "Int32",
        "Int64", "UInt16", "UInt32", "UInt64", "String", "TimeSpan", "Uri",
    ];

    private static bool IsBuiltInPrimitive(INamedTypeSymbol s)
        => s.ContainingNamespace is { Name: "System", ContainingNamespace.IsGlobalNamespace: true }
           && BuiltInPrimitiveLocalNames.Contains(s.Name);

    /// <summary>Lowers an <c>&lt;x:Array Type="T"&gt;</c> to <c>new T[] { … }</c> (XD27): each item lowers via
    /// the generic object path (so a <c>&lt;x:String&gt;</c> item lowers through <see cref="EmitInitTextPrimitive"/>).</summary>
    private static void EmitArray(Context c, int objectIndex, in ObjectRecord obj, string varExpr, INamedTypeSymbol? elementType, bool hasScope, INamedTypeSymbol? dataType)
    {
        if (elementType is null)
        {
            c.Todo($"x:Array element type unresolved (object {objectIndex})");
            c.Line($"var {varExpr} = global::System.Array.Empty<object>();");
            return;
        }

        var itemVars = new List<string>();
        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            if (member.Kind != XamlValueKind.Items)
                continue;

            int childIndex = member.ValueIndex;
            for (int i = 0; i < member.ItemCount; i++)
            {
                var childVar = c.NextVar();
                EmitObject(c, childIndex, childVar, isRoot: false, hasScope, dataType);
                itemVars.Add(childVar);
                childIndex += c.Doc.Objects[childIndex].SubtreeLength; // depth-first contiguous
            }
        }

        c.Line($"var {varExpr} = new {Global(elementType)}[] {{ {string.Join(", ", itemVars)} }};");
        EmitSpecialObjectName(c, in obj, varExpr, hasScope);
    }

    /// <summary>Lowers a built-in primitive element to its converted value (XD28): string/object → the raw
    /// literal; else the runtime converter (drift-free with the loader's <c>ConvertInitText</c>).</summary>
    private static void EmitInitTextPrimitive(Context c, int objectIndex, in ObjectRecord obj, string varExpr, INamedTypeSymbol primType, bool hasScope)
    {
        string text = string.Empty;
        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            if (member.Kind == XamlValueKind.Text && member.MemberId < 0) { text = c.Doc.Strings[member.ValueIndex]; break; }
        }

        string expr;
        if (primType.SpecialType is SpecialType.System_String or SpecialType.System_Object)
        {
            expr = $"\"{Escape(text)}\"";
        }
        else
        {
            c.UsesConverter = true;
            expr = $"({Global(primType)})__ConvertXamlValue(typeof({Global(primType)}), \"{Escape(text)}\")!";
        }

        c.Line($"var {varExpr} = {expr};");
        EmitSpecialObjectName(c, in obj, varExpr, hasScope); // a document-scope x:Name registers + sets the field
    }

    /// <summary>Registers an <c>x:Name</c> on a special-built object (x:Array / built-in primitive) — the
    /// document-scope leg of <see cref="EmitObject"/>'s directive handling (a template-scope name on a non-
    /// UIElement value has no registration target, matching the loader).</summary>
    private static void EmitSpecialObjectName(Context c, in ObjectRecord obj, string varExpr, bool hasScope)
    {
        if (!obj.HasFlag(ObjectFlags.HasName))
            return;

        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            if (member.Kind != XamlValueKind.Directive || member.DirectiveKind != (int) XamlDirectiveKind.Name)
                continue;

            if (c.TemplateContextVar is null && hasScope)
            {
                var name = c.Doc.Strings[member.ValueIndex];
                c.Line($"this.{name} = {varExpr};");
                c.Line($"__scope.Register(\"{name}\", {varExpr});");
            }
            return;
        }
    }

    // Lowers a deferred template body (the slice rooted at sliceHead — a single template-root object) to a static
    // local function `UIElement __FactoryN(TemplateBuildContext __ctx)` that builds a fresh subtree each call,
    // registering x:Name parts into __ctx's template name scope. Returns the factory name (wrapped in a
    // FuncTemplateContent by the caller). The factory is accumulated and appended at the end of InitializeComponent
    // (a local function is hoisted, so the forward reference resolves). Nested templates flatten into sibling factories.
    private static string EmitTemplateFactory(Context c, int sliceHead, bool hasScope, INamedTypeSymbol? templatedParentType)
    {
        var factoryName = c.NextFactory();
        var rootVar = c.NextVar();

        // Redirect emission into the factory body + enter template mode (x:Name → __ctx.RegisterName, {StaticResource}
        // → TODO since there's no end-of-tree FindResource anchor, {TemplateBinding} → the template's target type).
        // Save/restore for correct nesting.
        var bodyBuf = new StringBuilder();
        var savedBuffer = c.SwapBuffer(bodyBuf);
        var savedInTemplate = c.InTemplate;
        var savedCtxVar = c.TemplateContextVar;
        var savedTpt = c.TemplatedParentType;
        var savedCaptures = c.CurrentFactoryCaptures;
        var savedReferences = c.References.Count;       // {x:Reference} recorded inside this factory flush HERE,
        var savedScopeLines = c.DeferredScopeLines.Count; // against ITS scope — never the document's (isolation)
        var savedAmbientFloor = c.AmbientScopeFloor;    // the factory is a separate C# local function: its custom
        c.AmbientScopeFloor = c.AmbientScopeStack.Count; // extensions see only template dictionaries, not outer ones
        c.InTemplate = true;
        c.TemplateContextVar = "__ctx";
        c.TemplatedParentType = templatedParentType;
        c.CurrentFactoryCaptures = false;

        EmitObject(c, sliceHead, rootVar, isRoot: false, hasScope, dataType: null);

        // {x:Reference} + scope-embedding Installs recorded in this factory body resolve against the
        // per-build template scope, after the whole slice registered its names — the loader's end-of-slice
        // ResolveDeferredReferences point (forward references included).
        if (c.References.Count > savedReferences || c.DeferredScopeLines.Count > savedScopeLines)
        {
            c.Line("// {x:Reference} — resolve against this template build's now-complete name scope.");
            EmitReferenceResolutions(c, savedReferences, "__ctx.NameScope");
            c.References.RemoveRange(savedReferences, c.References.Count - savedReferences);
            FlushDeferredScopeLines(c, savedScopeLines);
        }

        // A factory that referenced an enclosing local (a same-dict {StaticResource} var) can't be `static` — it
        // must capture. One that didn't stays `static` (cleaner generated code; matches the non-capturing tests).
        var captures = c.CurrentFactoryCaptures;
        c.InTemplate = savedInTemplate;
        c.TemplateContextVar = savedCtxVar;
        c.TemplatedParentType = savedTpt;
        c.CurrentFactoryCaptures = savedCaptures;
        c.AmbientScopeFloor = savedAmbientFloor;
        c.SwapBuffer(savedBuffer);

        var fn = new StringBuilder();
        var staticMod = captures ? "" : "static ";
        fn.AppendLine($"{c.Indent}{staticMod}global::Cursorial.UI.UIElement {factoryName}(global::Cursorial.UI.Controls.TemplateBuildContext __ctx)");
        fn.AppendLine($"{c.Indent}{{");
        fn.Append(bodyBuf);
        fn.AppendLine($"{c.Indent}    return {rootVar};");
        fn.AppendLine($"{c.Indent}}}");
        c.Factories.Add(fn.ToString());

        return factoryName;
    }

    // Pre-scans an object's Text/Folded members for init-only CLR value properties (settable only in an object
    // initializer). Returns the initializer entries (`Prop = expr`) + the member indices to skip in the main loop.
    private static InitOnlyScan ScanInitOnlyMembers(Context c, in ObjectRecord obj, INamedTypeSymbol? objType, bool hasScope, INamedTypeSymbol? dataType)
    {
        var scan = new InitOnlyScan();
        if (objType is null)
            return scan;

        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            // An init-only CLR member arrives as an attribute (Text/Folded) or a property element (a single Object).
            if (member.Kind is not (XamlValueKind.Text or XamlValueKind.Folded or XamlValueKind.Object))
                continue;

            var xm = member.MemberId >= 0 ? c.Doc.ResolvedMembers[member.MemberId] : null;
            if (xm is null || RegisteredOwner(xm) is not null) // a UIProperty uses SetValue, never an initializer
                continue;

            if (XamlDataTypeScope.FindMember(objType, xm.Name) is not { } sym || !XamlDataTypeScope.IsInitOnlySettable(sym))
                continue;

            // A property element builds its child subtree into a local FIRST (emitted before the enclosing
            // `new T { Member = <var> }` that references it); an attribute converts its literal/folded value inline.
            var expr = member.Kind switch
            {
                XamlValueKind.Text => ScalarTypedExpr(c, xm, c.Doc.Strings[member.ValueIndex]),
                XamlValueKind.Folded => FoldedValueExpr(c, c.Doc.Constants[member.ValueIndex]),
                XamlValueKind.Object => BuildInitOnlyObjectChild(c, member.ValueIndex, hasScope, dataType),
                _ => null,
            };

            if (expr is null) // unresolved — let the member loop TODO it (don't skip)
                continue;

            scan.Entries.Add($"{xm.Name} = {expr}");
            scan.Indices.Add(m);
        }

        return scan;
    }

    // Builds an init-only property element's child subtree into a fresh local (emitted into the body BEFORE the
    // enclosing `new T { Member = <var> }`), returning that var — so an init-only CLR property set via a property
    // element (<Pen.Brush><SolidColorBrush/></Pen.Brush>) lands in the object initializer, not a CS8852 assignment.
    private static string BuildInitOnlyObjectChild(Context c, int childIndex, bool hasScope, INamedTypeSymbol? dataType)
    {
        var childVar = c.NextVar();
        EmitObject(c, childIndex, childVar, isRoot: false, hasScope, dataType);
        return childVar;
    }

    // A Text value: an object/string member takes the string literal directly; any other typed member runs
    // the (hand-written, AOT-clean) converter ladder via the emitted __ConvertXamlValue helper (X5.1).
    // (Init-only CLR targets are set in the construction object initializer, NOT here — see EmitObject.)
    private static void EmitScalarAssign(Context c, string varExpr, XamlMember xm, string text)
    {
        // Classes="accent primary" — the read-only ClassSet (no setter) takes a Classes.Add per name (static class
        // assignment, Avalonia parity; mirrors the runtime loader's ApplyTextMember Classes path).
        if (IsClassSetMember(xm))
        {
            foreach (var className in text.Split((char[]?) null, System.StringSplitOptions.RemoveEmptyEntries))
                c.Line($"{varExpr}.Classes.Add(\"{Escape(className)}\");");
            return;
        }

        if (RegisteredOwner(xm) is { } owner)
        {
            // SetValue takes object? — no cast needed.
            if (ScalarConvertExpr(c, xm, text) is { } raw)
                c.Line($"{varExpr}.SetValue({Global(owner)}.{xm.Name}Property, {raw});");
            else
                c.Todo($"unresolved value type for {xm.Name}=\"{Escape(text)}\"");
            return;
        }

        if (ClrSetBlocked(c, xm.Name))
        {
            c.Todo($"CLR property '{xm.Name}' is init-only/read-only — can't be set post-construction (set on the root, or a missed initializer)");
            return;
        }

        if (ScalarTypedExpr(c, xm, text) is { } typed)
            c.Line($"{varExpr}.{xm.Name} = {typed};");
        else
            c.Todo($"unresolved value type for {xm.Name}=\"{Escape(text)}\"");
    }

    // A Classes="…" member: the read-only ClassSet style-class set (UIElement.Classes), set via Classes.Add per name.
    private static bool IsClassSetMember(XamlMember xm)
        => ValueTypeSymbol(xm.ValueType) is { Name: "ClassSet", ContainingNamespace: { Name: "UI", ContainingNamespace.Name: "Cursorial" } };

    // The object?-typed expression for a Text value (a string literal, or the converter call). Null = unresolved.
    private static string? ScalarConvertExpr(Context c, XamlMember xm, string text)
    {
        if (IsObjectOrString(xm.ValueType))
            return $"\"{Escape(text)}\"";

        if (ValueTypeSymbol(xm.ValueType) is { } valueType)
        {
            // A System.Type-valued member (e.g. ControlTemplate.TargetType) takes a type TOKEN resolved via the
            // document xmlns → typeof(...). There is no string→Type value converter (the runtime loader has the
            // same gap — ConvertText would pass the raw string), so the converter ladder can't handle it.
            if (IsSystemType(valueType))
                return XamlDataTypeScope.ResolveToken(c.Doc, text, c.Resolver) is { } resolved
                    ? $"typeof({Global(resolved)})"
                    : null;

            c.UsesConverter = true;
            return $"__ConvertXamlValue(typeof({Global(valueType)}), \"{Escape(text)}\")";
        }

        return null;
    }

    private static bool IsSystemType(ITypeSymbol type)
        => type is { Name: "Type", ContainingNamespace: { Name: "System", ContainingNamespace.IsGlobalNamespace: true } };

    // The typed (cast) form for a CLR setter / object initializer (the converter's object? cast to the prop type).
    private static string? ScalarTypedExpr(Context c, XamlMember xm, string text)
    {
        if (ScalarConvertExpr(c, xm, text) is not { } raw)
            return null;

        return IsObjectOrString(xm.ValueType) ? raw : $"({Global(ValueTypeSymbol(xm.ValueType)!)}){raw}!";
    }

    // True only when the property is POSITIVELY known non-writable post-construction (init-only / read-only). A
    // symbol-walk miss keeps the current direct-set emit (avoids false TODOs for properties the walk doesn't surface).
    private static bool ClrSetBlocked(Context c, string name)
        => c.CurrentObjectType is { } t && XamlDataTypeScope.FindMember(t, name) is { } m && !XamlDataTypeScope.IsWritable(m);

    // A child element value: a ResourceDictionary member fills via Add(key, value) (the get-object dictionary,
    // keyed by x:Key); a registered-collection content member fills via Add(item); a single member is set
    // (SetValue for a UIProperty, else the CLR setter).
    private static void EmitChildAssign(Context c, string varExpr, XamlMember xm, string childVar, int childObjectIndex, bool single)
    {
        if (!single)
        {
            c.Line($"{varExpr}.{xm.Name}.Add({childVar});");
            return;
        }

        if (RegisteredOwner(xm) is { } owner)
        {
            c.Line($"{varExpr}.SetValue({Global(owner)}.{xm.Name}Property, {childVar});");
            return;
        }

        // An init-only / read-only CLR property set via a property element can't be assigned post-construction
        // (CS8852). A non-root init-only one is hoisted into the construction initializer by ScanInitOnlyMembers, so
        // reaching here means the root (`this`, already constructed) or an otherwise-unhoistable case — TODO, never
        // emit code that won't compile. (CurrentObjectType is re-asserted to the parent before this call.)
        if (ClrSetBlocked(c, xm.Name))
        {
            c.Todo($"CLR property '{xm.Name}' is init-only/read-only — can't be set post-construction via a property element");
            return;
        }

        c.Line($"{varExpr}.{xm.Name} = {childVar};");
    }

    // A <Foo.Resources> body: read the get-object Resources dictionary into a local and route every child
    // through the SAME entry machinery the top-level <ResourceDictionary> uses (EmitDictionaryEntry) — the
    // loader's AddOrMergeResourceChild. This gives inline Resources the full surface: a nested
    // <ResourceDictionary Source="…"/> folds (relative URI resolved), {x:Static}/{x:Type}/implicit
    // Style/DataTemplate keys, and aliasing entries — instead of the old plain-string-key-only Add.
    private static void EmitResourcesMember(Context c, string varExpr, XamlMember xm, in MemberRecord member)
    {
        var dictVar = c.NextVar();
        c.Line($"var {dictVar} = {varExpr}.{xm.Name};"); // the get-object dictionary — read, never assign
        c.AmbientScopeStack.Add(new ResourceScope(dictVar)); // the lexical resource scope for this element's subtree (the loader's Push)
        foreach (int idx in ResourceItems(c, member))
            EmitDictionaryEntry(c, dictVar, idx);
    }

    private static bool IsResourceDictionaryMember(XamlMember xm)
        => ValueTypeSymbol(xm.ValueType) is INamedTypeSymbol s && SymbolXamlModel.IsResourceDictionary(s);

    private static bool IsControlTemplateType(IXamlType valueType)
        => ValueTypeSymbol(valueType) is { Name: "ControlTemplate", ContainingNamespace.Name: "Controls" };

    private static bool IsDataTemplateType(IXamlType valueType)
        => ValueTypeSymbol(valueType) is { Name: "DataTemplate", ContainingNamespace.Name: "Controls" };

    private static bool IsItemsPanelTemplateType(IXamlType valueType)
        => ValueTypeSymbol(valueType) is { Name: "ItemsPanelTemplate", ContainingNamespace.Name: "Controls" };

    // The ControlTemplate's explicit TargetType (a Text member naming a type), resolved via the document xmlns, or null.
    private static INamedTypeSymbol? ResolveTemplateTargetType(Context c, in ObjectRecord obj)
    {
        for (int m = obj.MemberStart; m < obj.MemberStart + obj.MemberCount; m++)
        {
            ref readonly var member = ref c.Doc.Members[m];
            if (member.Kind != XamlValueKind.Text)
                continue;

            var xm = member.MemberId >= 0 ? c.Doc.ResolvedMembers[member.MemberId] : null;
            if (xm?.Name == "TargetType")
                return XamlDataTypeScope.ResolveToken(c.Doc, c.Doc.Strings[member.ValueIndex], c.Resolver);
        }

        return null;
    }

    // {x:Null} → null; {x:Static Type.Member} → the resolved static reference (global::Type.Member).
    // (Init-only CLR targets are set in the construction object initializer, NOT here — see EmitObject.)
    private static void EmitFoldedAssign(Context c, string varExpr, XamlMember xm, object? constant)
    {
        if (FoldedValueExpr(c, constant) is not { } valueExpr)
        {
            c.Todo($"folded value for {xm.Name} ({constant?.GetType().Name ?? "null"})");
            return;
        }

        if (RegisteredOwner(xm) is { } owner)
        {
            c.Line($"{varExpr}.SetValue({Global(owner)}.{xm.Name}Property, {valueExpr});");
            return;
        }

        if (ClrSetBlocked(c, xm.Name))
        {
            c.Todo($"CLR property '{xm.Name}' is init-only/read-only — can't be set post-construction");
            return;
        }

        c.Line($"{varExpr}.{xm.Name} = {valueExpr};");
    }

    // The C# expression for a folded constant: null, or {x:Static}'s resolved global:: reference. Null = not handled.
    private static string? FoldedValueExpr(Context c, object? constant) => constant switch
    {
        null => "null",
        XamlStaticReference staticRef => ResolveStaticPath(c, staticRef.MemberPath),
        _ => null, // not expected under FoldConstants=false
    };

