    // The reflective fallback (B3b) — a faithful `new Binding(path) { … }` mirroring the runtime handler's
    // BuildBinding (Mode/ElementName/Source/StringFormat/FallbackValue/RelativeSource), minus Converter. Returns
    // true when it emitted a working binding; false when it left a hard // TODO X5 gap (CURG3001, no runtime effect)
    // — the caller uses this to decide whether a CURG2002 "works-but-reflective" info is appropriate.
    private static bool EmitReflectiveBinding(Context c, string varExpr, INamedTypeSymbol owner, XamlMember xm, MarkupExtensionNode node)
    {
        // {Binding Source={x:Reference name}} anchors on a named element (the loader's NamedElementAnchor
        // path): Binding.Source is init-only, so the WHOLE Install defers to the scope-complete point — the
        // document flush, or this factory's end-of-slice flush — exactly the loader's DeferNameResolution.
        if (node.FindNamed("Source") is { IsNested: true } src &&
            src.Nested!.Name is "x:Reference" or "Reference")
        {
            if (FirstPositionalText(src.Nested!) is not { Length: > 0 } refName)
            {
                c.Todo($"{{Binding}} Source {{x:Reference}} for '{xm.Name}' has no element name");
                return false;
            }

            // A document-level anchor needs the document name scope (__scope); it only exists when the
            // document declares document-scope x:Names. Without one, no name can resolve — the loader
            // Fatals identically — so fence rather than emit a reference to an undeclared __scope (CS0103).
            if (!c.InTemplate && !c.HasDocumentScope)
            {
                c.Todo($"{{Binding Source={{x:Reference {refName}}}}} for '{xm.Name}' cannot resolve — the document declares no name scope");
                return false;
            }

            var scopeExpr = c.InTemplate ? "__ctx.NameScope" : "__scope";
            // Require, not Find — deferred to the scope-complete flush, so a miss is genuine (the loader's
            // DeferNameResolution → ReferenceNotFound Fatal), never a silent null Source rebinding to
            // DataContext. Static-call form (the generated code carries no `using` for the extension).
            if (ReflectiveBindingExpr(c, node, $"for '{xm.Name}'",
                    sourceOverrideExpr: $"global::Cursorial.UI.NameScopeExtensions.Require({scopeExpr}, \"{Escape(refName)}\")") is not { } anchored)
                return false;

            c.DeferredScopeLines.Add(
                $"global::Cursorial.UI.Data.BindingOperations.Install({varExpr}, {Global(owner)}.{xm.Name}Property, {anchored});");
            return true;
        }

        if (ReflectiveBindingExpr(c, node, $"for '{xm.Name}'") is not { } bindingExpr)
            return false; // a specific // TODO X5 was already emitted

        c.Line(
            $"global::Cursorial.UI.Data.BindingOperations.Install({varExpr}, {Global(owner)}.{xm.Name}Property, {bindingExpr});");
        return true;
    }

    // The reflective `new Binding("path") { … }` DESCRIPTOR expression (Mode / RelativeSource / Converter / path /
    // ElementName / Source / StringFormat / FallbackValue + baked prefixed-path owners) — the shared core of the
    // install lane (<see cref="EmitReflectiveBinding"/>, wrapped in BindingOperations.Install) and the Binding-
    // DESCRIPTOR lane (a Binding-typed slot such as DataCondition.Binding, used as an initializer value). Returns
    // null when a piece isn't lowerable, having emitted a specific // TODO X5 naming it via <paramref name="diagName"/>.
    private static string? ReflectiveBindingExpr(Context c, MarkupExtensionNode node, string diagName, string? sourceOverrideExpr = null)
    {
        if (CanonicalMode(node) is not { } modeName)
        {
            c.Todo($"{{Binding}} with an unrecognized Mode {diagName}");
            return null;
        }

        if (RelativeSourceInit(c, node) is not { } relSource)
        {
            c.Todo($"{{Binding}} RelativeSource {diagName} not supported in lowering (Self / TemplatedParent / FindAncestor)");
            return null;
        }

        if (ConverterInit(c, node) is not { } converterInit)
        {
            c.Todo($"{{Binding}} Converter {diagName} could not be lowered in this position (fenced/forward resource, unresolvable static, or a fenced custom extension)");
            return null;
        }

        // A namespace-prefixed type-qualified path segment `(prefix:Type.Member)` resolves its owner against the
        // document's xmlns in the loader; the emitted `new Binding("...")` carries no resolver, so bake the resolved
        // owners into a TypeResolver here so the reflective binding resolves them identically (#153). null ⇒ a prefix
        // couldn't be resolved at build — keep the raw path (fails at bind time exactly as the loader would) + info.
        string rawPath = BindingPathOf(node) ?? string.Empty;
        var prefixedOwners = CollectPrefixedPathOwners(c, rawPath);
        if (prefixedOwners is null)
        {
            c.Info($"{{Binding}} path '{rawPath}' has a namespace-prefixed type qualification whose owner could not be " +
                   "resolved at build; it stays reflective and resolves via the registry default at bind time (may not match the loader).");
            prefixedOwners = [];
        }

        // Source: an override (the install lane's resolved {x:Reference} anchor), a nested {x:Static}/
        // same-dict {StaticResource} resolved eagerly (the loader's ResolveNestedExtension), the bare string
        // (mirrors the handler), or — the previously-SILENT shape — an unlowerable nested extension, fenced:
        // reading its Text as null used to drop the Source and silently rebind against DataContext.
        string sourceInit;
        if (sourceOverrideExpr is not null)
            sourceInit = $"Source = {sourceOverrideExpr}";
        else if (node.FindNamed("Source") is { IsNested: true } nestedSource)
        {
            if (NestedSourceExpr(c, nestedSource.Nested!) is not { } sourceExpr)
            {
                c.Todo($"{{Binding}} Source {diagName} is a nested {{{nestedSource.Nested!.Name}}} not lowerable in this position");
                return null;
            }
            sourceInit = $"Source = {sourceExpr}";
        }
        else
            sourceInit = StringInit("Source", NamedText(node, "Source"));

        string path = Escape(rawPath);
        var inits = new List<string>(ModeInit(modeName))
        {
            relSource,
            converterInit,
            StringInit("ElementName", NamedText(node, "ElementName")),
            sourceInit,
            StringInit("StringFormat", NamedText(node, "StringFormat")),
            StringInit("FallbackValue", NamedText(node, "FallbackValue")),
            StringInit("TargetNullValue", NamedText(node, "TargetNullValue")),
            PathTypeResolverInit(prefixedOwners),                  // #153 — baked owners for prefixed type-qualified paths
        };

        return $"new global::Cursorial.UI.Data.Binding(\"{path}\"){Initializers(inits)}";
    }

    // A nested Source={x:Static}/{StaticResource} value, resolved eagerly like the loader's
    // ResolveNestedExtension: the static member reference, or a same-dictionary entry's var. {x:Reference}
    // returns null here — the INSTALL lane defers the whole Install for it; in a descriptor position
    // (DataCondition.Binding) it stays fenced. Other extensions: null (fenced by the caller).
    private static string? NestedSourceExpr(Context c, MarkupExtensionNode nested)
    {
        if (nested.Name is "x:Static" or "Static" && FirstPositionalText(nested) is { Length: > 0 } staticPath)
            return ResolveStaticPath(c, staticPath);

        if (nested.Name is "StaticResource" && FirstPositionalText(nested) is { Length: > 0 } key &&
            ResolveVisibleResourceVar(c, $"\"{Escape(key)}\"", out _) is { } srcVar)
            return srcVar;

        // A CUSTOM extension as the Source — eager target-less ProvideValue, the runtime's
        // ResolveNestedExtension default arm. Built-ins that fell through above stay declined.
        if (nested.Name is not ("x:Null" or "Null" or "x:Static" or "Static" or "x:Type" or "Type"
                or "StaticResource" or "DynamicResource" or "Binding" or "TemplateBinding"
                or "x:Reference" or "Reference") &&
            CustomExtensionExpr(c, nested, targetObjectExpr: null, targetPropertyExpr: null) is { } customSource)
            return customSource;

        return null;
    }

    // {TemplateBinding SourceProp} (inside a template body) → a one-way TemplateBinding tracking the templated
    // parent's SourceProp. The source property is resolved against the template's target type (statically known
    // here via the ControlTemplate TargetType / enclosing control); the engine finds the live templated parent
    // at apply-time via the target's TemplatedParent (so the lowered emission needs no parent reference).
    private static void EmitTemplateBinding(Context c, string varExpr, XamlMember xm, MarkupExtensionNode node)
    {
        if (RegisteredOwner(xm) is not { } targetOwner)
        {
            c.Todo($"{{TemplateBinding}} target '{xm.Name}' is not a bindable UIProperty");
            return;
        }

        if (c.TemplatedParentType is not { } parentType)
        {
            c.Todo($"{{TemplateBinding}} for '{xm.Name}' has no statically-known template target type (DataTemplate / unresolved TargetType)");
            return;
        }

        // The source name: positional, or the named Property= (WPF parity — the loader accepts both, so the
        // element form <TemplateBinding Property="Header"/> lowers too).
        if ((FirstPositionalText(node) ?? NamedText(node, "Property")) is not { Length: > 0 } rawSourceName)
        {
            c.Todo($"{{TemplateBinding}} for '{xm.Name}' has no source property name");
            return;
        }

        // Mirrors the loader's ResolveTemplateBindingSource: optional WPF parens, a type-qualified
        // `Owner.Prop` / `ns:Owner.Prop` (an attached or other-type property) resolved through the document
        // xmlns, else the templated parent's type, the target part's type, and finally the target property
        // itself when the name matches (Background→Background).
        var sourceName = rawSourceName.Trim();
        // The authored spelling IS the diagnostic pathText — often already type-qualified (`Owner.Prop`),
        // sometimes WPF-parenthesized; preserve it verbatim rather than re-deriving a spelling.
        var pathText = sourceName;
        if (sourceName.Length > 1 && sourceName[0] == '(' && sourceName[sourceName.Length - 1] == ')')
            sourceName = sourceName.Substring(1, sourceName.Length - 2).Trim();

        INamedTypeSymbol? sourceOwner;
        int dot = sourceName.LastIndexOf('.');
        if (dot > 0 && dot < sourceName.Length - 1)
        {
            var ownerToken = sourceName.Substring(0, dot);
            sourceName = sourceName.Substring(dot + 1);
            if (XamlDataTypeScope.ResolveToken(c.Doc, ownerToken, c.Resolver) is not { } ownerType)
            {
                c.Todo($"{{TemplateBinding {rawSourceName}}} — owner type '{ownerToken}' could not be resolved");
                return;
            }
            sourceOwner = SymbolXamlModel.FindRegisteredPropertyOwner(ownerType, sourceName);
        }
        else
        {
            // Declared-TargetType resolution vs the loader's runtime templated-parent type: registration
            // walks the base chain, so the UIProperty identity matches in every normal case.
            sourceOwner = SymbolXamlModel.FindRegisteredPropertyOwner(parentType, sourceName)
                          ?? (c.CurrentObjectType is { } partType ? SymbolXamlModel.FindRegisteredPropertyOwner(partType, sourceName) : null)
                          ?? (sourceName == xm.Name ? targetOwner : null);
        }

        if (sourceOwner is null)
        {
            c.Todo($"{{TemplateBinding {rawSourceName}}} — '{sourceName}' is not a registered property on '{parentType.Name}'");
            return;
        }

        // Value-shaping properties, shared by all three lanes below — the divergence this closes: a
        // {TemplateBinding …, Converter=…, StringFormat=…, FallbackValue=…} carries the same shaping a
        // {Binding} does (the runtime TemplateBinding/BindingBase support them; the lowering dropped them).
        // A present-but-unlowerable Converter (a forward/fenced resource) fails CLOSED, exactly as {Binding}.
        var converterInit = ConverterInit(c, node);
        if (converterInit is null)
        {
            c.Todo($"{{TemplateBinding}} for '{xm.Name}' has a Converter that is not lowerable in this position (a forward/fenced resource)");
            return;
        }

        var shaping = new[]
        {
            converterInit,
            StringInit("StringFormat", NamedText(node, "StringFormat")),
            StringInit("FallbackValue", NamedText(node, "FallbackValue")),
            StringInit("TargetNullValue", NamedText(node, "TargetNullValue")),
        };
        // The compiled lanes are CompiledBindings anchored on the templated parent — they carry Mode/RelativeSource
        // plus the shaping; the descriptor lane (TemplateBinding) is inherently OneWay/TemplatedParent, shaping only.
        var compiledInits = Initializers(new List<string>
        {
            "Mode = global::Cursorial.UI.Data.BindingMode.OneWay",
            "RelativeSource = global::Cursorial.UI.Data.RelativeSource.TemplatedParent",
        }.Concat(shaping));

        // The compiled TemplatedParent form (WS-PP3): the runtime TemplateBinding descriptor rides the
        // REFLECTION lane over its anchor — with the parent type and the registration statically known,
        // the same one-way reach lowers as a compiled GetValue chain: property-system-pure, AOT-clean,
        // and the carried field observes without a registry probe. A DirectProperty is EXCLUDED here — it
        // has no typed GetValue overload (the untyped one returns object?, which can't type the getter), so
        // it falls through to the CLR-wrapper lane below (or the runtime descriptor). This exclusion was
        // implicit while the value-type helper returned null for DirectProperty; it now handles both, so
        // the guard is explicit (a TemplateBinding DirectProperty source otherwise emitted non-compiling code).
        if (XamlPathParser.FindRegisteredPropertyField(sourceOwner, sourceName) is { } sourceField &&
            !XamlPathParser.IsDirectUIPropertyType(sourceField.Type) &&
            XamlPathParser.UIPropertyRegistrationValueType(sourceField) is { } sourceValueType)
        {
            var fieldRef = $"{Global(sourceField.ContainingType, false)}.{sourceField.Name}";
            c.Line(
                $"global::Cursorial.UI.Data.BindingOperations.Install({varExpr}, {Global(targetOwner)}.{xm.Name}Property, " +
                $"new global::Cursorial.UI.Data.CompiledBinding<{Global(parentType)}, {Global(sourceValueType)}>(" +
                $"static __s => __s.GetValue({fieldRef}), null, " +
                $"new global::Cursorial.UI.Data.CompiledPathStep[] {{ new global::Cursorial.UI.Data.CompiledPathStep(\"{Escape(sourceName)}\") {{ UIProperty = {fieldRef} }} }}, " +
                $"\"{Escape(pathText)}\"){compiledInits});");
            return;
        }

        // A DirectProperty source: its CLR wrapper IS the implementation (the standing exemption from
        // the always-GetValue rule), so the compiled form reads the wrapper — the carried field still
        // observes through the property system. Taken only when the parent IS the owner (or derives
        // from it), so the typed member access needs no cast; anything else keeps the runtime descriptor.
        if (XamlPathParser.FindRegisteredPropertyField(sourceOwner, sourceName) is { } directField &&
            IsAssignableTo(parentType, sourceOwner) &&
            XamlDataTypeScope.FindMember(sourceOwner, sourceName) is { IsStatic: false } directMember &&
            XamlDataTypeScope.IsReadable(directMember) &&
            XamlDataTypeScope.MemberType(directMember) is { } directValueType)
        {
            var directFieldRef = $"{Global(directField.ContainingType, false)}.{directField.Name}";
            c.Line(
                $"global::Cursorial.UI.Data.BindingOperations.Install({varExpr}, {Global(targetOwner)}.{xm.Name}Property, " +
                $"new global::Cursorial.UI.Data.CompiledBinding<{Global(parentType)}, {Global(directValueType)}>(" +
                $"static __s => __s.{EscapeId(sourceName)}, null, " +
                $"new global::Cursorial.UI.Data.CompiledPathStep[] {{ new global::Cursorial.UI.Data.CompiledPathStep(\"{Escape(sourceName)}\") {{ UIProperty = {directFieldRef} }} }}, " +
                $"\"{Escape(pathText)}\"){compiledInits});");
            return;
        }

        c.Line(
            $"global::Cursorial.UI.Data.BindingOperations.Install({varExpr}, {Global(targetOwner)}.{xm.Name}Property, " +
            $"new global::Cursorial.UI.Data.TemplateBinding({Global(sourceOwner)}.{sourceName}Property){Initializers(shaping)});");
    }

    // The binding path: the first positional argument, else the Path= named argument (mirrors the runtime handler).
    private static string? BindingPathOf(MarkupExtensionNode node)
        => node.PositionalArguments.Count > 0 && node.PositionalArguments[0].Text is { } p ? p : NamedText(node, "Path");

    // Collects every distinct namespace-PREFIXED type-qualified owner token `(prefix:Type.Member)` in a binding path,
    // resolved to its owner symbol against the document xmlns (#153). The emitted `new Binding("...")` carries no
    // resolver, so its reflective `DefaultPathTypeResolver` (registry simple-name only) can't bind a prefix — nor a
    // plain non-UIProperty owner qualified for clarity. So the caller bakes these owners into a LookupPathTypeResolver
    // (typeof(...) per token), resolving them exactly as the loader's xmlns resolver does — registered UIProperty
    // owners AND plain CLR-property owners alike, ambiguity-proof. Unprefixed `(Type.Member)` segments already resolve
    // by registry simple-name at runtime and are NOT collected (the resolver's default fallback handles them).
    //
    // Indexer contents are skipped: a quoted key `['a(ui:X.Y)']` may contain '(', ':', '.' that are NOT a segment
    // (mirror BindingPath.ParseIndexer — a quoted key runs to its closing quote, then ']' closes the indexer). The
    // FIRST '.' inside a group splits Type from Member (matches BindingPath.ParseTypeQualified). Returns:
    //   • a (possibly empty) list of (token, owner) — empty ⇒ no prefixed owners, emit the plain binding;
    //   • null ⇒ a prefix could NOT be resolved at build (unbound prefix / unknown type) — the caller keeps the raw
    //     path (which fails at bind time exactly as the loader's unbound-prefix parse would) and records an info.
    private static List<(string Token, INamedTypeSymbol Owner)>? CollectPrefixedPathOwners(Context c, string path)
    {
        var owners = new List<(string, INamedTypeSymbol)>();
        if (path.IndexOf('(') < 0)
            return owners; // no type-qualified segment

        int i = 0;
        while (i < path.Length)
        {
            char ch = path[i];

            if (ch == '[')
            {
                int j = i + 1;
                if (j < path.Length && path[j] == '\'')
                {
                    j++;
                    while (j < path.Length && path[j] != '\'')
                        j++;
                    if (j < path.Length)
                        j++; // consume the closing quote
                }
                while (j < path.Length && path[j] != ']')
                    j++;
                i = j < path.Length ? j + 1 : j; // consume the closing ']'
                continue;
            }

            if (ch != '(')
            {
                i++;
                continue;
            }

            int close = path.IndexOf(')', i);
            if (close < 0)
                break; // unterminated group — the runtime parser reports it; nothing to collect

            string body = path.Substring(i + 1, close - i - 1); // `Type.Member` (Type may be `prefix:Local`)
            int dot = body.IndexOf('.');
            string typeToken = dot < 0 ? body : body.Substring(0, dot);
            if (dot >= 0 && typeToken.IndexOf(':') >= 0)
            {
                if (XamlDataTypeScope.ResolveToken(c.Doc, typeToken, c.Resolver) is not { } owner)
                    return null; // unresolvable prefix — caller keeps the raw path + records an info

                if (!owners.Exists(o => string.Equals(o.Item1, typeToken, System.StringComparison.Ordinal)))
                    owners.Add((typeToken, owner));
            }

            i = close + 1;
        }

        return owners;
    }

    // The `TypeResolver = new LookupPathTypeResolver(("token", typeof(Owner)), ...)` initializer baking a binding
    // path's namespace-prefixed type-qualified owners (#153); "" when there are none (dropped by Initializers).
    private static string PathTypeResolverInit(List<(string Token, INamedTypeSymbol Owner)> owners)
    {
        if (owners.Count == 0)
            return string.Empty;

        var pairs = string.Join(", ", owners.Select(o => $"(\"{Escape(o.Token)}\", typeof({Global(o.Owner, false)}))"));
        return $"TypeResolver = new global::Cursorial.UI.Data.LookupPathTypeResolver({pairs})";
    }

