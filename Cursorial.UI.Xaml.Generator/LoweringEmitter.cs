    /// <summary>
    /// Resolves a relative <c>ResourceDictionary.Source</c> against the document's own source URI at
    /// COMPILE time (the runtime loader does the same for parsed documents) — a lowered document has no
    /// runtime parse, so the resolution must be baked in. Absolute references pass through untouched.
    /// </summary>
    private static string ResolveSourceUri(string raw, string? documentUri)
    {
        if (raw.Length == 0 || documentUri is null)
            return raw;
        if (Uri.TryCreate(raw, UriKind.Absolute, out _))
            return raw;
        if (!Uri.TryCreate(documentUri, UriKind.Absolute, out var baseUri) || !Uri.TryCreate(baseUri, raw, out var resolved))
            return raw;

        // System.Uri lowercases the authority; ours names an ASSEMBLY (case-sensitive to load on
        // Linux). Re-apply the document URI's original authority casing to the composed result.
        var schemeEnd = documentUri.IndexOf("://", StringComparison.Ordinal);
        if (schemeEnd >= 0)
        {
            var start = schemeEnd + 3;
            var end = documentUri.IndexOf('/', start);
            var authority = end < 0 ? documentUri.Substring(start) : documentUri.Substring(start, end - start);
            if (authority.Length > 0)
                return $"{resolved.Scheme}://{authority}{resolved.AbsolutePath}";
        }

        return resolved.ToString();
    }

